export function isTransactionCategoryIcon(value: unknown): value is TransactionCategoryIconName {
  return typeof value === "string" && value in TRANSACTION_CATEGORY_ICONS;
}

export function getTransactionCategoryIcon(value?: string | null): LucideIcon {
  return isTransactionCategoryIcon(value) ? TRANSACTION_CATEGORY_ICONS[value] : CircleSlash;
}

export function TransactionCategoryIcon({ name, ...props }: LucideProps & { name?: string | null }) {
  return createElement(getTransactionCategoryIcon(name), props);
}
