ALTER TABLE public.config_geral
  ADD COLUMN IF NOT EXISTS permitir_produto_avulso_os boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.osproduto_avulso (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordemservicoid integer NOT NULL REFERENCES public.ordemservico(id) ON DELETE CASCADE,
  titulo text NOT NULL,
  quantidade integer NOT NULL CHECK (quantidade > 0),
  precounitario numeric NOT NULL CHECK (precounitario >= 0),
  subtotal numeric NOT NULL CHECK (subtotal >= 0),
  desconto_tipo public.enum_tipo_desconto_venda,
  desconto numeric NOT NULL DEFAULT 0 CHECK (desconto >= 0),
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS osproduto_avulso_ordem_idx
  ON public.osproduto_avulso(ordemservicoid, id);

ALTER TABLE public.osproduto_avulso ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.osproduto_avulso NO FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.osproduto_avulso FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.osproduto_avulso TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.osproduto_avulso_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.vincular_produto_avulso_os(
  p_ordem_id integer,
  p_avulso_id bigint,
  p_produto_id integer
) RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_item public.osproduto_avulso%ROWTYPE;
  v_estoque numeric;
  v_modo text := 'ORCAMENTO';
BEGIN
  SELECT * INTO v_item
  FROM public.osproduto_avulso
  WHERE id = p_avulso_id AND ordemservicoid = p_ordem_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Produto avulso não encontrado.' USING ERRCODE = 'P0002';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.osproduto
    WHERE ordemservicoid = p_ordem_id AND produtoid = p_produto_id
  ) THEN
    RAISE EXCEPTION 'O produto selecionado já está neste orçamento.' USING ERRCODE = '23505';
  END IF;

  SELECT estoque INTO v_estoque
  FROM public.produto
  WHERE id = p_produto_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Produto não encontrado.' USING ERRCODE = 'P0002';
  END IF;

  SELECT COALESCE(modo_baixa_estoque_os::text, 'ORCAMENTO') INTO v_modo
  FROM public.config_geral ORDER BY id DESC LIMIT 1;

  IF v_modo = 'ORCAMENTO' AND v_estoque < v_item.quantidade THEN
    RAISE EXCEPTION 'Estoque insuficiente. Disponível: %, solicitado: %.', v_estoque, v_item.quantidade
      USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO public.osproduto (
    ordemservicoid, produtoid, quantidade, precounitario, subtotal,
    desconto_tipo, desconto
  ) VALUES (
    p_ordem_id, p_produto_id, v_item.quantidade, v_item.precounitario,
    v_item.subtotal, v_item.desconto_tipo, v_item.desconto
  );

  IF v_modo = 'ORCAMENTO' THEN
    UPDATE public.produto
    SET estoque = estoque - v_item.quantidade
    WHERE id = p_produto_id;

    INSERT INTO public.osproduto_baixa (ordemservicoid, produtoid, quantidade)
    VALUES (p_ordem_id, p_produto_id, v_item.quantidade)
    ON CONFLICT (ordemservicoid, produtoid)
    DO UPDATE SET quantidade = EXCLUDED.quantidade;
  END IF;

  DELETE FROM public.osproduto_avulso WHERE id = v_item.id;
END;
$$;

REVOKE ALL ON FUNCTION public.vincular_produto_avulso_os(integer, bigint, integer)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.vincular_produto_avulso_os(integer, bigint, integer)
  TO service_role;
