-- Numeração de NF-e definida na transmissão, e não no rascunho.
--
-- Até aqui `nfe_alocar_numero` era chamada ao criar o rascunho: todo rascunho
-- consumia um número de `nfe_config.ultimo_numero`. Rascunho excluído, ou nota
-- rejeitada seguida de uma nova emissão, deixavam buracos permanentes na
-- sequência — e furo de numeração só se resolve com pedido de inutilização.
--
-- Regra nova, valendo para os dois motores (emissão a partir de OS/Venda e
-- emissão avulsa): o rascunho carrega apenas um número provisório
-- (numero_definitivo = false), usado para montar a prévia do XML e do DANFE. O
-- número real é alocado no envio para a SEFAZ e só é consumido de fato quando a
-- nota existe lá — autorizada, denegada ou aguardando retorno de lote. Rejeição
-- e exclusão devolvem o número para a fila de reaproveitamento.
BEGIN;

ALTER TABLE public.nfe
  ADD COLUMN IF NOT EXISTS numero_definitivo boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.nfe.numero_definitivo IS
  'true quando o numero/serie ja foram alocados para transmissao. Rascunho e nota rejeitada ficam false: o numero exibido e provisorio.';

-- Nota que chegou à SEFAZ segura o número para sempre. ASSINADA, ENVIADA e
-- PENDENTE_ENVIO entram junto por precaução: não sabemos o desfecho, e número
-- reaproveitado indevidamente vira rejeição 539 (duplicidade).
UPDATE public.nfe
   SET numero_definitivo = true
 WHERE status IN ('AUTORIZADA', 'DENEGADA', 'CANCELADA', 'ENVIADA', 'ASSINADA', 'PENDENTE_ENVIO');

-- Fila de números liberados: alimentada por rejeição/exclusão e consumida antes
-- de incrementar `ultimo_numero`, para a sequência se fechar sozinha.
CREATE TABLE IF NOT EXISTS public.nfe_numero_liberado (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  config_id bigint NOT NULL REFERENCES public.nfe_config(id) ON DELETE CASCADE,
  serie integer NOT NULL,
  numero integer NOT NULL CHECK (numero > 0),
  motivo text,
  createdat timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT nfe_numero_liberado_unico UNIQUE (config_id, serie, numero)
);

ALTER TABLE public.nfe_numero_liberado ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.nfe_numero_liberado IS
  'Numeros de NF-e que foram reservados mas nunca chegaram a existir na SEFAZ. Sao reaproveitados na proxima transmissao antes de avancar ultimo_numero.';

-- Recupera o que a regra antiga já queimou: todo número até `ultimo_numero` que
-- não está preso a uma nota transmitida volta para a fila. Inclui os buracos de
-- rascunhos já excluídos e os números que rascunhos/rejeitadas ainda exibem —
-- esses passaram a ser provisórios com a coluna acima.
INSERT INTO public.nfe_numero_liberado (config_id, serie, numero, motivo)
SELECT c.id, c.serie, g.n, 'BACKFILL_REGRA_NUMERACAO'
  FROM public.nfe_config c
  CROSS JOIN LATERAL generate_series(1, c.ultimo_numero) AS g(n)
 WHERE NOT EXISTS (
   SELECT 1
     FROM public.nfe x
    WHERE x.empresaid = c.empresaid
      AND x.serie = c.serie
      AND x.numero = g.n
      AND x.numero_definitivo
 )
ON CONFLICT ON CONSTRAINT nfe_numero_liberado_unico DO NOTHING;

-- Aloca o próximo número: primeiro o menor liberado, depois a sequência.
CREATE OR REPLACE FUNCTION public.nfe_alocar_numero(p_config_id bigint)
RETURNS TABLE (
  numero integer,
  serie integer,
  empresaid bigint,
  modelo public.enum_modelo_nfe,
  ambiente public.enum_ambiente_nfe
)
LANGUAGE plpgsql
AS $$
DECLARE
  v_config public.nfe_config%ROWTYPE;
  v_reaproveitado integer;
BEGIN
  SELECT *
    INTO v_config
    FROM public.nfe_config
   WHERE id = p_config_id
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Configuração de NF-e % não encontrada.', p_config_id;
  END IF;

  -- O lock na config acima serializa as alocações concorrentes.
  DELETE FROM public.nfe_numero_liberado l
   WHERE l.id = (
     SELECT id
       FROM public.nfe_numero_liberado
      WHERE config_id = p_config_id
        AND serie = v_config.serie
      ORDER BY numero
      LIMIT 1
   )
  RETURNING l.numero INTO v_reaproveitado;

  IF v_reaproveitado IS NOT NULL THEN
    numero := v_reaproveitado;
    serie := v_config.serie;
    empresaid := v_config.empresaid;
    modelo := v_config.modelo;
    ambiente := v_config.ambiente;
    RETURN NEXT;
    RETURN;
  END IF;

  UPDATE public.nfe_config
     SET ultimo_numero = COALESCE(ultimo_numero, 0) + 1,
         updatedat = now()
   WHERE id = p_config_id
   RETURNING ultimo_numero, nfe_config.serie, nfe_config.empresaid, nfe_config.modelo, nfe_config.ambiente
    INTO numero, serie, empresaid, modelo, ambiente;

  RETURN NEXT;
END;
$$;

-- Devolve para a fila o número de uma nota que não chegou à SEFAZ.
-- Chamada na rejeição e antes de excluir rascunho/rejeitada.
CREATE OR REPLACE FUNCTION public.nfe_liberar_numero(p_nfe_id bigint, p_motivo text DEFAULT NULL)
RETURNS boolean
LANGUAGE plpgsql
AS $$
DECLARE
  v_nfe public.nfe%ROWTYPE;
  v_config public.nfe_config%ROWTYPE;
BEGIN
  SELECT * INTO v_nfe FROM public.nfe WHERE id = p_nfe_id FOR UPDATE;
  IF NOT FOUND OR NOT v_nfe.numero_definitivo OR v_nfe.numero IS NULL THEN
    RETURN false;
  END IF;

  -- Só volta o número de nota que a SEFAZ nunca registrou.
  IF v_nfe.status IN ('AUTORIZADA', 'DENEGADA', 'CANCELADA', 'ENVIADA', 'ASSINADA', 'PENDENTE_ENVIO') THEN
    RETURN false;
  END IF;

  SELECT * INTO v_config
    FROM public.nfe_config
   WHERE empresaid = v_nfe.empresaid
   ORDER BY id
   LIMIT 1
   FOR UPDATE;

  IF NOT FOUND THEN
    RETURN false;
  END IF;

  UPDATE public.nfe
     SET numero_definitivo = false,
         updatedat = now()
   WHERE id = p_nfe_id;

  INSERT INTO public.nfe_numero_liberado (config_id, serie, numero, motivo)
  VALUES (v_config.id, v_nfe.serie, v_nfe.numero, p_motivo)
  ON CONFLICT ON CONSTRAINT nfe_numero_liberado_unico DO NOTHING;

  RETURN true;
END;
$$;

COMMIT;
