-- Modulo de orcamentos avulsos.
--
-- Orcamento e um documento comercial proprio, independente de ordemservico: pode
-- existir sem cliente, sem veiculo e sem setor, e nunca movimenta estoque nem
-- financeiro. So quando vira OS o material passa a existir para o estoque — e
-- ainda assim quem decide a baixa e a flag config_geral.modo_baixa_estoque_os,
-- exatamente como numa OS aberta a mao.
--
-- O vinculo mora em ordemservico.orcamentoid (e nao no orcamento) para permitir
-- que um orcamento grande gere mais de uma OS sem migration futura, e para que
-- "esta OS veio do orcamento X" seja consultavel do lado que os relatorios
-- perguntam.

create table if not exists public.orcamento (
  id bigint generated by default as identity primary key,
  clienteid integer references public.cliente(id) on delete set null,
  veiculoid integer references public.veiculo(id) on delete set null,
  usuariocriadorid uuid references public.usuario(id),

  -- Apenas dois estados, espelhando os badges da listagem: em aberto ou ja
  -- convertido em OS. Orcamento recusado se resolve por descarte (is_deleted).
  status text not null default 'ABERTO'
    check (status in ('ABERTO', 'CONVERTIDO')),

  descricao text,
  observacoes text,

  subtotal numeric not null default 0 check (subtotal >= 0),
  desconto_tipo public.enum_tipo_desconto_venda,
  desconto numeric not null default 0 check (desconto >= 0),
  valor_frete numeric not null default 0 check (valor_frete >= 0),
  total numeric not null default 0 check (total >= 0),

  is_deleted boolean not null default false,
  deleted_at timestamptz,
  deleted_by uuid,
  created_by uuid,
  updated_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- A listagem sempre filtra por situacao e esconde descartados; o indice parcial
-- cobre as duas abas sem carregar as linhas descartadas.
create index if not exists orcamento_status_idx
  on public.orcamento (status, id desc)
  where is_deleted = false;

create index if not exists orcamento_cliente_idx
  on public.orcamento (clienteid, id desc)
  where is_deleted = false;

create table if not exists public.orcamento_produto (
  orcamentoid bigint not null references public.orcamento(id) on delete cascade,
  produtoid integer not null references public.produto(id),
  quantidade numeric not null check (quantidade > 0),
  -- Preco congelado no momento da cotacao: o orcamento e uma promessa ao
  -- cliente, entao mudanca posterior na tabela de precos nao o reescreve.
  precounitario numeric not null check (precounitario >= 0),
  desconto_tipo public.enum_tipo_desconto_venda,
  desconto numeric not null default 0 check (desconto >= 0),
  subtotal numeric not null default 0 check (subtotal >= 0),
  primary key (orcamentoid, produtoid)
);

create table if not exists public.orcamento_servico (
  orcamentoid bigint not null references public.orcamento(id) on delete cascade,
  servicoid integer not null references public.servico(id),
  descricao text,
  quantidade numeric not null check (quantidade > 0),
  precounitario numeric not null check (precounitario >= 0),
  desconto_tipo public.enum_tipo_desconto_venda,
  desconto numeric not null default 0 check (desconto >= 0),
  subtotal numeric not null default 0 check (subtotal >= 0),
  primary key (orcamentoid, servicoid)
);

-- Espelha osproduto_avulso: cotar item que a oficina nao tem cadastrado e
-- justamente o que se faz num orcamento, entao aqui nao ha flag que habilite.
create table if not exists public.orcamento_produto_avulso (
  id bigint generated by default as identity primary key,
  orcamentoid bigint not null references public.orcamento(id) on delete cascade,
  titulo text not null,
  quantidade integer not null check (quantidade > 0),
  precounitario numeric not null check (precounitario >= 0),
  desconto_tipo public.enum_tipo_desconto_venda,
  desconto numeric not null default 0 check (desconto >= 0),
  subtotal numeric not null default 0 check (subtotal >= 0)
);

create index if not exists orcamento_produto_avulso_orcamento_idx
  on public.orcamento_produto_avulso (orcamentoid, id);

alter table public.ordemservico
  add column if not exists orcamentoid bigint references public.orcamento(id) on delete set null;

create index if not exists ordemservico_orcamento_idx
  on public.ordemservico (orcamentoid)
  where orcamentoid is not null;

comment on column public.ordemservico.orcamentoid is
  'Orcamento avulso que originou esta OS, quando houver.';

