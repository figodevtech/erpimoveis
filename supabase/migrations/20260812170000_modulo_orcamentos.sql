-- Permissoes do modulo, no molde de 20260805130000_ordens_finalizar_sem_cobranca.
insert into public.permissao (nome, descricao)
values
  ('orcamentos:visualizar', 'Visualizar orcamentos avulsos'),
  ('orcamentos:criar', 'Criar orcamentos avulsos'),
  ('orcamentos:editar', 'Editar orcamentos avulsos e gerar OS a partir deles'),
  ('orcamentos:excluir', 'Descartar orcamentos avulsos')
on conflict (nome) do update
set descricao = excluded.descricao;

-- Backfill: quem ja mexe em ordens passa a mexer em orcamentos, para o modulo
-- nascer utilizavel sem exigir revisao manual de todos os perfis.
insert into public.perfilpermissao (perfilid, permissaoid)
select distinct pp.perfilid, nova.id
from public.perfilpermissao pp
join public.permissao base on base.id = pp.permissaoid and base.nome = 'ordens:visualizar'
join public.permissao nova on nova.nome = 'orcamentos:visualizar'
on conflict do nothing;

