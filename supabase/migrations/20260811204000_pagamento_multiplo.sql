-- Pagamento múltiplo: um recebimento que quita várias OS ou várias vendas.
--
-- PROBLEMA
-- Para receber um PIX que cobre três OS, o operador abria três diálogos e digitava
-- banco, método e data três vezes — e não sobrava registro de que aquilo foi UM
-- pagamento. Sem essa identidade não há como conferir contra o extrato nem desfazer
-- a operação como unidade.
--
-- MODELO
-- `transacao.ordemservicoid` e `transacao.vendaid` são FKs escalares: uma linha não
-- pertence a duas OS. Então o pagamento vira N transações irmãs (N × P no parcelado)
-- amarradas por `pagamento_multiplo_id`.
--
-- NÃO HÁ TRANSAÇÃO "PAI", diferente do adiantamento (20260806200000). Lá o pai é o
-- dinheiro da antecipadora e os filhos são títulos preexistentes sendo convertidos,
-- com `banco_id = NULL` justamente para o banco não contar duas vezes. Aqui os filhos
-- SÃO o dinheiro: no modo à vista cada um carrega o banco e a soma é exatamente o
-- valor recebido. Um pai duplicaria a entrada no fluxo de caixa.
BEGIN;

CREATE TABLE IF NOT EXISTS public.pagamento_multiplo (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descricao text NOT NULL,
  modo text NOT NULL,
  tipo_documento text NOT NULL,
  valor_total numeric(14,2) NOT NULL,
  data timestamptz NOT NULL DEFAULT now(),
  banco_id bigint REFERENCES public.bancoconta(id),
  metodopagamento public.metodo_pagamento,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pagamento_multiplo_modo_check CHECK (modo IN ('AVISTA', 'PARCELADO')),
  CONSTRAINT pagamento_multiplo_tipo_check CHECK (tipo_documento IN ('OS', 'VENDA')),
  CONSTRAINT pagamento_multiplo_valor_check CHECK (valor_total > 0),
  -- À vista o dinheiro já entrou e tem que ter entrado em algum lugar. Parcelado
  -- ainda não entrou, e exigir banco aqui obrigaria a chutar a conta.
  CONSTRAINT pagamento_multiplo_banco_check CHECK (modo <> 'AVISTA' OR banco_id IS NOT NULL)
);

ALTER TABLE public.pagamento_multiplo OWNER TO postgres;

COMMENT ON TABLE public.pagamento_multiplo IS
  'Um pagamento único rateado entre vários documentos. As linhas são as transações com este pagamento_multiplo_id.';

ALTER TABLE public.transacao
  ADD COLUMN IF NOT EXISTS pagamento_multiplo_id bigint
    REFERENCES public.pagamento_multiplo(id) ON DELETE RESTRICT;

COMMENT ON COLUMN public.transacao.pagamento_multiplo_id IS
  'Grupo do pagamento múltiplo a que esta linha pertence. Nulo em lançamento avulso.';

CREATE INDEX IF NOT EXISTS idx_transacao_pagamento_multiplo
  ON public.transacao (pagamento_multiplo_id)
  WHERE pagamento_multiplo_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Revalidação de status da venda.
--
-- A OS já tem `recalcular_status_financeiro_os`. A venda não tinha função própria:
-- a mesma regra vive inline dentro de `baixar_transacao_pendente`. Esta função
-- reproduz essa regra SEM alterá-la — inclusive o fato de que, na venda, só título
-- já baixado (`pendente = false`) quita, ao contrário da OS, que conta o pendente
-- como comprometido. Quando `baixar_transacao_pendente` for tocada de novo, ela
-- deveria passar a chamar esta função para não haver duas verdades.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.recalcular_status_financeiro_venda(p_venda_id integer)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_total_devido numeric(14,2);
  v_total_pago numeric(14,2);
  v_status text;
BEGIN
  SELECT v.status::text,
         round(
           greatest(coalesce(v.valortotal, 0), 0) +
           CASE
             WHEN v.acrescimo_financeiro_tipo = 'PORCENTAGEM' THEN
               greatest(coalesce(v.valortotal, 0), 0) *
               least(greatest(coalesce(v.acrescimo_financeiro_valor, 0), 0), 100) / 100
             WHEN v.acrescimo_financeiro_tipo = 'FIXO' THEN
               greatest(coalesce(v.acrescimo_financeiro_valor, 0), 0)
             ELSE 0
           END,
           2
         )
    INTO v_status, v_total_devido
  FROM public.venda v
  WHERE v.id = p_venda_id;

  IF NOT FOUND THEN RETURN; END IF;

  -- Venda cancelada não volta ao fluxo por causa de pagamento.
  IF v_status = 'CANCELADA' THEN RETURN; END IF;

  SELECT coalesce(round(sum(t.valor - coalesce(t.valor_acrescimos, 0)), 2), 0)
    INTO v_total_pago
  FROM public.transacao t
  WHERE t.vendaid = p_venda_id
    AND upper(t.tipo::text) = 'RECEITA'
    AND t.pendente = false
    AND t.is_deleted = false;

  UPDATE public.venda
  SET status = (CASE WHEN v_total_devido > 0 AND v_total_pago >= v_total_devido
                     THEN 'FINALIZADA' ELSE 'PAGAMENTO' END)::public.enum_status_venda,
      updatedat = now()
  WHERE id = p_venda_id
    AND status::text IS DISTINCT FROM (
      CASE WHEN v_total_devido > 0 AND v_total_pago >= v_total_devido
           THEN 'FINALIZADA' ELSE 'PAGAMENTO' END
    );
END;
$function$;

ALTER FUNCTION public.recalcular_status_financeiro_venda(integer) OWNER TO postgres;

-- ---------------------------------------------------------------------------
-- Registro. Tudo ou nada: ou o grupo inteiro entra, ou nada entra. Diferente da
-- baixa em lote (que é uma sequência de baixas independentes), aqui as linhas são
-- partes de um mesmo valor — meia gravação deixaria o rateio sem fechar.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.registrar_pagamento_multiplo(p_payload jsonb)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_tipo_documento text := upper(coalesce(p_payload->>'tipo_documento', ''));
  v_modo text := upper(coalesce(p_payload->>'modo', ''));
  v_valor_total numeric(14,2) := round(coalesce((p_payload->>'valor_total')::numeric, 0), 2);
  v_data timestamptz := coalesce(nullif(p_payload->>'data', '')::timestamptz, now());
  v_banco_id bigint := nullif(p_payload->>'banco_id', '')::bigint;
  v_metodo public.metodo_pagamento := nullif(p_payload->>'metodopagamento', '')::public.metodo_pagamento;
  v_created_by uuid := nullif(p_payload->>'created_by', '')::uuid;
  v_categoria text := coalesce(nullif(p_payload->>'categoria', ''), 'NÃO RELACIONADO');
  v_categoria_id integer := nullif(p_payload->>'categoria_id', '')::integer;
  v_plano_id integer := nullif(p_payload->>'plano_de_conta_id', '')::integer;
  v_centro_id integer := nullif(p_payload->>'centro_custo_id', '')::integer;
  v_pendente boolean := (v_modo = 'PARCELADO');
  v_grupo_id bigint;
  v_linha jsonb;
  v_soma numeric(14,2);
  v_doc_id integer;
  v_documentos integer[] := ARRAY[]::integer[];
  v_nome text;
  v_cpfcnpj text;
  v_cliente_id integer;
  v_descricao text;
BEGIN
  IF v_tipo_documento NOT IN ('OS', 'VENDA') THEN
    RAISE EXCEPTION 'tipo_documento deve ser OS ou VENDA.' USING ERRCODE = 'P0001';
  END IF;
  IF v_modo NOT IN ('AVISTA', 'PARCELADO') THEN
    RAISE EXCEPTION 'modo deve ser AVISTA ou PARCELADO.' USING ERRCODE = 'P0001';
  END IF;
  IF v_valor_total <= 0 THEN
    RAISE EXCEPTION 'O valor do pagamento deve ser maior que zero.' USING ERRCODE = 'P0001';
  END IF;
  IF jsonb_typeof(p_payload->'linhas') <> 'array'
     OR jsonb_array_length(p_payload->'linhas') = 0 THEN
    RAISE EXCEPTION 'Informe as linhas do rateio.' USING ERRCODE = 'P0001';
  END IF;

  -- A soma do rateio precisa fechar com o valor recebido. Sem esta guarda o grupo
  -- diria ter recebido um valor enquanto os documentos abateriam outro.
  SELECT round(coalesce(sum((item->>'valor')::numeric), 0), 2) INTO v_soma
    FROM jsonb_array_elements(p_payload->'linhas') AS item;

  IF v_soma <> v_valor_total THEN
    RAISE EXCEPTION 'A soma do rateio (%) difere do valor do pagamento (%).',
      v_soma, v_valor_total USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO public.pagamento_multiplo (
    descricao, modo, tipo_documento, valor_total, data, banco_id, metodopagamento, created_by
  ) VALUES (
    coalesce(nullif(btrim(p_payload->>'descricao'), ''),
             'Pagamento múltiplo de ' || jsonb_array_length(p_payload->'linhas') || ' lançamento(s)'),
    v_modo, v_tipo_documento, v_valor_total, v_data, v_banco_id, v_metodo, v_created_by
  ) RETURNING id INTO v_grupo_id;

  FOR v_linha IN SELECT value FROM jsonb_array_elements(p_payload->'linhas') LOOP
    v_doc_id := (v_linha->>'documento_id')::integer;

    IF v_doc_id IS NULL THEN
      RAISE EXCEPTION 'Linha do rateio sem documento.' USING ERRCODE = 'P0001';
    END IF;
    IF round((v_linha->>'valor')::numeric, 2) <= 0 THEN
      RAISE EXCEPTION 'Linha do rateio com valor não positivo no documento #%.', v_doc_id
        USING ERRCODE = 'P0001';
    END IF;

    -- `nomepagador` e `cpfcnpjpagador` são NOT NULL: vêm do cliente do documento.
    IF v_tipo_documento = 'OS' THEN
      SELECT o.clienteid INTO v_cliente_id
        FROM public.ordemservico o
       WHERE o.id = v_doc_id AND coalesce(o.is_deleted, false) = false;
      IF NOT FOUND THEN
        RAISE EXCEPTION 'Ordem de serviço #% não encontrada.', v_doc_id USING ERRCODE = 'P0002';
      END IF;
    ELSE
      SELECT v.clienteid INTO v_cliente_id
        FROM public.venda v
       WHERE v.id = v_doc_id;
      IF NOT FOUND THEN
        RAISE EXCEPTION 'Venda #% não encontrada.', v_doc_id USING ERRCODE = 'P0002';
      END IF;
    END IF;

    SELECT c.nomerazaosocial, c.cpfcnpj INTO v_nome, v_cpfcnpj
      FROM public.cliente c WHERE c.id = v_cliente_id;

    v_descricao := coalesce(
      nullif(btrim(v_linha->>'descricao'), ''),
      CASE WHEN v_tipo_documento = 'OS'
           THEN 'Pagamento da OS #' || v_doc_id
           ELSE 'Pagamento da Venda #' || v_doc_id END
    );

    IF coalesce((v_linha->>'total_parcelas')::integer, 1) > 1 THEN
      v_descricao := v_descricao || ' - Parcela '
        || (v_linha->>'parcela')::integer || '/' || (v_linha->>'total_parcelas')::integer;
    END IF;

    INSERT INTO public.transacao (
      descricao, valor, "valorLiquido", data, metodopagamento, categoria, categoria_id,
      plano_de_conta_id, centro_custo_id, tipo, cliente_id, banco_id,
      nomepagador, cpfcnpjpagador, pendente, pago_em,
      ordemservicoid, vendaid, pagamento_multiplo_id, created_by
    ) VALUES (
      v_descricao,
      round((v_linha->>'valor')::numeric, 2),
      round((v_linha->>'valor')::numeric, 2),
      -- Parcelado: `data` é o vencimento e `vencimento_em` fica para a baixa
      -- preencher, como em todo título pendente do sistema.
      coalesce(nullif(v_linha->>'vencimento_em', '')::timestamptz, v_data),
      v_metodo, v_categoria, v_categoria_id, v_plano_id, v_centro_id,
      'RECEITA'::public.tipos_transacao, v_cliente_id,
      CASE WHEN v_pendente THEN NULL ELSE v_banco_id END,
      coalesce(nullif(btrim(v_nome), ''), 'Cliente'),
      coalesce(nullif(btrim(v_cpfcnpj), ''), 'NÃO INFORMADO'),
      v_pendente,
      CASE WHEN v_pendente THEN NULL ELSE v_data END,
      CASE WHEN v_tipo_documento = 'OS' THEN v_doc_id ELSE NULL END,
      CASE WHEN v_tipo_documento = 'VENDA' THEN v_doc_id ELSE NULL END,
      v_grupo_id, v_created_by
    );

    IF NOT (v_doc_id = ANY (v_documentos)) THEN
      v_documentos := array_append(v_documentos, v_doc_id);
    END IF;
  END LOOP;

  -- Revalida cada documento uma única vez, depois de todas as linhas gravadas.
  FOREACH v_doc_id IN ARRAY v_documentos LOOP
    IF v_tipo_documento = 'OS' THEN
      PERFORM public.recalcular_status_financeiro_os(v_doc_id);
    ELSE
      PERFORM public.recalcular_status_financeiro_venda(v_doc_id);
    END IF;
  END LOOP;

  RETURN v_grupo_id;
END;
$function$;

ALTER FUNCTION public.registrar_pagamento_multiplo(jsonb) OWNER TO postgres;

-- ---------------------------------------------------------------------------
-- Exclusão do pagamento inteiro.
--
-- Recusa se alguma linha já foi baixada: no parcelado o grupo é um compromisso,
-- e apagá-lo depois que o cliente pagou parte deixaria dinheiro recebido sem
-- origem. Mesmo motivo pelo qual o adiantamento trava.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.excluir_pagamento_multiplo(
  p_id bigint,
  p_deleted_by uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_grupo public.pagamento_multiplo%ROWTYPE;
  v_baixadas integer;
  v_documentos integer[];
  v_doc_id integer;
  v_removidas integer;
BEGIN
  SELECT * INTO v_grupo FROM public.pagamento_multiplo WHERE id = p_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Pagamento múltiplo #% não encontrado.', p_id USING ERRCODE = 'P0002';
  END IF;

  -- Só no parcelado a checagem faz sentido: à vista TODAS as linhas nascem
  -- baixadas, e o que se está desfazendo é justamente o recebimento inteiro.
  IF v_grupo.modo = 'PARCELADO' THEN
    SELECT count(*) INTO v_baixadas
      FROM public.transacao t
     WHERE t.pagamento_multiplo_id = p_id
       AND t.is_deleted = false
       AND t.pendente = false;

    IF v_baixadas > 0 THEN
      RAISE EXCEPTION
        'Este pagamento tem % parcela(s) já baixada(s). Estorne essas baixas antes de excluir o pagamento.',
        v_baixadas USING ERRCODE = 'P0001';
    END IF;
  END IF;

  SELECT array_agg(DISTINCT coalesce(t.ordemservicoid, t.vendaid))
    INTO v_documentos
    FROM public.transacao t
   WHERE t.pagamento_multiplo_id = p_id
     AND t.is_deleted = false;

  UPDATE public.transacao
     SET is_deleted = true,
         deleted_at = now(),
         deleted_by = p_deleted_by,
         updated_at = now()
   WHERE pagamento_multiplo_id = p_id
     AND is_deleted = false;

  GET DIAGNOSTICS v_removidas = ROW_COUNT;

  IF v_documentos IS NOT NULL THEN
    FOREACH v_doc_id IN ARRAY v_documentos LOOP
      IF v_grupo.tipo_documento = 'OS' THEN
        PERFORM public.recalcular_status_financeiro_os(v_doc_id);
      ELSE
        PERFORM public.recalcular_status_financeiro_venda(v_doc_id);
      END IF;
    END LOOP;
  END IF;

  DELETE FROM public.pagamento_multiplo WHERE id = p_id;

  RETURN jsonb_build_object(
    'id', p_id,
    'transacoes_removidas', v_removidas,
    'documentos', coalesce(to_jsonb(v_documentos), '[]'::jsonb)
  );
END;
$function$;

ALTER FUNCTION public.excluir_pagamento_multiplo(bigint, uuid) OWNER TO postgres;

REVOKE ALL ON FUNCTION public.recalcular_status_financeiro_venda(integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.registrar_pagamento_multiplo(jsonb) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.excluir_pagamento_multiplo(bigint, uuid) FROM PUBLIC, anon, authenticated;
