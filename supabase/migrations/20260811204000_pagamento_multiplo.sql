GRANT EXECUTE ON FUNCTION public.excluir_pagamento_multiplo(bigint, uuid) TO service_role;

ALTER TABLE public.pagamento_multiplo ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pagamento_multiplo NO FORCE ROW LEVEL SECURITY;

COMMIT;
