-- Pagamento múltiplo: uma movimentação de dinheiro, uma transação.
--
-- PROBLEMA
-- O desenho original (20260811204000) resolveu o rateio criando uma transação por
-- documento, porque `transacao.ordemservicoid` e `transacao.vendaid` são FKs
-- escalares e uma linha não cabe em duas OS. O efeito colateral é que o fluxo de
-- caixa passou a mostrar N linhas para UM recebimento: pagar duas OS num PIX
-- produzia dois lançamentos, e três OS em 4x produziam doze.
--
-- O caixa não registra documentos, registra dinheiro. Se entrou um PIX, entrou
-- uma linha.
--
-- MODELO
-- O rateio sai da transação e vira tabela própria: `pagamento_multiplo_rateio`
-- liga transação → documento → valor. A transação deixa de apontar para uma OS
-- e passa a ser só o dinheiro; quem sabe quanto coube a cada documento é o
-- rateio.
--
--   à vista       1 transação, N linhas de rateio
--   parcelado     P transações (uma por parcela), cada uma com N linhas
--
-- A pergunta "quanto este documento recebeu?" passa a ter uma fonte só — a view
-- `recebimento_por_documento` —, que soma o vínculo direto e o rateio. Todas as
-- funções que respondiam isso pelo `ordemservicoid` passam a ler dela, para não
-- existirem duas verdades sobre o mesmo saldo.
--
-- CUIDADO QUE ESTA MIGRATION PRECISA TER
-- `sincronizar_eventos_financeiros_transacao` ignora transação ligada a OS ou
-- venda: é assim que o recebimento não vira receita na DRE, já que a receita foi
-- reconhecida pelos eventos da OS. Com `ordemservicoid` nulo, a transação do
-- pagamento múltiplo passaria a ser vista como lançamento avulso e a receita
-- seria contada DUAS vezes, sem erro nenhum na tela. Por isso o grupo entra na
-- lista de exclusão daquela função.
BEGIN;

-- ---------------------------------------------------------------------- rateio
CREATE TABLE IF NOT EXISTS public.pagamento_multiplo_rateio (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pagamento_multiplo_id bigint NOT NULL
    REFERENCES public.pagamento_multiplo(id) ON DELETE CASCADE,
  transacao_id bigint NOT NULL
    REFERENCES public.transacao(id) ON DELETE CASCADE,
  tipo_documento text NOT NULL,
  documento_id integer NOT NULL,
  valor numeric(14,2) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pagamento_multiplo_rateio_tipo_check CHECK (tipo_documento IN ('OS', 'VENDA')),
  CONSTRAINT pagamento_multiplo_rateio_valor_check CHECK (valor > 0),
  -- Um documento aparece uma vez por transação: duas fatias na mesma parcela
  -- seriam o mesmo abatimento contado duas vezes.
  CONSTRAINT pagamento_multiplo_rateio_uk UNIQUE (transacao_id, tipo_documento, documento_id)
);

ALTER TABLE public.pagamento_multiplo_rateio OWNER TO postgres;

COMMENT ON TABLE public.pagamento_multiplo_rateio IS
  'Quanto de cada transação de pagamento múltiplo coube a cada OS ou venda. É o vínculo que a FK escalar de transacao não consegue expressar.';

CREATE INDEX IF NOT EXISTS idx_pagamento_multiplo_rateio_documento
  ON public.pagamento_multiplo_rateio (tipo_documento, documento_id);
CREATE INDEX IF NOT EXISTS idx_pagamento_multiplo_rateio_transacao
  ON public.pagamento_multiplo_rateio (transacao_id);

ALTER TABLE public.pagamento_multiplo_rateio ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pagamento_multiplo_rateio NO FORCE ROW LEVEL SECURITY;

-- ------------------------------------------------------------------- a fonte
-- Recebimentos de um documento, venham por vínculo direto ou por rateio.
CREATE OR REPLACE VIEW public.recebimento_por_documento AS
  SELECT t.id AS transacao_id,
         CASE WHEN t.ordemservicoid IS NOT NULL THEN 'OS' ELSE 'VENDA' END AS tipo_documento,
         coalesce(t.ordemservicoid, t.vendaid) AS documento_id,
         greatest(coalesce(t.valor, 0) - greatest(coalesce(t.valor_acrescimos, 0), 0), 0) AS valor,
         t.pendente,
         t.pagamento_multiplo_id
    FROM public.transacao t
   WHERE t.is_deleted = false
     AND upper(t.tipo::text) = 'RECEITA'
     AND t.evento_financeiro_id IS NULL
     AND (t.ordemservicoid IS NOT NULL OR t.vendaid IS NOT NULL)
  UNION ALL
  -- A fatia já é valor de face: o rateio é calculado sobre o saldo do documento,
  -- sem acréscimo financeiro, que pertence à transação inteira.
  SELECT t.id, r.tipo_documento, r.documento_id, r.valor, t.pendente, t.pagamento_multiplo_id
    FROM public.pagamento_multiplo_rateio r
    JOIN public.transacao t ON t.id = r.transacao_id
   WHERE t.is_deleted = false;

COMMENT ON VIEW public.recebimento_por_documento IS
  'Fonte única de "quanto esta OS ou venda recebeu". Unifica o vínculo direto (transacao.ordemservicoid/vendaid) e o rateio do pagamento múltiplo.';

ALTER VIEW public.recebimento_por_documento OWNER TO postgres;

-- --------------------------------------------------------------- leitores: OS
CREATE OR REPLACE FUNCTION public.resumo_financeiro_os(p_ordemservicoid integer)
RETURNS TABLE (
  total_devido numeric(14,2),
  valor_recebido numeric(14,2),
  valor_pendente numeric(14,2),
  valor_comprometido numeric(14,2),
  saldo_a_receber numeric(14,2),
  saldo_disponivel_lancamento numeric(14,2),
  quantidade_transacoes bigint,
  quitada boolean
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
  WITH dados_os AS (
    SELECT round(
      greatest(coalesce(o.orcamentototal, 0), 0) +
      CASE
        WHEN o.acrescimo_financeiro_tipo = 'PORCENTAGEM' THEN
          greatest(coalesce(o.orcamentototal, 0), 0) *
          least(greatest(coalesce(o.acrescimo_financeiro_valor, 0), 0), 100) / 100
        WHEN o.acrescimo_financeiro_tipo = 'FIXO' THEN
          greatest(coalesce(o.acrescimo_financeiro_valor, 0), 0)
        ELSE 0
      END,
      2
    )::numeric(14,2) AS total
    FROM public.ordemservico o
    WHERE o.id = p_ordemservicoid
      AND coalesce(o.is_deleted, false) = false
  ),
  pagamentos AS (
    SELECT
      coalesce(round(sum(r.valor) FILTER (WHERE r.pendente = false), 2), 0)::numeric(14,2) AS recebido,
      coalesce(round(sum(r.valor) FILTER (WHERE r.pendente = true), 2), 0)::numeric(14,2) AS pendente,
      count(*)::bigint AS quantidade
    FROM public.recebimento_por_documento r
    WHERE r.tipo_documento = 'OS'
      AND r.documento_id = p_ordemservicoid
  )
  SELECT
    d.total,
    p.recebido,
    p.pendente,
    round(p.recebido + p.pendente, 2)::numeric(14,2),
    greatest(round(d.total - p.recebido, 2), 0)::numeric(14,2),
    greatest(round(d.total - p.recebido - p.pendente, 2), 0)::numeric(14,2),
    p.quantidade,
    (d.total > 0 AND round(p.recebido + p.pendente, 2) >= d.total)
  FROM dados_os d
  CROSS JOIN pagamentos p;
$function$;

ALTER FUNCTION public.resumo_financeiro_os(integer) OWNER TO postgres;

-- ------------------------------------------------------------ leitores: venda
-- Regra da venda preservada: só título já baixado quita (ao contrário da OS, que
-- conta o pendente como comprometido). O que muda é a origem do número.
CREATE OR REPLACE FUNCTION public.recalcular_status_financeiro_venda(p_venda_id integer)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_total_devido numeric(14,2);
  v_total_pago numeric(14,2);
  v_status text;
  v_novo text;
BEGIN
  SELECT v.status::text,
         round(
           greatest(coalesce(v.valortotal, 0), 0) +
           CASE
             WHEN v.acrescimo_financeiro_tipo = 'PORCENTAGEM' THEN
               greatest(coalesce(v.valortotal, 0), 0) *
               least(greatest(coalesce(v.acrescimo_financeiro_valor, 0), 0), 100) / 100
             WHEN v.acrescimo_financeiro_tipo = 'FIXO' THEN
               greatest(coalesce(v.acrescimo_financeiro_valor, 0), 0)
             ELSE 0
           END,
           2
         )
    INTO v_status, v_total_devido
  FROM public.venda v
  WHERE v.id = p_venda_id;

  IF NOT FOUND THEN RETURN; END IF;
  IF v_status = 'CANCELADA' THEN RETURN; END IF;

  SELECT coalesce(round(sum(r.valor), 2), 0)
    INTO v_total_pago
  FROM public.recebimento_por_documento r
  WHERE r.tipo_documento = 'VENDA'
    AND r.documento_id = p_venda_id
    AND r.pendente = false;

  v_novo := CASE WHEN v_total_devido > 0 AND v_total_pago >= v_total_devido
                 THEN 'FINALIZADA' ELSE 'PAGAMENTO' END;

  UPDATE public.venda
  SET status = v_novo::public.enum_status_venda,
      updatedat = now()
  WHERE id = p_venda_id
    AND status::text IS DISTINCT FROM v_novo;
END;
$function$;

ALTER FUNCTION public.recalcular_status_financeiro_venda(integer) OWNER TO postgres;

-- ------------------------------------------------------- revalidação em grupo
-- Uma transação de pagamento múltiplo toca vários documentos. Qualquer mudança
-- nela (baixa, exclusão, valor) precisa revalidar todos eles.
CREATE OR REPLACE FUNCTION public.recalcular_documentos_da_transacao(p_transacao_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT DISTINCT tipo_documento, documento_id
      FROM public.pagamento_multiplo_rateio
     WHERE transacao_id = p_transacao_id
  LOOP
    IF r.tipo_documento = 'OS' THEN
      PERFORM public.recalcular_status_financeiro_os(r.documento_id);
    ELSE
      PERFORM public.recalcular_status_financeiro_venda(r.documento_id);
    END IF;
  END LOOP;
END;
$function$;

ALTER FUNCTION public.recalcular_documentos_da_transacao(bigint) OWNER TO postgres;

CREATE OR REPLACE FUNCTION public.tg_recalcular_status_financeiro_os()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_old_os integer;
  v_new_os integer;
BEGIN
  IF TG_OP <> 'INSERT'
     AND OLD.ordemservicoid IS NOT NULL
     AND upper(OLD.tipo::text) = 'RECEITA'
     AND OLD.evento_financeiro_id IS NULL THEN
    v_old_os := OLD.ordemservicoid;
  END IF;

  IF TG_OP <> 'DELETE'
     AND NEW.ordemservicoid IS NOT NULL
     AND upper(NEW.tipo::text) = 'RECEITA'
     AND NEW.evento_financeiro_id IS NULL THEN
    v_new_os := NEW.ordemservicoid;
  END IF;

  IF v_old_os IS NOT NULL THEN
    PERFORM public.recalcular_status_financeiro_os(v_old_os);
  END IF;
  IF v_new_os IS NOT NULL AND v_new_os IS DISTINCT FROM v_old_os THEN
    PERFORM public.recalcular_status_financeiro_os(v_new_os);
  END IF;

  -- Transação de pagamento múltiplo não aponta para documento nenhum: quem sabe
  -- quais ela tocou é o rateio.
  IF TG_OP = 'DELETE' THEN
    IF OLD.pagamento_multiplo_id IS NOT NULL THEN
      PERFORM public.recalcular_documentos_da_transacao(OLD.id);
    END IF;
    RETURN OLD;
  END IF;

  IF NEW.pagamento_multiplo_id IS NOT NULL THEN
    PERFORM public.recalcular_documentos_da_transacao(NEW.id);
  END IF;
  RETURN NEW;
END;
$function$;

ALTER FUNCTION public.tg_recalcular_status_financeiro_os() OWNER TO postgres;

-- O rateio nasce depois da transação; sem este gatilho o documento só saberia do
-- pagamento no próximo evento que o tocasse.
CREATE OR REPLACE FUNCTION public.tg_recalcular_documento_do_rateio()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_tipo text := CASE WHEN TG_OP = 'DELETE' THEN OLD.tipo_documento ELSE NEW.tipo_documento END;
  v_doc integer := CASE WHEN TG_OP = 'DELETE' THEN OLD.documento_id ELSE NEW.documento_id END;
BEGIN
  IF v_tipo = 'OS' THEN
    PERFORM public.recalcular_status_financeiro_os(v_doc);
  ELSE
    PERFORM public.recalcular_status_financeiro_venda(v_doc);
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_recalcular_documento_do_rateio ON public.pagamento_multiplo_rateio;
CREATE TRIGGER trg_recalcular_documento_do_rateio
AFTER INSERT OR DELETE ON public.pagamento_multiplo_rateio
FOR EACH ROW EXECUTE FUNCTION public.tg_recalcular_documento_do_rateio();

-- ------------------------------------------------------------------- a DRE
-- Sem `pagamento_multiplo_id` nesta lista, a transação do recebimento viraria
-- evento de receita avulsa e a DRE contaria a mesma receita duas vezes: uma pelos
-- eventos da OS, outra pelo dinheiro que os quitou.
CREATE OR REPLACE FUNCTION public.sincronizar_eventos_financeiros_transacao(p_transacaoid bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
declare
  v_tx public.transacao%ROWTYPE;
  v_linha_id integer;
  v_exclui boolean := false;
  v_natureza text;
  v_natureza_dre text;
begin
  select * into v_tx from public.transacao where id = p_transacaoid;
  if not found then return; end if;

  if v_tx.is_deleted
     or v_tx.evento_financeiro_id is not null
     or v_tx.ordemservicoid is not null
     or v_tx.vendaid is not null
     or v_tx.pagamento_multiplo_id is not null
     or v_tx.entrada_id is not null
     or v_tx.usoconsumo_entrada_id is not null
     or v_tx.origem = 'ORIGEM_MIGRACAO' then
    update public.eventos_financeiros
       set status = 'CANCELADO', updated_at = now()
     where source_type = 'TRANSACAO' and source_id = p_transacaoid and status = 'ATIVO';
    return;
  end if;

  select mp.linha_id, mp.exclui_do_resultado
    into v_linha_id, v_exclui
    from public.planosdeconta pc
    join public.dre_mapeamento mp
      on mp.origem_tipo = 'PLANO_GRUPO' and mp.origem_id = pc.grupo_id and mp.ativo
   where pc.id = v_tx.plano_de_conta_id
   limit 1;

  if coalesce(v_exclui, false) then
    update public.eventos_financeiros
       set status = 'CANCELADO', updated_at = now()
     where source_type = 'TRANSACAO' and source_id = p_transacaoid and status = 'ATIVO';
    return;
  end if;

  v_natureza := case when upper(v_tx.tipo::text) = 'RECEITA' then 'RECEITA' else 'DESPESA' end;

  select dl.natureza_dre into v_natureza_dre
    from public.dre_linha dl where dl.id = v_linha_id;

  v_natureza_dre := coalesce(v_natureza_dre,
    case when v_natureza = 'RECEITA' then 'RECEITA' else 'DESPESA' end);

  insert into public.eventos_financeiros
    (ordemservicoid, source_type, source_id, origem, natureza, natureza_dre,
     chave_origem, descricao, detalhe, valor, competencia_em, dre_linha_id,
     centro_custo_id, transacaoid, dados_snapshot, pode_gerar_transacao, status)
  values
    (null, 'TRANSACAO', p_transacaoid, 'AVULSO', v_natureza, v_natureza_dre,
     'TRANSACAO', coalesce(nullif(v_tx.descricao, ''), 'Lancamento #' || p_transacaoid),
     nullif(v_tx.plano_de_conta, ''), round(coalesce(v_tx.valor, 0), 2),
     coalesce(v_tx.competencia_em, v_tx.data), v_linha_id,
     v_tx.centro_custo_id, p_transacaoid,
     jsonb_build_object('categoria', v_tx.categoria, 'sem_classificacao', v_linha_id is null),
     false, 'ATIVO')
  on conflict (source_type, source_id, origem, chave_origem, natureza)
    where ordemservicoid is null
  do update set valor = excluded.valor,
                descricao = excluded.descricao,
                detalhe = excluded.detalhe,
                competencia_em = excluded.competencia_em,
                dre_linha_id = excluded.dre_linha_id,
                natureza_dre = excluded.natureza_dre,
                centro_custo_id = excluded.centro_custo_id,
                dados_snapshot = excluded.dados_snapshot,
                status = 'ATIVO',
                updated_at = now()
  where public.eventos_financeiros.status <> 'CONVERTIDO';
end;
$function$;

DROP TRIGGER IF EXISTS trg_eventos_financeiros_transacao ON public.transacao;
CREATE TRIGGER trg_eventos_financeiros_transacao
AFTER INSERT OR UPDATE OF valor, tipo, competencia_em, data, plano_de_conta_id,
                          centro_custo_id, is_deleted, descricao, origem,
                          pagamento_multiplo_id
ON public.transacao
FOR EACH ROW EXECUTE FUNCTION public.tg_eventos_financeiros_transacao();

-- ------------------------------------------------------------------ registro
CREATE OR REPLACE FUNCTION public.registrar_pagamento_multiplo(p_payload jsonb)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_tipo_documento text := upper(coalesce(p_payload->>'tipo_documento', ''));
  v_modo text := upper(coalesce(p_payload->>'modo', ''));
  v_valor_total numeric(14,2) := round(coalesce((p_payload->>'valor_total')::numeric, 0), 2);
  v_data timestamptz := coalesce(nullif(p_payload->>'data', '')::timestamptz, now());
  v_banco_id bigint := nullif(p_payload->>'banco_id', '')::bigint;
  v_metodo public.metodo_pagamento := nullif(p_payload->>'metodopagamento', '')::public.metodo_pagamento;
  v_created_by uuid := nullif(p_payload->>'created_by', '')::uuid;
  v_categoria text := coalesce(nullif(p_payload->>'categoria', ''), 'NÃO RELACIONADO');
  v_categoria_id integer := nullif(p_payload->>'categoria_id', '')::integer;
  v_plano_id integer := nullif(p_payload->>'plano_de_conta_id', '')::integer;
  v_centro_id integer := nullif(p_payload->>'centro_custo_id', '')::integer;
  v_pendente boolean := (v_modo = 'PARCELADO');
  v_grupo_id bigint;
  v_soma numeric(14,2);
  v_doc_id integer;
  v_documentos integer[] := ARRAY[]::integer[];
  v_cliente_id integer := nullif(p_payload->>'cliente_id', '')::integer;
  v_nome text := nullif(btrim(p_payload->>'nomepagador'), '');
  v_cpfcnpj text := nullif(btrim(p_payload->>'cpfcnpjpagador'), '');
  v_clientes integer[];
  v_descricao_grupo text;
  v_descricao text;
  v_parcela record;
  v_transacao_id bigint;
  v_total_parcelas integer;
  v_comprometido numeric(14,2);
  v_devido numeric(14,2);
BEGIN
  IF v_tipo_documento NOT IN ('OS', 'VENDA') THEN
    RAISE EXCEPTION 'tipo_documento deve ser OS ou VENDA.' USING ERRCODE = 'P0001';
  END IF;
  IF v_modo NOT IN ('AVISTA', 'PARCELADO') THEN
    RAISE EXCEPTION 'modo deve ser AVISTA ou PARCELADO.' USING ERRCODE = 'P0001';
  END IF;
  IF v_valor_total <= 0 THEN
    RAISE EXCEPTION 'O valor do pagamento deve ser maior que zero.' USING ERRCODE = 'P0001';
  END IF;
  IF jsonb_typeof(p_payload->'linhas') <> 'array'
     OR jsonb_array_length(p_payload->'linhas') = 0 THEN
    RAISE EXCEPTION 'Informe as linhas do rateio.' USING ERRCODE = 'P0001';
  END IF;

  SELECT round(coalesce(sum((item->>'valor')::numeric), 0), 2) INTO v_soma
    FROM jsonb_array_elements(p_payload->'linhas') AS item;

  IF v_soma <> v_valor_total THEN
    RAISE EXCEPTION 'A soma do rateio (%) difere do valor do pagamento (%).',
      v_soma, v_valor_total USING ERRCODE = 'P0001';
  END IF;

  SELECT array_agg(DISTINCT (item->>'documento_id')::integer)
    INTO v_documentos
    FROM jsonb_array_elements(p_payload->'linhas') AS item;

  -- O lock vive até o fim desta transação e serializa com a validação de limite
  -- do pagamento avulso: duas telas não comprometem o mesmo saldo.
  FOREACH v_doc_id IN ARRAY v_documentos LOOP
    PERFORM pg_advisory_xact_lock(87001, v_doc_id);
  END LOOP;

  -- Pagador: quando os documentos são do mesmo cliente, é ele. Misturando
  -- clientes não existe um pagador só, e inventar um seria pior que assumir.
  IF v_cliente_id IS NULL THEN
    IF v_tipo_documento = 'OS' THEN
      SELECT array_agg(DISTINCT o.clienteid) INTO v_clientes
        FROM public.ordemservico o WHERE o.id = ANY (v_documentos);
    ELSE
      SELECT array_agg(DISTINCT v.clienteid) INTO v_clientes
        FROM public.venda v WHERE v.id = ANY (v_documentos);
    END IF;

    IF array_length(v_clientes, 1) = 1 THEN
      v_cliente_id := v_clientes[1];
    END IF;
  END IF;

  IF v_cliente_id IS NOT NULL AND (v_nome IS NULL OR v_cpfcnpj IS NULL) THEN
    SELECT coalesce(v_nome, c.nomerazaosocial), coalesce(v_cpfcnpj, c.cpfcnpj)
      INTO v_nome, v_cpfcnpj
      FROM public.cliente c WHERE c.id = v_cliente_id;
  END IF;

  v_descricao_grupo := coalesce(
    nullif(btrim(p_payload->>'descricao'), ''),
    'Pagamento múltiplo de ' || array_length(v_documentos, 1) || ' documento(s)');

  INSERT INTO public.pagamento_multiplo (
    descricao, modo, tipo_documento, valor_total, data, banco_id, metodopagamento, created_by
  ) VALUES (
    v_descricao_grupo, v_modo, v_tipo_documento, v_valor_total, v_data,
    v_banco_id, v_metodo, v_created_by
  ) RETURNING id INTO v_grupo_id;

  SELECT max((item->>'total_parcelas')::integer) INTO v_total_parcelas
    FROM jsonb_array_elements(p_payload->'linhas') AS item;
  v_total_parcelas := greatest(coalesce(v_total_parcelas, 1), 1);

  -- Uma transação por PARCELA — não por documento. É aqui que o modelo muda: o
  -- caixa recebe uma linha por movimentação de dinheiro, e o rateio guarda a
  -- repartição entre os documentos.
  FOR v_parcela IN
    SELECT (item->>'parcela')::integer AS numero,
           round(sum((item->>'valor')::numeric), 2) AS valor,
           min(nullif(item->>'vencimento_em', '')) AS vencimento
      FROM jsonb_array_elements(p_payload->'linhas') AS item
     GROUP BY (item->>'parcela')::integer
     ORDER BY 1
  LOOP
    v_descricao := v_descricao_grupo;
    IF v_total_parcelas > 1 THEN
      v_descricao := v_descricao || ' - Parcela ' || v_parcela.numero || '/' || v_total_parcelas;
    END IF;

    INSERT INTO public.transacao (
      descricao, valor, "valorLiquido", data, metodopagamento, categoria, categoria_id,
      plano_de_conta_id, centro_custo_id, tipo, cliente_id, banco_id,
      nomepagador, cpfcnpjpagador, pendente, pago_em,
      ordemservicoid, vendaid, pagamento_multiplo_id, created_by
    ) VALUES (
      v_descricao,
      v_parcela.valor,
      v_parcela.valor,
      coalesce(v_parcela.vencimento::timestamptz, v_data),
      v_metodo, v_categoria, v_categoria_id, v_plano_id, v_centro_id,
      'RECEITA'::public.tipos_transacao, v_cliente_id,
      CASE WHEN v_pendente THEN NULL ELSE v_banco_id END,
      coalesce(v_nome, 'Diversos'),
      coalesce(v_cpfcnpj, 'NÃO INFORMADO'),
      v_pendente,
      CASE WHEN v_pendente THEN NULL ELSE v_data END,
      NULL, NULL,
      v_grupo_id, v_created_by
    ) RETURNING id INTO v_transacao_id;

    INSERT INTO public.pagamento_multiplo_rateio (
      pagamento_multiplo_id, transacao_id, tipo_documento, documento_id, valor
    )
    SELECT v_grupo_id, v_transacao_id, v_tipo_documento,
           (item->>'documento_id')::integer,
           round((item->>'valor')::numeric, 2)
      FROM jsonb_array_elements(p_payload->'linhas') AS item
     WHERE (item->>'parcela')::integer = v_parcela.numero
       AND round((item->>'valor')::numeric, 2) > 0;
  END LOOP;

  -- Pós-condição: nenhum documento pode ter ficado comprometido além do que deve.
  -- Roda com o lock na mão, então também cobre a corrida com o pagamento avulso.
  FOREACH v_doc_id IN ARRAY v_documentos LOOP
    IF v_tipo_documento = 'OS' THEN
      SELECT r.total_devido, r.valor_comprometido
        INTO v_devido, v_comprometido
        FROM public.resumo_financeiro_os(v_doc_id) r;
    ELSE
      SELECT round(
               greatest(coalesce(v.valortotal, 0), 0) +
               CASE
                 WHEN v.acrescimo_financeiro_tipo = 'PORCENTAGEM' THEN
                   greatest(coalesce(v.valortotal, 0), 0) *
                   least(greatest(coalesce(v.acrescimo_financeiro_valor, 0), 0), 100) / 100
                 WHEN v.acrescimo_financeiro_tipo = 'FIXO' THEN
                   greatest(coalesce(v.acrescimo_financeiro_valor, 0), 0)
                 ELSE 0
               END, 2)
        INTO v_devido
        FROM public.venda v WHERE v.id = v_doc_id;

      SELECT coalesce(round(sum(r.valor), 2), 0) INTO v_comprometido
        FROM public.recebimento_por_documento r
       WHERE r.tipo_documento = 'VENDA' AND r.documento_id = v_doc_id;
    END IF;

    IF coalesce(v_devido, 0) <= 0 THEN
      RAISE EXCEPTION 'O documento #% não possui valor financeiro disponível para pagamento.',
        v_doc_id USING ERRCODE = '23514';
    END IF;
    IF round(coalesce(v_comprometido, 0), 2) > v_devido THEN
      RAISE EXCEPTION 'O rateio ultrapassa o saldo do documento #%: comprometido % de %.',
        v_doc_id, v_comprometido, v_devido USING ERRCODE = '23514';
    END IF;
  END LOOP;

  RETURN v_grupo_id;
END;
$function$;

ALTER FUNCTION public.registrar_pagamento_multiplo(jsonb) OWNER TO postgres;

-- ------------------------------------------------------------------ exclusão
CREATE OR REPLACE FUNCTION public.excluir_pagamento_multiplo(
  p_id bigint,
  p_deleted_by uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_grupo public.pagamento_multiplo%ROWTYPE;
  v_baixadas integer;
  v_documentos jsonb;
  v_doc record;
  v_removidas integer;
BEGIN
  SELECT * INTO v_grupo FROM public.pagamento_multiplo WHERE id = p_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Pagamento múltiplo #% não encontrado.', p_id USING ERRCODE = 'P0002';
  END IF;

  IF v_grupo.modo = 'PARCELADO' THEN
    SELECT count(*) INTO v_baixadas
      FROM public.transacao t
     WHERE t.pagamento_multiplo_id = p_id
       AND t.is_deleted = false
       AND t.pendente = false;

    IF v_baixadas > 0 THEN
      RAISE EXCEPTION
        'Este pagamento tem % parcela(s) já baixada(s). Estorne essas baixas antes de excluir o pagamento.',
        v_baixadas USING ERRCODE = 'P0001';
    END IF;
  END IF;

  -- Os documentos agora vivem no rateio, e não no `ordemservicoid` das linhas.
  SELECT coalesce(jsonb_agg(DISTINCT jsonb_build_object('tipo', tipo_documento, 'id', documento_id)), '[]'::jsonb)
    INTO v_documentos
    FROM public.pagamento_multiplo_rateio
   WHERE pagamento_multiplo_id = p_id;

  UPDATE public.transacao
     SET is_deleted = true,
         deleted_at = now(),
         deleted_by = p_deleted_by,
         updated_at = now()
   WHERE pagamento_multiplo_id = p_id
     AND is_deleted = false;

  GET DIAGNOSTICS v_removidas = ROW_COUNT;

  FOR v_doc IN
    SELECT DISTINCT tipo_documento, documento_id
      FROM public.pagamento_multiplo_rateio
     WHERE pagamento_multiplo_id = p_id
  LOOP
    IF v_doc.tipo_documento = 'OS' THEN
      PERFORM public.recalcular_status_financeiro_os(v_doc.documento_id);
    ELSE
      PERFORM public.recalcular_status_financeiro_venda(v_doc.documento_id);
    END IF;
  END LOOP;

  -- O grupo NÃO é apagado. A versão anterior tentava, e não podia: as transações
  -- são excluídas por `is_deleted` e continuam referenciando o grupo, cuja FK é
  -- ON DELETE RESTRICT — ou seja, excluir um pagamento múltiplo sempre falhou com
  -- erro de chave estrangeira. Manter a linha também preserva o histórico de que
  -- aquele recebimento existiu e foi desfeito; o rateio segue junto, e some das
  -- contas porque `recebimento_por_documento` só olha transação não excluída.

  RETURN jsonb_build_object(
    'id', p_id,
    'transacoes_removidas', v_removidas,
    'documentos', v_documentos
  );
END;
$function$;

ALTER FUNCTION public.excluir_pagamento_multiplo(bigint, uuid) OWNER TO postgres;

-- --------------------------------------------------------------------- baixa
-- A baixa de uma parcela do grupo precisa revalidar todos os documentos que ela
-- cobre. De quebra, a venda passa a usar `recalcular_status_financeiro_venda`
-- em vez da cópia inline da mesma regra — que agora ficaria cega ao rateio.
CREATE OR REPLACE FUNCTION public.baixar_transacao_pendente(
  p_transacao_id bigint,
  p_pago_em timestamp with time zone,
  p_banco_id bigint,
  p_metodopagamento text,
  p_plano_de_conta_id integer DEFAULT NULL,
  p_centro_custo_id integer DEFAULT NULL,
  p_baixado_por uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_transacao public.transacao%ROWTYPE;
  v_metodo public.metodo_pagamento;
BEGIN
  IF p_transacao_id IS NULL OR p_transacao_id <= 0 THEN
    RAISE EXCEPTION 'Transação inválida.' USING ERRCODE = '22023';
  END IF;
  IF p_pago_em IS NULL THEN
    RAISE EXCEPTION 'Data do pagamento obrigatória.' USING ERRCODE = '22023';
  END IF;
  IF p_banco_id IS NULL OR p_banco_id <= 0 THEN
    RAISE EXCEPTION 'Banco obrigatório.' USING ERRCODE = '22023';
  END IF;
  IF nullif(btrim(p_metodopagamento), '') IS NULL THEN
    RAISE EXCEPTION 'Método de pagamento obrigatório.' USING ERRCODE = '22023';
  END IF;

  BEGIN
    v_metodo := btrim(p_metodopagamento)::public.metodo_pagamento;
  EXCEPTION WHEN OTHERS THEN
    RAISE EXCEPTION 'Método de pagamento inválido: %.', btrim(p_metodopagamento)
      USING ERRCODE = '22023';
  END;

  UPDATE public.transacao
  SET vencimento_em = coalesce(vencimento_em, data),
      data = p_pago_em,
      pago_em = p_pago_em,
      baixado_por = p_baixado_por,
      banco_id = p_banco_id,
      metodopagamento = v_metodo,
      plano_de_conta_id = p_plano_de_conta_id,
      centro_custo_id = p_centro_custo_id,
      pendente = false,
      updated_at = now()
  WHERE id = p_transacao_id
    AND pendente = true
    AND is_deleted = false
  RETURNING * INTO v_transacao;

  IF NOT FOUND THEN
    IF EXISTS (
      SELECT 1 FROM public.transacao
      WHERE id = p_transacao_id AND is_deleted = false
    ) THEN
      RAISE EXCEPTION 'A transação já foi baixada.' USING ERRCODE = '23505';
    END IF;
    RAISE EXCEPTION 'Transação não encontrada.' USING ERRCODE = 'P0002';
  END IF;

  INSERT INTO public.transacao_baixa_historico (
    transacao_id, vencimento_em, pago_em, baixado_por, banco_id, metodopagamento
  ) VALUES (
    v_transacao.id, v_transacao.vencimento_em, v_transacao.pago_em,
    v_transacao.baixado_por, v_transacao.banco_id, v_transacao.metodopagamento
  );

  IF upper(v_transacao.tipo::text) = 'RECEITA' AND v_transacao.evento_financeiro_id IS NULL THEN
    IF v_transacao.ordemservicoid IS NOT NULL THEN
      PERFORM public.recalcular_status_financeiro_os(v_transacao.ordemservicoid);
    END IF;

    IF v_transacao.vendaid IS NOT NULL THEN
      PERFORM public.recalcular_status_financeiro_venda(v_transacao.vendaid);
    END IF;

    IF v_transacao.pagamento_multiplo_id IS NOT NULL THEN
      PERFORM public.recalcular_documentos_da_transacao(v_transacao.id);
    END IF;
  END IF;

  RETURN jsonb_build_object(
    'id', v_transacao.id,
    'pago_em', v_transacao.pago_em,
    'vencimento_em', v_transacao.vencimento_em,
    'pendente', false
  );
END;
$function$;

ALTER FUNCTION public.baixar_transacao_pendente(bigint, timestamp with time zone, bigint, text, integer, integer, uuid) OWNER TO postgres;

-- ------------------------------------------------------- reversão de status
-- Reverter a OS apagava a transação de recebimento dela. Com um pagamento que
-- cobre várias OS não existe "a transação dela": apagar levaria junto o
-- recebimento das outras. Em vez de mexer no caixa por baixo do operador, a
-- reversão para e diz o que precisa ser feito antes.
CREATE OR REPLACE FUNCTION public.tg_excluir_transacoes_financeiras_os_por_status()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_grupos text;
BEGIN
  IF new.status::text IS NOT DISTINCT FROM old.status::text
     OR new.status::text NOT IN ('ORCAMENTO', 'CANCELADO', 'SEM_COBRANCA') THEN
    RETURN new;
  END IF;

  SELECT string_agg(DISTINCT '#' || g.pagamento_multiplo_id || ' (com ' || g.outros || ')', '; ')
    INTO v_grupos
    FROM (
      SELECT r.pagamento_multiplo_id,
             (SELECT string_agg(DISTINCT o.tipo_documento || ' #' || o.documento_id, ', ')
                FROM public.pagamento_multiplo_rateio o
               WHERE o.pagamento_multiplo_id = r.pagamento_multiplo_id
                 AND NOT (o.tipo_documento = 'OS' AND o.documento_id = new.id)) AS outros
        FROM public.pagamento_multiplo_rateio r
        JOIN public.transacao t ON t.id = r.transacao_id AND t.is_deleted = false
       WHERE r.tipo_documento = 'OS' AND r.documento_id = new.id
    ) g;

  IF v_grupos IS NOT NULL THEN
    RAISE EXCEPTION
      'Esta OS foi paga em pagamento múltiplo %. Exclua o pagamento pelo financeiro antes de reverter o status.',
      v_grupos USING ERRCODE = 'P0001';
  END IF;

  DELETE FROM public.transacao t
   WHERE t.ordemservicoid = new.id
     AND upper(t.tipo::text) = 'RECEITA'
     AND t.evento_financeiro_id IS NULL
     AND t.is_deleted = false;

  RETURN new;
END;
$function$;

-- -------------------------------------------------------------- dados atuais
-- Consolida os grupos já gravados no modelo antigo: a primeira transação de cada
-- parcela vira a linha do dinheiro, as irmãs saem e o vínculo que cada uma tinha
-- com seu documento vira rateio. Sem isto, os grupos existentes ficariam com N
-- linhas no caixa e sem rateio nenhum.
ALTER TABLE public.transacao DISABLE TRIGGER transacao_valor_apos_baixa_trg;

DO $backfill$
DECLARE
  v_grupo record;
  v_parcela record;
BEGIN
  FOR v_grupo IN SELECT * FROM public.pagamento_multiplo LOOP
    FOR v_parcela IN
      SELECT t.data AS competencia,
             min(t.id) AS sobrevivente,
             round(sum(t.valor), 2) AS valor,
             count(*) AS linhas
        FROM public.transacao t
       WHERE t.pagamento_multiplo_id = v_grupo.id
         AND t.is_deleted = false
       GROUP BY t.data
    LOOP
      CONTINUE WHEN v_parcela.linhas <= 1
        AND EXISTS (SELECT 1 FROM public.pagamento_multiplo_rateio
                     WHERE transacao_id = v_parcela.sobrevivente);

      INSERT INTO public.pagamento_multiplo_rateio (
        pagamento_multiplo_id, transacao_id, tipo_documento, documento_id, valor
      )
      SELECT v_grupo.id, v_parcela.sobrevivente, v_grupo.tipo_documento,
             coalesce(t.ordemservicoid, t.vendaid), round(t.valor, 2)
        FROM public.transacao t
       WHERE t.pagamento_multiplo_id = v_grupo.id
         AND t.is_deleted = false
         AND t.data = v_parcela.competencia
         AND coalesce(t.ordemservicoid, t.vendaid) IS NOT NULL
      ON CONFLICT (transacao_id, tipo_documento, documento_id) DO NOTHING;

      UPDATE public.transacao
         SET valor = v_parcela.valor,
             "valorLiquido" = v_parcela.valor,
             ordemservicoid = NULL,
             vendaid = NULL,
             descricao = v_grupo.descricao,
             updated_at = now()
       WHERE id = v_parcela.sobrevivente;

      UPDATE public.transacao
         SET is_deleted = true,
             deleted_at = now(),
             updated_at = now()
       WHERE pagamento_multiplo_id = v_grupo.id
         AND is_deleted = false
         AND data = v_parcela.competencia
         AND id <> v_parcela.sobrevivente;
    END LOOP;
  END LOOP;
END
$backfill$;

ALTER TABLE public.transacao ENABLE TRIGGER transacao_valor_apos_baixa_trg;

