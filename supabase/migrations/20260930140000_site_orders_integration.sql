begin;

create table if not exists public.site_order_link (
  id bigint generated by default as identity primary key,
  empresa_id integer not null references public.empresa(id) on delete cascade,
  site_order_id bigint not null,
  venda_id integer references public.venda(id) on delete set null,
  site_customer_id bigint,
  site_status text not null,
  payment_provider text,
  gateway_payment_id text,
  total_amount numeric(14,2) not null default 0,
  order_created_at timestamptz,
  import_status text not null default 'PENDENTE'
    check (import_status in ('PENDENTE', 'PROCESSANDO', 'IMPORTADA', 'ERRO')),
  import_locked_at timestamptz,
  import_error text,
  raw_order jsonb not null default '{}'::jsonb,
  last_synced_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (empresa_id, site_order_id),
  unique (venda_id)
);

create index if not exists idx_site_order_link_status
  on public.site_order_link (empresa_id, import_status, order_created_at desc);

comment on table public.site_order_link is
  'Vincula pedidos do banco independente da loja a vendas do ERP, com importacao idempotente.';

create or replace function public.fn_importar_pedido_site(
  p_empresa_id integer,
  p_pedido jsonb
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_site_order_id bigint := (p_pedido->>'id')::bigint;
  v_site_customer_id bigint := nullif(p_pedido->'customer'->>'id', '')::bigint;
  v_status text := upper(coalesce(p_pedido->>'status', ''));
  v_documento text := regexp_replace(coalesce(p_pedido->'customer'->>'document', ''), '\D', '', 'g');
  v_nome text := nullif(btrim(p_pedido->'customer'->>'name'), '');
  v_email text := nullif(lower(btrim(p_pedido->'customer'->>'email')), '');
  v_telefone text := nullif(regexp_replace(coalesce(p_pedido->'customer'->>'phone', ''), '\D', '', 'g'), '');
  v_endereco jsonb := coalesce(p_pedido->'shippingAddress', '{}'::jsonb);
  v_cliente_id integer;
  v_venda_id integer;
  v_itens jsonb := coalesce(p_pedido->'items', '[]'::jsonb);
begin
  if v_site_order_id is null or v_site_order_id <= 0 then
    raise exception 'Pedido do site sem identificador valido.';
  end if;
  if v_status <> 'PAGO' then
    raise exception 'Somente pedidos pagos podem ser importados. Pedido %, status %.', v_site_order_id, v_status;
  end if;
  if length(v_documento) not in (11, 14) or v_nome is null or v_email is null then
    raise exception 'Cliente do pedido % possui cadastro incompleto.', v_site_order_id;
  end if;
  if jsonb_typeof(v_itens) <> 'array' or jsonb_array_length(v_itens) = 0 then
    raise exception 'Pedido % nao possui itens.', v_site_order_id;
  end if;

  insert into public.site_order_link (
    empresa_id, site_order_id, site_customer_id, site_status,
    payment_provider, gateway_payment_id, total_amount, order_created_at,
    import_status, import_locked_at, raw_order, last_synced_at
  ) values (
    p_empresa_id, v_site_order_id, v_site_customer_id, v_status,
    nullif(p_pedido->>'paymentProvider', ''), nullif(p_pedido->>'gatewayPaymentId', ''),
    coalesce((p_pedido->>'total')::numeric, 0), nullif(p_pedido->>'createdAt', '')::timestamptz,
    'PROCESSANDO', now(), p_pedido, now()
  )
  on conflict (empresa_id, site_order_id) do update set
    site_status = excluded.site_status,
    payment_provider = excluded.payment_provider,
    gateway_payment_id = excluded.gateway_payment_id,
    total_amount = excluded.total_amount,
    raw_order = excluded.raw_order,
    last_synced_at = now(),
    updated_at = now();

  select venda_id into v_venda_id
    from public.site_order_link
   where empresa_id = p_empresa_id and site_order_id = v_site_order_id
   for update;

  if v_venda_id is not null then
    return v_venda_id;
  end if;

  select id into v_cliente_id
    from public.cliente
   where regexp_replace(coalesce(cpfcnpj, ''), '\D', '', 'g') = v_documento
     and is_deleted = false
   order by id
   limit 1;

  if v_cliente_id is null then
    begin
      insert into public.cliente (
        tipopessoa, cpfcnpj, nomerazaosocial, email, telefone,
        endereco, endereconumero, enderecocomplemento, bairro,
        cidade, estado, cep, status
      ) values (
        case when length(v_documento) = 14 then 'JURIDICA' else 'FISICA' end::public.enum_tipopessoa,
        v_documento, v_nome, v_email, coalesce(v_telefone, 'SITE' || v_site_customer_id::text),
        nullif(v_endereco->>'logradouro', ''), nullif(v_endereco->>'numero', ''),
        nullif(v_endereco->>'complemento', ''), nullif(v_endereco->>'bairro', ''),
        coalesce(nullif(v_endereco->>'cidade', ''), 'Nao informado'),
        coalesce(nullif(v_endereco->>'estado', ''), 'NI'),
        nullif(regexp_replace(coalesce(v_endereco->>'cep', ''), '\D', '', 'g'), ''),
        'ATIVO'
      ) returning id into v_cliente_id;
    exception when unique_violation then
      select id into v_cliente_id
        from public.cliente
       where regexp_replace(coalesce(cpfcnpj, ''), '\D', '', 'g') = v_documento
       order by id
       limit 1;
      if v_cliente_id is null then
        raise;
      end if;
    end;
  end if;

  v_venda_id := public.fn_criar_venda_marketplace_com_itens(
    jsonb_build_object(
      'clienteId', v_cliente_id,
      'status', 'FINALIZADA',
      'canal', 'ONLINE',
      'statusEntrega', 'SEPARACAO',
      'subTotal', (p_pedido->>'subtotal')::numeric,
      'valorTotal', (p_pedido->>'total')::numeric,
      'formaPagamento', coalesce(nullif(p_pedido->>'paymentMethod', ''), 'ASAAS'),
      'dataVenda', coalesce(nullif(p_pedido->>'createdAt', ''), now()::text),
      'observacoes', 'Pedido do Site #' || v_site_order_id,
      'itens', v_itens
    )
  );

  update public.site_order_link
     set venda_id = v_venda_id,
         import_status = 'IMPORTADA',
         import_locked_at = null,
         import_error = null,
         updated_at = now()
   where empresa_id = p_empresa_id and site_order_id = v_site_order_id;

  return v_venda_id;
exception when others then
  update public.site_order_link
     set import_status = 'ERRO', import_locked_at = null,
         import_error = sqlerrm, updated_at = now()
   where empresa_id = p_empresa_id and site_order_id = v_site_order_id;
  raise;
end;
$$;

alter table public.site_order_link enable row level security;
revoke all on public.site_order_link from public, anon, authenticated;
grant all on public.site_order_link to service_role;
grant usage, select on sequence public.site_order_link_id_seq to service_role;
revoke all on function public.fn_importar_pedido_site(integer, jsonb) from public, anon, authenticated;
grant execute on function public.fn_importar_pedido_site(integer, jsonb) to service_role;

commit;
