BEGIN;

-- Os arquivos ficam no Storage; esta tabela guarda apenas o vínculo e os
-- metadados necessários para listar e auditar os anexos de uma transação.
CREATE TABLE IF NOT EXISTS public.transacao_anexo (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transacao_id bigint NOT NULL
    REFERENCES public.transacao(id) ON DELETE CASCADE,
  nome text NOT NULL,
  tipo text NOT NULL,
  tamanho integer NOT NULL,
  path text NOT NULL,
  descricao text,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT transacao_anexo_nome_preenchido CHECK (btrim(nome) <> ''),
  CONSTRAINT transacao_anexo_tipo_preenchido CHECK (btrim(tipo) <> ''),
  CONSTRAINT transacao_anexo_path_preenchido CHECK (btrim(path) <> ''),
  CONSTRAINT transacao_anexo_tamanho_valido CHECK (tamanho > 0 AND tamanho <= 10485760),
  CONSTRAINT transacao_anexo_path_unique UNIQUE (path)
);

CREATE INDEX IF NOT EXISTS transacao_anexo_transacao_created_idx
  ON public.transacao_anexo (transacao_id, created_at DESC);

-- O ERP usa NextAuth e service_role pelas APIs do servidor. Nenhum documento
-- financeiro pode ser lido diretamente pelos papéis do navegador.
ALTER TABLE public.transacao_anexo ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transacao_anexo NO FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.transacao_anexo FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.transacao_anexo_id_seq FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.transacao_anexo TO service_role;
GRANT ALL ON SEQUENCE public.transacao_anexo_id_seq TO service_role;

-- Bucket privado: a aplicação entrega URLs assinadas de curta duração.
INSERT INTO storage.buckets (
  id,
  name,
  owner,
  public,
  file_size_limit,
  allowed_mime_types
)
VALUES (
  'transacao_anexos',
  'transacao_anexos',
  NULL,
  false,
  10485760,
  ARRAY['application/pdf', 'image/jpeg', 'image/png', 'image/webp']
)
ON CONFLICT (id) DO UPDATE
SET name = EXCLUDED.name,
    public = EXCLUDED.public,
    file_size_limit = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types;

COMMIT;
