create table if not exists public.veiculo_imagem (
  id bigint generated by default as identity primary key,
  veiculo_id bigint not null references public.veiculo(id) on delete cascade,
  url text not null,
  path text,
  ordem integer not null default 1,
  createdat timestamptz not null default now()
);

create index if not exists idx_veiculo_imagem_veiculo_id_ordem
  on public.veiculo_imagem (veiculo_id, ordem);

alter table public.veiculo
  add column if not exists "imgUrl" text;

insert into storage.buckets (id, name, public)
values ('veiculo_imagem', 'veiculo_imagem', true)
on conflict (id) do nothing;
