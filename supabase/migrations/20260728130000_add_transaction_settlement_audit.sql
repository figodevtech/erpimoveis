-- Baixa atomica e auditavel de transacoes financeiras pendentes.
BEGIN;

ALTER TABLE public.transacao
  ADD COLUMN IF NOT EXISTS vencimento_em timestamp with time zone,
  ADD COLUMN IF NOT EXISTS pago_em timestamp with time zone,
  ADD COLUMN IF NOT EXISTS baixado_por uuid;

CREATE TABLE IF NOT EXISTS public.transacao_baixa_historico (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Mantemos o identificador mesmo se a transacao for posteriormente excluida.
  transacao_id bigint NOT NULL,
  vencimento_em timestamp with time zone NOT NULL,
  pago_em timestamp with time zone NOT NULL,
  baixado_por uuid,
  banco_id bigint,
  metodopagamento text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  UNIQUE (transacao_id)
);

CREATE INDEX IF NOT EXISTS transacao_baixa_historico_pago_em_idx
  ON public.transacao_baixa_historico(pago_em DESC);
CREATE INDEX IF NOT EXISTS transacao_baixado_por_idx
  ON public.transacao(baixado_por)
  WHERE baixado_por IS NOT NULL;

CREATE OR REPLACE FUNCTION public.proteger_transacao_baixa_historico()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  RAISE EXCEPTION 'O historico de baixa e imutavel.' USING ERRCODE = '55000';
END;
$$;

DROP TRIGGER IF EXISTS trg_proteger_transacao_baixa_historico
  ON public.transacao_baixa_historico;
CREATE TRIGGER trg_proteger_transacao_baixa_historico
  BEFORE UPDATE OR DELETE ON public.transacao_baixa_historico
  FOR EACH ROW EXECUTE FUNCTION public.proteger_transacao_baixa_historico();

CREATE OR REPLACE FUNCTION public.baixar_transacao_pendente(
  p_transacao_id bigint,
  p_pago_em timestamp with time zone,
  p_banco_id bigint,
  p_metodopagamento text,
  p_plano_de_conta_id integer DEFAULT NULL,
  p_centro_custo_id integer DEFAULT NULL,
  p_baixado_por uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_transacao public.transacao%ROWTYPE;
  v_total_devido numeric(14,2);
  v_total_pago numeric(14,2);
BEGIN
  IF p_transacao_id IS NULL OR p_transacao_id <= 0 THEN
    RAISE EXCEPTION 'Transacao invalida.' USING ERRCODE = '22023';
  END IF;
  IF p_pago_em IS NULL THEN
    RAISE EXCEPTION 'Data do pagamento obrigatoria.' USING ERRCODE = '22023';
  END IF;
  IF p_banco_id IS NULL OR p_banco_id <= 0 THEN
    RAISE EXCEPTION 'Banco obrigatorio.' USING ERRCODE = '22023';
  END IF;
  IF nullif(btrim(p_metodopagamento), '') IS NULL THEN
    RAISE EXCEPTION 'Metodo de pagamento obrigatorio.' USING ERRCODE = '22023';
  END IF;

  UPDATE public.transacao
  SET vencimento_em = coalesce(vencimento_em, data),
      data = p_pago_em,
      pago_em = p_pago_em,
      baixado_por = p_baixado_por,
      banco_id = p_banco_id,
      metodopagamento = btrim(p_metodopagamento),
      plano_de_conta_id = p_plano_de_conta_id,
      centro_custo_id = p_centro_custo_id,
      pendente = false,
      updated_at = now()
  WHERE id = p_transacao_id
    AND pendente = true
    AND is_deleted = false
  RETURNING * INTO v_transacao;

  IF NOT FOUND THEN
    IF EXISTS (
      SELECT 1 FROM public.transacao
      WHERE id = p_transacao_id AND is_deleted = false
    ) THEN
      RAISE EXCEPTION 'A transacao ja foi baixada.' USING ERRCODE = '23505';
    END IF;
    RAISE EXCEPTION 'Transacao nao encontrada.' USING ERRCODE = 'P0002';
  END IF;

  INSERT INTO public.transacao_baixa_historico (
    transacao_id, vencimento_em, pago_em, baixado_por, banco_id, metodopagamento
  ) VALUES (
    v_transacao.id, v_transacao.vencimento_em, v_transacao.pago_em,
    v_transacao.baixado_por, v_transacao.banco_id, v_transacao.metodopagamento
  );

  -- Revalida somente recebimentos vinculados a venda ou OS.
  IF upper(v_transacao.tipo::text) = 'RECEITA' AND v_transacao.evento_financeiro_id IS NULL THEN
    IF v_transacao.ordemservicoid IS NOT NULL THEN
      SELECT round(
        greatest(coalesce(os.orcamentototal, 0), 0) +
        CASE
          WHEN os.acrescimo_financeiro_tipo = 'PORCENTAGEM' THEN
            greatest(coalesce(os.orcamentototal, 0), 0) * least(greatest(coalesce(os.acrescimo_financeiro_valor, 0), 0), 100) / 100
          WHEN os.acrescimo_financeiro_tipo = 'FIXO' THEN greatest(coalesce(os.acrescimo_financeiro_valor, 0), 0)
          ELSE 0
        END,
        2
      ) INTO v_total_devido
      FROM public.ordemservico os
      WHERE os.id = v_transacao.ordemservicoid;

      SELECT coalesce(round(sum(t.valor), 2), 0) INTO v_total_pago
      FROM public.transacao t
      WHERE t.ordemservicoid = v_transacao.ordemservicoid
        AND upper(t.tipo::text) = 'RECEITA'
        AND t.pendente = false
        AND t.is_deleted = false
        AND t.evento_financeiro_id IS NULL;

      UPDATE public.ordemservico
      SET status = CASE WHEN v_total_pago >= v_total_devido THEN 'CONCLUIDO' ELSE 'PAGAMENTO' END,
          datasaida = CASE WHEN v_total_pago >= v_total_devido THEN coalesce(datasaida, p_pago_em) ELSE datasaida END,
          updatedat = now()
      WHERE id = v_transacao.ordemservicoid;
    END IF;

    IF v_transacao.vendaid IS NOT NULL THEN
      SELECT round(
        greatest(coalesce(v.valortotal, 0), 0) +
        CASE
          WHEN v.acrescimo_financeiro_tipo = 'PORCENTAGEM' THEN
            greatest(coalesce(v.valortotal, 0), 0) * least(greatest(coalesce(v.acrescimo_financeiro_valor, 0), 0), 100) / 100
          WHEN v.acrescimo_financeiro_tipo = 'FIXO' THEN greatest(coalesce(v.acrescimo_financeiro_valor, 0), 0)
          ELSE 0
        END,
        2
      ) INTO v_total_devido
      FROM public.venda v
      WHERE v.id = v_transacao.vendaid;

      SELECT coalesce(round(sum(t.valor), 2), 0) INTO v_total_pago
      FROM public.transacao t
      WHERE t.vendaid = v_transacao.vendaid
        AND upper(t.tipo::text) = 'RECEITA'
        AND t.pendente = false
        AND t.is_deleted = false;

      UPDATE public.venda
      SET status = CASE WHEN v_total_pago >= v_total_devido THEN 'FINALIZADA' ELSE 'PAGAMENTO' END,
          updatedat = now()
      WHERE id = v_transacao.vendaid;
    END IF;
  END IF;

  RETURN jsonb_build_object(
    'id', v_transacao.id,
    'pago_em', v_transacao.pago_em,
    'vencimento_em', v_transacao.vencimento_em,
    'pendente', false
  );
END;
$$;

ALTER TABLE public.transacao_baixa_historico OWNER TO postgres;
ALTER FUNCTION public.baixar_transacao_pendente(bigint, timestamp with time zone, bigint, text, integer, integer, uuid) OWNER TO postgres;
ALTER FUNCTION public.proteger_transacao_baixa_historico() OWNER TO postgres;
REVOKE ALL ON TABLE public.transacao_baixa_historico FROM anon, authenticated;
REVOKE ALL ON FUNCTION public.baixar_transacao_pendente(bigint, timestamp with time zone, bigint, text, integer, integer, uuid) FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.transacao_baixa_historico TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.transacao_baixa_historico_id_seq TO service_role;
GRANT EXECUTE ON FUNCTION public.baixar_transacao_pendente(bigint, timestamp with time zone, bigint, text, integer, integer, uuid) TO service_role;

COMMIT;
