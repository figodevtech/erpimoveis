-- Estados que faltavam para a NFC-e e registro de inutilização de numeração.
--
-- 1) CONTINGENCIA e RESULTADO_INCERTO
--
-- A NFC-e é emitida com o cliente no balcão: quando a SEFAZ não responde, a
-- venda não pode parar. Isso cria dois estados que a NF-e nunca precisou:
--
--   CONTINGENCIA      documento emitido offline (tpEmis=9), aguardando
--                     transmissão quando a conexão voltar;
--   RESULTADO_INCERTO enviamos, a conexão caiu antes da resposta e NÃO sabemos
--                     se a SEFAZ autorizou.
--
-- RESULTADO_INCERTO é o estado mais importante dos dois. Sem ele, um timeout
-- vira "não autorizada" e o operador emite outra nota — duplicando um documento
-- que talvez já exista na SEFAZ. O caminho correto é consultar a chave.
--
-- 2) nfe_inutilizacao
--
-- Cancelamento e inutilização são coisas diferentes: cancelamento é evento
-- sobre nota autorizada; inutilização declara que uma FAIXA DE NÚMEROS nunca
-- virou documento. Faixa quebrada sem inutilizar é pendência com o fisco.
BEGIN;

ALTER TYPE public.enum_status_nfe ADD VALUE IF NOT EXISTS 'CONTINGENCIA';
ALTER TYPE public.enum_status_nfe ADD VALUE IF NOT EXISTS 'RESULTADO_INCERTO';

COMMIT;

BEGIN;

CREATE TABLE IF NOT EXISTS public.nfe_inutilizacao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresaid integer NOT NULL REFERENCES public.empresa(id) ON DELETE CASCADE,
  modelo public.enum_modelo_nfe NOT NULL,
  ambiente public.enum_ambiente_nfe NOT NULL,
  serie integer NOT NULL,
  ano smallint NOT NULL,
  numero_inicial integer NOT NULL CHECK (numero_inicial > 0),
  numero_final integer NOT NULL CHECK (numero_final > 0),
  justificativa text NOT NULL,
  status text NOT NULL DEFAULT 'PENDENTE',
  cstat text,
  motivo text,
  protocolo text,
  xml_enviado text,
  xml_retorno text,
  created_by uuid,
  createdat timestamp with time zone NOT NULL DEFAULT now(),
  updatedat timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT nfe_inutilizacao_faixa_valida CHECK (numero_final >= numero_inicial),
  CONSTRAINT nfe_inutilizacao_justificativa_minima CHECK (char_length(btrim(justificativa)) >= 15)
);

COMMENT ON TABLE public.nfe_inutilizacao IS
  'Faixas de numeracao declaradas como nao utilizadas. Nao confundir com cancelamento, que e evento sobre nota autorizada.';
COMMENT ON COLUMN public.nfe_inutilizacao.justificativa IS
  'Minimo de 15 caracteres, como exige o leiaute do servico NFeInutilizacao.';

-- Uma faixa homologada não pode ser declarada duas vezes para o mesmo
-- estabelecimento/modelo/série/ano.
CREATE UNIQUE INDEX IF NOT EXISTS nfe_inutilizacao_faixa_unica
  ON public.nfe_inutilizacao (empresaid, modelo, ambiente, serie, ano, numero_inicial, numero_final)
  WHERE status = 'HOMOLOGADA';

CREATE INDEX IF NOT EXISTS nfe_inutilizacao_empresa_modelo_idx
  ON public.nfe_inutilizacao (empresaid, modelo, ano DESC);

ALTER TABLE public.nfe_inutilizacao ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------
-- Idempotência da emissão por origem
--
-- Uma venda ou OS não pode ter duas notas TRANSMITIDAS do mesmo modelo. O
-- serviço já verifica antes de criar o rascunho, mas duas requisições
-- simultâneas passam pela verificação juntas — a trava transacional abaixo
-- serializa a ocupação da origem e fecha essa corrida no banco.
--
-- RASCUNHO fica de fora da guarda de propósito: rascunho duplicado é lixo
-- barato, tratado na camada de serviço, e incluí-lo aqui faria esta migration
-- quebrar em bases que já acumularam dois rascunhos para a mesma origem.
-- REJEITADA, CANCELADA e DENEGADA também ficam fora: não ocupam mais a origem.
-- ---------------------------------------------------------------------------
-- Bases anteriores já podem conter mais de uma nota transmitida para a mesma
-- origem. Esses documentos fiscais não podem ser cancelados ou excluídos por uma
-- migration. Os índices abaixo aceleram a guarda, sem reescrever o histórico.
CREATE INDEX IF NOT EXISTS nfe_origem_venda_modelo_transmitida_idx
  ON public.nfe (vendaid, modelo)
  WHERE vendaid IS NOT NULL
    AND is_deleted = false
    AND status IN ('ASSINADA', 'ENVIADA', 'AUTORIZADA', 'PENDENTE_ENVIO', 'CONTINGENCIA', 'RESULTADO_INCERTO');

CREATE INDEX IF NOT EXISTS nfe_origem_os_modelo_transmitida_idx
  ON public.nfe (ordemservicoid, modelo)
  WHERE ordemservicoid IS NOT NULL
    AND is_deleted = false
    AND status IN ('ASSINADA', 'ENVIADA', 'AUTORIZADA', 'PENDENTE_ENVIO', 'CONTINGENCIA', 'RESULTADO_INCERTO');

-- A trava por origem fecha a corrida entre duas transmissões sem exigir que o
-- legado já esteja limpo. Uma nota que já ocupava a origem pode avançar entre
-- estados transmitidos; a guarda atua quando uma nova nota tenta passar a ocupar.
CREATE OR REPLACE FUNCTION public.nfe_impedir_origem_transmitida_duplicada()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_status_ocupa boolean;
  v_status_anterior_ocupava boolean := false;
BEGIN
  v_status_ocupa := NOT coalesce(NEW.is_deleted, false)
    AND NEW.status IN (
      'ASSINADA', 'ENVIADA', 'AUTORIZADA', 'PENDENTE_ENVIO',
      'CONTINGENCIA', 'RESULTADO_INCERTO'
    );

  IF NOT v_status_ocupa THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    v_status_anterior_ocupava := NOT coalesce(OLD.is_deleted, false)
      AND OLD.status IN (
        'ASSINADA', 'ENVIADA', 'AUTORIZADA', 'PENDENTE_ENVIO',
        'CONTINGENCIA', 'RESULTADO_INCERTO'
      );

    -- Transições como ASSINADA -> ENVIADA -> AUTORIZADA não criam uma nova
    -- ocupação e precisam continuar funcionando inclusive no histórico legado.
    IF v_status_anterior_ocupava
       AND NEW.vendaid IS NOT DISTINCT FROM OLD.vendaid
       AND NEW.ordemservicoid IS NOT DISTINCT FROM OLD.ordemservicoid
       AND NEW.modelo IS NOT DISTINCT FROM OLD.modelo THEN
      RETURN NEW;
    END IF;
  END IF;

  IF NEW.vendaid IS NOT NULL THEN
    PERFORM pg_advisory_xact_lock(
      hashtextextended(format('nfe:venda:%s:modelo:%s', NEW.vendaid, NEW.modelo), 0)
    );

    IF EXISTS (
      SELECT 1
        FROM public.nfe existente
       WHERE existente.id <> coalesce(NEW.id, -1)
         AND existente.vendaid = NEW.vendaid
         AND existente.modelo = NEW.modelo
         AND existente.is_deleted = false
         AND existente.status IN (
           'ASSINADA', 'ENVIADA', 'AUTORIZADA', 'PENDENTE_ENVIO',
           'CONTINGENCIA', 'RESULTADO_INCERTO'
         )
    ) THEN
      RAISE EXCEPTION USING
        ERRCODE = '23505',
        MESSAGE = format(
          'A venda %s já possui uma nota transmitida do modelo %s.',
          NEW.vendaid,
          NEW.modelo
        ),
        CONSTRAINT = 'nfe_origem_venda_modelo_transmitida_idx';
    END IF;
  END IF;

  IF NEW.ordemservicoid IS NOT NULL THEN
    PERFORM pg_advisory_xact_lock(
      hashtextextended(format('nfe:os:%s:modelo:%s', NEW.ordemservicoid, NEW.modelo), 0)
    );

    IF EXISTS (
      SELECT 1
        FROM public.nfe existente
       WHERE existente.id <> coalesce(NEW.id, -1)
         AND existente.ordemservicoid = NEW.ordemservicoid
         AND existente.modelo = NEW.modelo
         AND existente.is_deleted = false
         AND existente.status IN (
           'ASSINADA', 'ENVIADA', 'AUTORIZADA', 'PENDENTE_ENVIO',
           'CONTINGENCIA', 'RESULTADO_INCERTO'
         )
    ) THEN
      RAISE EXCEPTION USING
        ERRCODE = '23505',
        MESSAGE = format(
          'A OS %s já possui uma nota transmitida do modelo %s.',
          NEW.ordemservicoid,
          NEW.modelo
        ),
        CONSTRAINT = 'nfe_origem_os_modelo_transmitida_idx';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_nfe_origem_transmitida_unica ON public.nfe;
CREATE TRIGGER trg_nfe_origem_transmitida_unica
BEFORE INSERT OR UPDATE OF vendaid, ordemservicoid, modelo, status, is_deleted
ON public.nfe
FOR EACH ROW
EXECUTE FUNCTION public.nfe_impedir_origem_transmitida_duplicada();

-- ---------------------------------------------------------------------------
-- Os dois estados novos SEGURAM o número
--
-- RESULTADO_INCERTO pode já existir na SEFAZ — devolver o número para a fila
-- levaria a próxima nota a sair com número duplicado (rejeição 539).
-- CONTINGENCIA é documento que já foi entregue ao consumidor em papel e será
-- transmitido depois: o número está comprometido.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.nfe_liberar_numero(p_nfe_id bigint, p_motivo text DEFAULT NULL)
RETURNS boolean
LANGUAGE plpgsql
AS $$
DECLARE
  v_nfe public.nfe%ROWTYPE;
  v_config public.nfe_config%ROWTYPE;
BEGIN
  SELECT * INTO v_nfe FROM public.nfe WHERE id = p_nfe_id FOR UPDATE;
  IF NOT FOUND OR NOT v_nfe.numero_definitivo OR v_nfe.numero IS NULL THEN
    RETURN false;
  END IF;

  IF v_nfe.status IN (
    'AUTORIZADA', 'DENEGADA', 'CANCELADA', 'ENVIADA', 'ASSINADA',
    'PENDENTE_ENVIO', 'CONTINGENCIA', 'RESULTADO_INCERTO'
  ) THEN
    RETURN false;
  END IF;

  SELECT * INTO v_config
    FROM public.nfe_config
   WHERE empresaid = v_nfe.empresaid
     AND modelo = v_nfe.modelo
   ORDER BY id
   LIMIT 1
   FOR UPDATE;

  IF NOT FOUND THEN
    RETURN false;
  END IF;

  UPDATE public.nfe
     SET numero_definitivo = false,
         updatedat = now()
   WHERE id = p_nfe_id;

  INSERT INTO public.nfe_numero_liberado (config_id, serie, numero, motivo)
  VALUES (v_config.id, v_nfe.serie, v_nfe.numero, p_motivo)
  ON CONFLICT ON CONSTRAINT nfe_numero_liberado_unico DO NOTHING;

  RETURN true;
END;
$$;

COMMIT;
