-- Guarda o que o ERP enviou ao Mercado Livre ao validar e ao publicar um anúncio.
-- Sem isso, uma recusa como "user has not mode me1" não pode ser reconstituída
-- depois: o payload e a resposta do calculador de envios se perdem na requisição.
-- Nenhum token trafega aqui; os payloads do Mercado Livre não os contêm.
create table if not exists public.mercadolivre_listing_payload_log (
  id bigint generated by default as identity primary key,
  empresa_id bigint not null references public.empresa(id) on delete cascade,
  produto_id bigint references public.produto(id) on delete set null,
  ml_user_id bigint,
  ml_item_id text,
  operacao text not null check (operacao in ('VALIDACAO', 'CRIACAO')),
  status text not null check (status in ('SUCESSO', 'AVISO', 'ERRO')),
  category_id text,
  listing_type_id text,
  shipping_mode text,
  logistic_type text,
  free_shipping boolean,
  http_status integer,
  -- Corpo exato de POST /items (e de POST /items/validate, que usa o mesmo).
  item_payload jsonb not null default '{}'::jsonb,
  -- Contexto e resposta de POST /users/{id}/shipping_modes, origem das recusas de envio.
  shipping_modes_request jsonb,
  shipping_modes_response jsonb,
  response jsonb,
  warnings jsonb not null default '[]'::jsonb,
  error text,
  created_at timestamptz not null default now()
);

create index if not exists mercadolivre_listing_payload_log_empresa_created_idx
  on public.mercadolivre_listing_payload_log (empresa_id, created_at desc);

create index if not exists mercadolivre_listing_payload_log_produto_idx
  on public.mercadolivre_listing_payload_log (produto_id, created_at desc);

alter table public.mercadolivre_listing_payload_log enable row level security;
