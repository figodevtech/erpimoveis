-- Boleto do terceirizado: varias despesas da OS num lancamento so.
--
-- PROBLEMA
-- Numa OS, cada servico terceirizado ganha sua propria despesa — e assim tem que
-- ser: e o que sustenta a rentabilidade por servico e a linha 4.3 da DRE. Mas o
-- terceirizado que fez dois servicos cobra os dois num boleto so, e ai o sistema
-- obrigava uma transacao por despesa. O caixa mostrava duas linhas onde saiu um
-- pagamento.
--
-- Pior: se esse boleto fosse parcelado nao havia saida nenhuma. O caminho
-- "Lancar no financeiro" da despesa recusa parcelamento ("Um evento financeiro
-- deve gerar uma unica transacao"), entao para lancar 5x o operador tinha que
-- abandonar o caminho da OS e criar uma despesa avulsa — perdendo o vinculo com
-- o servico, que era justamente o ponto.
--
-- Mesma filosofia da 20260811220000: o caixa nao registra documentos, registra
-- dinheiro. Se saiu um boleto, saiu um boleto — em 1x ou em 5x.
--
-- MODELO
-- Os N eventos e as P parcelas passam a pertencer a um grupo, `lancamento_de_
-- eventos`. E o mesmo desenho de `transacao_parcelamento` e `pagamento_multiplo`:
-- uma tabela-grupo, e as linhas sao quem aponta para ela.
--
--   eventos_financeiros (N)  -->  lancamento_de_eventos  <--  transacao (P)
--
-- O grupo e o que torna "tudo-ou-nada" expressavel. Com vinculo direto nao
-- existe "a" transacao que quita a despesa quando sao 5 parcelas, e qualquer
-- parcela eleita como ancora tornaria a reversao incoerente: excluir a parcela 1
-- devolveria as despesas para prevista com 4 parcelas de divida ainda no caixa.
--
-- Num lancamento por grupo, `transacao.evento_financeiro_id` e
-- `eventos_financeiros.transacaoid` ficam NULOS — quem liga e o grupo. O caminho
-- antigo (1 despesa -> 1 transacao) continua existindo e serve os dados ja
-- gravados e os eventos de RECEITA. Nao ha backfill.
--
-- CUIDADO QUE ESTA MIGRATION PRECISA TER
-- 1. A transacao do grupo tem `evento_financeiro_id` NULO, e era essa coluna a
--    primeira condicao da lista de exclusao de `sincronizar_eventos_financeiros_
--    transacao` — a lista que impede a baixa de virar custo novo, ja que o custo
--    foi reconhecido pelo evento SERVICO:DESPESA. Sem acrescentar `lancamento_id`
--    ali, a DRE contaria o mesmo custo DUAS VEZES, sem erro nenhum na tela.
--    (`ordemservicoid is not null` ja cobriria, porque as parcelas sempre tem OS;
--    a condicao nova e protecao redundante e, sobretudo, documentacao.)
-- 2. `idx_eventos_financeiros_transacao` impedia N eventos por transacao, mas
--    tambem e o que garante UMA linha no upsert de evento AVULSO (ver o
--    comentario em 20260817140000). Por isso ele e ESCOPADO para
--    source_type='TRANSACAO', nao removido.

BEGIN;

-- ------------------------------------------------------------------ o grupo
CREATE TABLE IF NOT EXISTS public.lancamento_de_eventos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordemservicoid integer NOT NULL
    REFERENCES public.ordemservico(id) ON DELETE CASCADE,
  -- A descricao sem o sufixo " - Parcela i/N", como em transacao_parcelamento:
  -- se todas as parcelas forem renomeadas, nao ha de onde reler a base sem
  -- depender de uma delas estar intacta.
  descricao text NOT NULL,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

