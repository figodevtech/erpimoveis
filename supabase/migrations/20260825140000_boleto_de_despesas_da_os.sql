-- --------------------------------------------------------- a guarda da DRE
-- Identica a versao de 20260817140000, com UMA condicao a mais na lista de
-- exclusao: `lancamento_id is not null`. Ver o CUIDADO 1 no cabecalho — e esta
-- linha que impede o custo do servico terceirizado de ser contado duas vezes.
CREATE OR REPLACE FUNCTION public.sincronizar_eventos_financeiros_transacao(p_transacaoid bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
declare
  v_tx public.transacao%ROWTYPE;
  v_linha_id integer;
  v_exclui boolean := false;
  v_natureza text;
  v_natureza_dre text;
begin
  select * into v_tx from public.transacao where id = p_transacaoid;
  if not found then return; end if;

  -- Liquidacao de algo ja reconhecido, compra que vira estoque, saldo de
  -- abertura migrado, antecipacao de recebiveis ou movimentacao de tesouraria:
  -- nao e resultado novo. Se ja existir evento, encerra.
  --
  -- SAQUE e DEPOSITO entram nesta lista pelo que sao: dinheiro mudando de lugar
  -- entre o caixa e a conta. Nao dependem da conta do plano — um saque numa
  -- conta de despesa continua sendo saque. Quando um gasto de verdade for
  -- lancado como saque, o conserto e trocar o tipo do lancamento, nao fazer a
  -- DRE adivinhar.
  --
  -- `lancamento_id` e a parcela de um boleto que quita despesas de OS. O custo
  -- ja foi reconhecido pelos eventos SERVICO:DESPESA; a parcela e so a saida de
  -- caixa. Sem esta condicao a DRE contaria o custo duas vezes.
  if v_tx.is_deleted
     or v_tx.evento_financeiro_id is not null
     or v_tx.lancamento_id is not null
     or v_tx.ordemservicoid is not null
     or v_tx.vendaid is not null
     or v_tx.entrada_id is not null
     or v_tx.usoconsumo_entrada_id is not null
     or v_tx.origem = 'ORIGEM_MIGRACAO'
     or coalesce(v_tx.eh_adiantamento, false)
     or v_tx.adiantamento_id is not null
     or upper(v_tx.tipo::text) in ('SAQUE', 'DEPOSITO') then
    update public.eventos_financeiros
       set status = 'CANCELADO', updated_at = now()
     where source_type = 'TRANSACAO' and source_id = p_transacaoid and status = 'ATIVO';
    return;
  end if;

  select mp.linha_id, mp.exclui_do_resultado
    into v_linha_id, v_exclui
    from public.planosdeconta pc
    join public.dre_mapeamento mp
      on mp.origem_tipo = 'PLANO_GRUPO' and mp.origem_id = pc.grupo_id and mp.ativo
   where pc.id = v_tx.plano_de_conta_id
   limit 1;

  if coalesce(v_exclui, false) then
    update public.eventos_financeiros
       set status = 'CANCELADO', updated_at = now()
     where source_type = 'TRANSACAO' and source_id = p_transacaoid and status = 'ATIVO';
    return;
  end if;

  v_natureza := case when upper(v_tx.tipo::text) = 'RECEITA' then 'RECEITA' else 'DESPESA' end;

  select dl.natureza_dre into v_natureza_dre
    from public.dre_linha dl where dl.id = v_linha_id;

  v_natureza_dre := coalesce(v_natureza_dre,
    case when v_natureza = 'RECEITA' then 'RECEITA' else 'DESPESA' end);

  -- `natureza` faz parte da chave do `on conflict`, e o indice unico escopado
  -- garante no maximo um evento AVULSO por transacao. Se a natureza mudou, o
  -- upsert nao reconheceria a linha existente e tentaria inserir uma segunda,
  -- batendo naquele indice. Realinhar antes deixa o upsert seguir normalmente.
  update public.eventos_financeiros
     set natureza = v_natureza, updated_at = now()
   where source_type = 'TRANSACAO'
     and source_id = p_transacaoid
     and status <> 'CONVERTIDO'
     and natureza is distinct from v_natureza;

  insert into public.eventos_financeiros
    (ordemservicoid, source_type, source_id, origem, natureza, natureza_dre,
     chave_origem, descricao, detalhe, valor, competencia_em, dre_linha_id,
     centro_custo_id, transacaoid, dados_snapshot, pode_gerar_transacao, status)
  values
    (null, 'TRANSACAO', p_transacaoid, 'AVULSO', v_natureza, v_natureza_dre,
     'TRANSACAO', coalesce(nullif(v_tx.descricao, ''), 'Lancamento #' || p_transacaoid),
     nullif(v_tx.plano_de_conta, ''), round(coalesce(v_tx.valor, 0), 2),
     coalesce(v_tx.competencia_em, v_tx.data), v_linha_id,
     v_tx.centro_custo_id, p_transacaoid,
     jsonb_build_object('categoria', v_tx.categoria, 'sem_classificacao', v_linha_id is null),
     false, 'ATIVO')
  on conflict (source_type, source_id, origem, chave_origem, natureza)
    where ordemservicoid is null
  do update set valor = excluded.valor,
                descricao = excluded.descricao,
                detalhe = excluded.detalhe,
                competencia_em = excluded.competencia_em,
                dre_linha_id = excluded.dre_linha_id,
                natureza_dre = excluded.natureza_dre,
                centro_custo_id = excluded.centro_custo_id,
                dados_snapshot = excluded.dados_snapshot,
                status = 'ATIVO',
                updated_at = now()
  where public.eventos_financeiros.status <> 'CONVERTIDO';
end;
$function$;

COMMENT ON FUNCTION public.sincronizar_eventos_financeiros_transacao(bigint) IS
  'Evento de resultado de uma transacao avulsa. Ignora o que e liquidacao de algo ja reconhecido (OS, venda, evento, lancamento de despesas de OS), compra que vira estoque, saldo de abertura migrado, antecipacao de recebiveis e movimentacao de tesouraria (saque e deposito).';
-- ------------------------------------------------------------- registrar
-- O TS prepara e valida, esta funcao persiste. Existe porque as tres escritas
-- (grupo, parcelas, eventos) precisam ser UMA transacao: pelo PostgREST seriam
-- tres chamadas, e uma falha no meio deixaria parcelas no caixa sem despesa
-- nenhuma convertida. Mesma divisao de trabalho de registrar_pagamento_multiplo.
CREATE OR REPLACE FUNCTION public.registrar_lancamento_de_eventos(p_payload jsonb)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_os_id integer := nullif(p_payload->>'ordemservicoid', '')::integer;
  v_created_by uuid := nullif(p_payload->>'created_by', '')::uuid;
  v_pendente boolean := coalesce((p_payload->>'pendente')::boolean, true);
  v_data timestamptz := coalesce(nullif(p_payload->>'data', '')::timestamptz, now());
  v_metodo public.metodo_pagamento := nullif(p_payload->>'metodopagamento', '')::public.metodo_pagamento;
  v_categoria text := coalesce(nullif(p_payload->>'categoria', ''), 'NAO RELACIONADO');
  v_categoria_id integer := nullif(p_payload->>'categoria_id', '')::integer;
  v_plano_id integer := nullif(p_payload->>'plano_de_conta_id', '')::integer;
  v_centro_id integer := nullif(p_payload->>'centro_custo_id', '')::integer;
  v_fornecedor_id integer := nullif(p_payload->>'fornecedor_id', '')::integer;
  v_banco_id bigint := nullif(p_payload->>'banco_id', '')::bigint;
  v_nome text := coalesce(nullif(btrim(p_payload->>'nomepagador'), ''), 'Despesa interna');
  v_cpfcnpj text := coalesce(nullif(btrim(p_payload->>'cpfcnpjpagador'), ''), 'NAO INFORMADO');
  v_ids bigint[];
  v_qtd integer;
  v_soma_eventos numeric(14,2);
  v_soma_linhas numeric(14,2);
  v_maus text;
  v_grupo_id bigint;
  v_descricao_grupo text;
  v_descricao text;
  v_total_parcelas integer;
  v_parcela record;
BEGIN
  IF v_os_id IS NULL THEN
    RAISE EXCEPTION 'Informe a ordem de servico do lancamento.' USING ERRCODE = 'P0001';
  END IF;
  IF jsonb_typeof(p_payload->'eventos_ids') <> 'array'
     OR jsonb_array_length(p_payload->'eventos_ids') = 0 THEN
    RAISE EXCEPTION 'Selecione ao menos uma despesa para lancar.' USING ERRCODE = 'P0001';
  END IF;
  IF jsonb_typeof(p_payload->'linhas') <> 'array'
     OR jsonb_array_length(p_payload->'linhas') = 0 THEN
    RAISE EXCEPTION 'Informe as parcelas do lancamento.' USING ERRCODE = 'P0001';
  END IF;

  SELECT array_agg(DISTINCT item::text::bigint)
    INTO v_ids
    FROM jsonb_array_elements(p_payload->'eventos_ids') AS item;

  -- Trava todas as despesas ate o fim desta transacao: duas telas lancando
  -- grupos que dividem uma despesa serializam aqui, e a segunda encontra o
  -- vinculo ja preenchido.
  PERFORM 1 FROM public.eventos_financeiros WHERE id = ANY (v_ids) FOR UPDATE;

  SELECT count(*), round(coalesce(sum(e.valor), 0), 2)
    INTO v_qtd, v_soma_eventos
    FROM public.eventos_financeiros e WHERE e.id = ANY (v_ids);

  IF v_qtd <> coalesce(array_length(v_ids, 1), 0) THEN
    RAISE EXCEPTION 'Uma ou mais despesas selecionadas nao existem mais.' USING ERRCODE = 'P0002';
  END IF;

  SELECT string_agg(e.id::text, ', ' ORDER BY e.id) INTO v_maus
    FROM public.eventos_financeiros e
   WHERE e.id = ANY (v_ids)
     AND (e.status <> 'ATIVO' OR e.transacaoid IS NOT NULL OR e.lancamento_id IS NOT NULL);
  IF v_maus IS NOT NULL THEN
    RAISE EXCEPTION 'Despesa(s) % ja foi(ram) lancada(s) no financeiro ou cancelada(s).', v_maus
      USING ERRCODE = 'P0001';
  END IF;

  SELECT string_agg(e.id::text, ', ' ORDER BY e.id) INTO v_maus
    FROM public.eventos_financeiros e
   WHERE e.id = ANY (v_ids) AND NOT e.pode_gerar_transacao;
  IF v_maus IS NOT NULL THEN
    RAISE EXCEPTION 'Despesa(s) % e(sao) lancamento(s) automatico(s) e nao gera(m) transacao.', v_maus
      USING ERRCODE = 'P0001';
  END IF;

  SELECT string_agg(e.id::text, ', ' ORDER BY e.id) INTO v_maus
    FROM public.eventos_financeiros e
   WHERE e.id = ANY (v_ids)
     AND (e.ordemservicoid IS DISTINCT FROM v_os_id OR e.natureza <> 'DESPESA');
  IF v_maus IS NOT NULL THEN
    RAISE EXCEPTION 'Despesa(s) % nao pertence(m) a esta OS ou nao e(sao) despesa.', v_maus
      USING ERRCODE = 'P0001';
  END IF;

  SELECT round(coalesce(sum((item->>'valor')::numeric), 0), 2)
    INTO v_soma_linhas
    FROM jsonb_array_elements(p_payload->'linhas') AS item;

  IF v_soma_linhas <> v_soma_eventos THEN
    RAISE EXCEPTION 'A soma das parcelas (%) difere da soma das despesas selecionadas (%).',
      v_soma_linhas, v_soma_eventos USING ERRCODE = 'P0001';
  END IF;

  v_descricao_grupo := coalesce(
    nullif(btrim(p_payload->>'descricao'), ''),
    'Despesas da OS #' || v_os_id);

  INSERT INTO public.lancamento_de_eventos (ordemservicoid, descricao, created_by)
  VALUES (v_os_id, v_descricao_grupo, v_created_by)
  RETURNING id INTO v_grupo_id;

  SELECT max((item->>'total_parcelas')::integer) INTO v_total_parcelas
    FROM jsonb_array_elements(p_payload->'linhas') AS item;
  v_total_parcelas := greatest(coalesce(v_total_parcelas, 1), 1);

  FOR v_parcela IN
    SELECT (item->>'parcela')::integer AS numero,
           round((item->>'valor')::numeric, 2) AS valor,
           round(coalesce((item->>'valor_liquido')::numeric,
                          (item->>'valor')::numeric), 2) AS valor_liquido,
           nullif(item->>'vencimento_em', '') AS vencimento
      FROM jsonb_array_elements(p_payload->'linhas') AS item
     ORDER BY 1
  LOOP
    v_descricao := v_descricao_grupo;
    IF v_total_parcelas > 1 THEN
      v_descricao := v_descricao || ' - Parcela ' || v_parcela.numero || '/' || v_total_parcelas;
    END IF;

    INSERT INTO public.transacao (
      descricao, valor, "valorLiquido", data, vencimento_em, metodopagamento,
      categoria, categoria_id, plano_de_conta_id, centro_custo_id, tipo,
      fornecedor_id, banco_id, nomepagador, cpfcnpjpagador, pendente, pago_em,
      ordemservicoid, lancamento_id, created_by, baixado_por
    ) VALUES (
      v_descricao,
      v_parcela.valor,
      v_parcela.valor_liquido,
      coalesce(v_parcela.vencimento::timestamptz, v_data),
      v_parcela.vencimento::timestamptz,
      v_metodo, v_categoria, v_categoria_id, v_plano_id, v_centro_id,
      'DESPESA'::public.tipos_transacao,
      v_fornecedor_id,
      CASE WHEN v_pendente THEN NULL ELSE v_banco_id END,
      v_nome, v_cpfcnpj,
      v_pendente,
      CASE WHEN v_pendente THEN NULL ELSE v_data END,
      v_os_id, v_grupo_id, v_created_by,
      CASE WHEN v_pendente THEN NULL ELSE v_created_by END
    );
  END LOOP;

  UPDATE public.eventos_financeiros
     SET status = 'CONVERTIDO', lancamento_id = v_grupo_id, updated_at = now()
   WHERE id = ANY (v_ids);

  RETURN v_grupo_id;
END;
$function$;

