  FOREIGN KEY (versao_atual_id)
  REFERENCES public.fiscal_sped_versao(id)
  ON DELETE RESTRICT;

CREATE TABLE public.fiscal_sped_validacao_execucao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competencia_id bigint NOT NULL
    REFERENCES public.fiscal_sped_competencia(id) ON DELETE RESTRICT,
  versao_id bigint
    REFERENCES public.fiscal_sped_versao(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'PROCESSANDO',
  context_hash text NOT NULL,
  quantidade_bloqueios integer NOT NULL DEFAULT 0,
  quantidade_erros integer NOT NULL DEFAULT 0,
  quantidade_avisos integer NOT NULL DEFAULT 0,
  quantidade_informacoes integer NOT NULL DEFAULT 0,
  iniciado_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  iniciado_at timestamptz NOT NULL DEFAULT now(),
  concluido_at timestamptz,
  CONSTRAINT fiscal_sped_validacao_status_chk
    CHECK (status IN ('PROCESSANDO', 'CONCLUIDA', 'FALHOU')),
  CONSTRAINT fiscal_sped_validacao_hash_chk CHECK (context_hash ~ '^[a-f0-9]{64}$'),
  CONSTRAINT fiscal_sped_validacao_contadores_chk CHECK (
    quantidade_bloqueios >= 0
    AND quantidade_erros >= 0
    AND quantidade_avisos >= 0
    AND quantidade_informacoes >= 0
  )
);

CREATE INDEX fiscal_sped_validacao_competencia_idx
  ON public.fiscal_sped_validacao_execucao(competencia_id, iniciado_at DESC);
CREATE INDEX fiscal_sped_validacao_versao_idx
  ON public.fiscal_sped_validacao_execucao(versao_id, iniciado_at DESC)
  WHERE versao_id IS NOT NULL;

CREATE TABLE public.fiscal_sped_inconsistencia (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execucao_id bigint NOT NULL
    REFERENCES public.fiscal_sped_validacao_execucao(id) ON DELETE RESTRICT,
  severidade text NOT NULL,
  codigo text NOT NULL,
  registro_efd text,
  campo_efd text,
  tabela_origem text,
  registro_origem_id text,
  referencia_origem jsonb NOT NULL DEFAULT '{}'::jsonb,
  mensagem text NOT NULL,
  status text NOT NULL DEFAULT 'ABERTA',
  resolucao text,
  resolvida_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  resolvida_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_inconsistencia_severidade_chk
    CHECK (severidade IN ('BLOQUEIO', 'ERRO', 'AVISO', 'INFORMACAO')),
