CREATE TABLE public.fiscal_sped_competencia (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL
    REFERENCES public.empresa(id) ON DELETE RESTRICT,
  competencia date NOT NULL,
  status text NOT NULL DEFAULT 'ABERTA',
  versao_atual_id bigint,
  lock_version integer NOT NULL DEFAULT 0,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  fechada_at timestamptz,
  fechada_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  CONSTRAINT fiscal_sped_competencia_mes_chk
    CHECK (competencia = date_trunc('month', competencia)::date),
  CONSTRAINT fiscal_sped_competencia_status_chk
    CHECK (status IN ('ABERTA', 'EM_VALIDACAO', 'COM_ERROS', 'APTA', 'FECHADA')),
  CONSTRAINT fiscal_sped_competencia_lock_chk CHECK (lock_version >= 0),
  CONSTRAINT fiscal_sped_competencia_fechamento_chk CHECK (
    (status = 'FECHADA' AND fechada_at IS NOT NULL AND fechada_by IS NOT NULL)
    OR status <> 'FECHADA'
  ),
  UNIQUE (empresa_id, competencia)
);

CREATE INDEX fiscal_sped_competencia_status_idx
  ON public.fiscal_sped_competencia(empresa_id, status, competencia DESC);

CREATE TABLE public.fiscal_sped_versao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competencia_id bigint NOT NULL
    REFERENCES public.fiscal_sped_competencia(id) ON DELETE RESTRICT,
  numero integer NOT NULL,
  finalidade text NOT NULL,
  status text NOT NULL DEFAULT 'RASCUNHO',
  versao_anterior_id bigint
    REFERENCES public.fiscal_sped_versao(id) ON DELETE RESTRICT,
  leiaute text NOT NULL,
  guia_pratico text NOT NULL,
  motor_versao text NOT NULL,
  git_commit text NOT NULL,
  source_cutoff_at timestamptz NOT NULL,
  context_hash text NOT NULL,
  motivo_abertura text,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  validated_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  closed_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  validated_at timestamptz,
  closed_at timestamptz,
  substituted_at timestamptz,
  CONSTRAINT fiscal_sped_versao_numero_chk CHECK (numero > 0),
  CONSTRAINT fiscal_sped_versao_finalidade_chk
    CHECK (finalidade IN ('ORIGINAL', 'RETIFICADORA')),
  CONSTRAINT fiscal_sped_versao_status_chk
    CHECK (status IN ('RASCUNHO', 'VALIDADA', 'FECHADA', 'SUBSTITUIDA')),
  CONSTRAINT fiscal_sped_versao_leiaute_chk CHECK (leiaute ~ '^[0-9]{3}$'),
  CONSTRAINT fiscal_sped_versao_git_chk CHECK (git_commit ~ '^[a-f0-9]{7,64}$'),
  CONSTRAINT fiscal_sped_versao_hash_chk CHECK (context_hash ~ '^[a-f0-9]{64}$'),
  CONSTRAINT fiscal_sped_versao_validacao_chk CHECK (
    (status IN ('VALIDADA', 'FECHADA', 'SUBSTITUIDA') AND validated_at IS NOT NULL)
    OR status = 'RASCUNHO'
  ),
  CONSTRAINT fiscal_sped_versao_fechamento_chk CHECK (
    (status IN ('FECHADA', 'SUBSTITUIDA') AND closed_at IS NOT NULL AND closed_by IS NOT NULL)
    OR status IN ('RASCUNHO', 'VALIDADA')
  ),
  UNIQUE (competencia_id, numero)
);

CREATE UNIQUE INDEX fiscal_sped_versao_editavel_uk
  ON public.fiscal_sped_versao(competencia_id)
  WHERE status IN ('RASCUNHO', 'VALIDADA');
CREATE INDEX fiscal_sped_versao_competencia_status_idx
  ON public.fiscal_sped_versao(competencia_id, status, numero DESC);

ALTER TABLE public.fiscal_sped_competencia
