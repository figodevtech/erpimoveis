CREATE TABLE public.fiscal_sped_cadastro_snapshot (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  versao_id bigint NOT NULL
    REFERENCES public.fiscal_sped_versao(id) ON DELETE RESTRICT,
  tipo text NOT NULL,
  codigo text NOT NULL,
  documento_tipo text NOT NULL DEFAULT 'SEM_DOCUMENTO',
  documento_canonico text,
  documento_original text,
  payload jsonb NOT NULL,
  source_refs jsonb NOT NULL DEFAULT '[]'::jsonb,
  payload_sha256 text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_cadastro_tipo_chk CHECK (
    tipo IN ('EMPRESA', 'CONFIG', 'CONTABILISTA', 'PARTICIPANTE', 'ITEM', 'UNIDADE')
  ),
  CONSTRAINT fiscal_sped_cadastro_codigo_chk
    CHECK (nullif(btrim(codigo), '') IS NOT NULL AND position('|' IN codigo) = 0),
  CONSTRAINT fiscal_sped_cadastro_documento_chk CHECK (
    (documento_tipo = 'SEM_DOCUMENTO' AND documento_canonico IS NULL)
    OR (documento_tipo = 'CPF' AND documento_canonico ~ '^[0-9]{11}$')
    OR (documento_tipo = 'CNPJ'
      AND documento_canonico = public.fiscal_cnpj_normalizar(documento_canonico)
      AND public.fiscal_cnpj_valido(documento_canonico))
    OR (documento_tipo = 'ID_EXTERIOR'
      AND nullif(btrim(documento_canonico), '') IS NOT NULL
      AND position('|' IN documento_canonico) = 0)
  ),
  CONSTRAINT fiscal_sped_cadastro_hash_chk CHECK (payload_sha256 ~ '^[a-f0-9]{64}$'),
  UNIQUE (versao_id, tipo, codigo)
);

CREATE INDEX fiscal_sped_cadastro_documento_idx
  ON public.fiscal_sped_cadastro_snapshot(versao_id, documento_canonico)
  WHERE documento_canonico IS NOT NULL;

