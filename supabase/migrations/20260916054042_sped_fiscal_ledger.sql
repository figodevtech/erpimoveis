  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_inventario_fechamento_status_chk
    CHECK (status IN ('RASCUNHO', 'EM_VALIDACAO', 'APROVADO', 'CANCELADO')),
  CONSTRAINT fiscal_inventario_fechamento_aprovacao_chk CHECK (
    (status = 'APROVADO' AND approved_by IS NOT NULL AND approved_at IS NOT NULL)
    OR status <> 'APROVADO'
  ),
  UNIQUE (empresa_id, data_inventario, motivo)
);

CREATE TABLE public.fiscal_inventario_item (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventario_id bigint NOT NULL
    REFERENCES public.fiscal_inventario_fechamento(id) ON DELETE RESTRICT,
  produto_id integer REFERENCES public.produto(id) ON DELETE RESTRICT,
  item_config_id bigint REFERENCES public.fiscal_sped_item_config(id) ON DELETE RESTRICT,
  codigo_item text NOT NULL,
  unidade text NOT NULL,
  quantidade numeric(20,6) NOT NULL,
  valor_unitario numeric(20,6) NOT NULL,
  valor_total numeric(18,2) NOT NULL,
  indicador_propriedade text NOT NULL,
  participante_codigo text,
  participante_documento_tipo text NOT NULL DEFAULT 'SEM_DOCUMENTO',
  participante_documento_canonico text,
  participante_documento_original text,
  cst_icms text,
  aliquota_icms_interna numeric(9,6),
  base_icms numeric(18,2),
  valor_icms numeric(18,2),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_inventario_item_quantidades_chk CHECK (
    quantidade >= 0 AND valor_unitario >= 0 AND valor_total >= 0
  ),
  CONSTRAINT fiscal_inventario_item_propriedade_chk
    CHECK (indicador_propriedade IN ('PROPRIO', 'TERCEIRO_EM_POSSE', 'PROPRIO_EM_TERCEIRO')),
  CONSTRAINT fiscal_inventario_item_participante_chk CHECK (
    (participante_documento_tipo = 'SEM_DOCUMENTO'
      AND participante_documento_canonico IS NULL)
    OR (participante_documento_tipo = 'CPF'
      AND participante_documento_canonico ~ '^[0-9]{11}$')
    OR (participante_documento_tipo = 'CNPJ'
      AND participante_documento_canonico = public.fiscal_cnpj_normalizar(participante_documento_canonico)
      AND public.fiscal_cnpj_valido(participante_documento_canonico))
    OR (participante_documento_tipo = 'ID_EXTERIOR'
      AND nullif(btrim(participante_documento_canonico), '') IS NOT NULL
      AND position('|' IN participante_documento_canonico) = 0)
  ),
  CONSTRAINT fiscal_inventario_item_aliquota_chk
    CHECK (aliquota_icms_interna IS NULL OR aliquota_icms_interna >= 0),
  CONSTRAINT fiscal_inventario_item_icms_chk CHECK (
    (base_icms IS NULL OR base_icms >= 0) AND (valor_icms IS NULL OR valor_icms >= 0)
  ),
  UNIQUE NULLS NOT DISTINCT (
    inventario_id, codigo_item, indicador_propriedade, participante_codigo
  )
);

CREATE INDEX fiscal_inventario_item_inventario_idx
  ON public.fiscal_inventario_item(inventario_id, codigo_item, id);

ALTER TABLE public.fiscal_sped_config
  ADD COLUMN inventario_fechamento_id bigint
    REFERENCES public.fiscal_inventario_fechamento(id) ON DELETE RESTRICT;

COMMIT;
