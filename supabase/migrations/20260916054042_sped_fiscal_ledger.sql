    CHECK (status IN ('ABERTA', 'RECONHECIDA', 'RESOLVIDA')),
  CONSTRAINT fiscal_sped_inconsistencia_reconhecimento_chk CHECK (
    status <> 'RECONHECIDA'
    OR severidade IN ('AVISO', 'INFORMACAO')
  ),
  CONSTRAINT fiscal_sped_inconsistencia_resolucao_chk CHECK (
    (status = 'ABERTA' AND resolvida_at IS NULL AND resolvida_by IS NULL)
    OR (status <> 'ABERTA' AND resolvida_at IS NOT NULL AND resolvida_by IS NOT NULL)
  )
);

CREATE INDEX fiscal_sped_inconsistencia_execucao_idx
  ON public.fiscal_sped_inconsistencia(execucao_id, severidade, status, id);
CREATE INDEX fiscal_sped_inconsistencia_origem_idx
  ON public.fiscal_sped_inconsistencia(tabela_origem, registro_origem_id)
  WHERE tabela_origem IS NOT NULL;

CREATE TABLE public.fiscal_sped_documento_snapshot (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  versao_id bigint NOT NULL
    REFERENCES public.fiscal_sped_versao(id) ON DELETE RESTRICT,
  fonte_tipo text NOT NULL,
  fonte_tabela text NOT NULL,
  fonte_id text NOT NULL,
  operacao text NOT NULL,
  chave_acesso text NOT NULL,
  modelo text NOT NULL,
  codigo_situacao text NOT NULL,
  data_emissao_civil date NOT NULL,
  data_emissao_original text,
  data_emissao_offset text,
  data_emissao_instante_utc timestamptz,
  data_escrituracao_civil date,
  participante_codigo text,
  participante_documento_tipo text NOT NULL DEFAULT 'SEM_DOCUMENTO',
  participante_documento_canonico text,
  participante_documento_original text,
  xml_sha256 text NOT NULL,
  payload jsonb NOT NULL,
  source_refs jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_documento_fonte_tipo_chk
    CHECK (fonte_tipo IN ('NFE_EMITIDA', 'NFE_RECEBIDA', 'NFC_E', 'OUTRO')),
  CONSTRAINT fiscal_sped_documento_operacao_chk
    CHECK (operacao IN ('ENTRADA', 'SAIDA')),
  CONSTRAINT fiscal_sped_documento_chave_chk
    CHECK (chave_acesso ~ '^[0-9]{44}$'),
  CONSTRAINT fiscal_sped_documento_xml_hash_chk
    CHECK (xml_sha256 ~ '^[a-f0-9]{64}$'),
  CONSTRAINT fiscal_sped_documento_offset_chk CHECK (
    data_emissao_offset IS NULL
    OR data_emissao_offset ~ '^(Z|[+-](0[0-9]|1[0-4]):[0-5][0-9])$'
  ),
  CONSTRAINT fiscal_sped_documento_participante_chk CHECK (
    (participante_documento_tipo = 'SEM_DOCUMENTO'
      AND participante_documento_canonico IS NULL)
    OR (participante_documento_tipo = 'CPF'
      AND participante_documento_canonico ~ '^[0-9]{11}$')
    OR (participante_documento_tipo = 'CNPJ'
      AND participante_documento_canonico = public.fiscal_cnpj_normalizar(participante_documento_canonico)
      AND public.fiscal_cnpj_valido(participante_documento_canonico))
    OR (participante_documento_tipo = 'ID_EXTERIOR'
      AND nullif(btrim(participante_documento_canonico), '') IS NOT NULL
      AND position('|' IN participante_documento_canonico) = 0)
  ),
  UNIQUE (versao_id, fonte_tipo, fonte_tabela, fonte_id),
  UNIQUE (versao_id, chave_acesso)
);

CREATE INDEX fiscal_sped_documento_versao_data_idx
  ON public.fiscal_sped_documento_snapshot(versao_id, data_emissao_civil, id);

