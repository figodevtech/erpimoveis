CREATE TABLE public.fiscal_sped_ajuste_apuracao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competencia_id bigint NOT NULL
    REFERENCES public.fiscal_sped_competencia(id) ON DELETE RESTRICT,
  registro_destino text NOT NULL,
  natureza text NOT NULL,
  codigo_ajuste text NOT NULL,
  uf text,
  valor numeric(18,2) NOT NULL,
  descricao text NOT NULL,
  evidencia text NOT NULL,
  numero_documento text,
  referencia jsonb NOT NULL DEFAULT '{}'::jsonb,
  ativo boolean NOT NULL DEFAULT true,
  created_by uuid NOT NULL REFERENCES public.usuario(id) ON DELETE RESTRICT,
  updated_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_ajuste_registro_chk CHECK (
    registro_destino IN ('E111', 'E115', 'E116', 'E311', 'E312', 'E313', 'E316')
  ),
  CONSTRAINT fiscal_sped_ajuste_natureza_chk CHECK (
    (registro_destino IN ('E111', 'E311') AND natureza IN (
      'DEBITO', 'CREDITO', 'ESTORNO_CREDITO', 'ESTORNO_DEBITO',
      'DEDUCAO', 'DEBITO_ESPECIAL'
    ))
    OR (registro_destino = 'E115' AND natureza = 'INFORMATIVO')
    OR (registro_destino IN ('E116', 'E316') AND natureza = 'RECOLHIMENTO')
    OR (registro_destino IN ('E112', 'E312', 'E313') AND natureza = 'REFERENCIA')
  ),
  CONSTRAINT fiscal_sped_ajuste_codigo_chk
    CHECK (nullif(btrim(codigo_ajuste), '') IS NOT NULL),
  CONSTRAINT fiscal_sped_ajuste_evidencia_chk
    CHECK (nullif(btrim(evidencia), '') IS NOT NULL),
  CONSTRAINT fiscal_sped_ajuste_uf_chk CHECK (uf IS NULL OR uf ~ '^[A-Z]{2}$'),
  CONSTRAINT fiscal_sped_ajuste_valor_chk CHECK (valor >= 0)
);

CREATE INDEX fiscal_sped_ajuste_competencia_idx
  ON public.fiscal_sped_ajuste_apuracao(competencia_id, ativo, registro_destino, id);

