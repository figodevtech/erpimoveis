BEGIN;

CREATE TABLE public.fiscal_sped_config (
  empresa_id integer PRIMARY KEY
    REFERENCES public.empresa(id) ON DELETE RESTRICT,
  timezone_iana text,
  timezone_status text NOT NULL DEFAULT 'PENDENTE',
  perfil_efd text,
  perfil_efd_status text NOT NULL DEFAULT 'PENDENTE',
  indicador_atividade text,
  indicador_atividade_status text NOT NULL DEFAULT 'PENDENTE',
  bloco_k_obrigatorio boolean,
  bloco_k_status text NOT NULL DEFAULT 'PENDENTE',
  registro_1400_aplicavel boolean,
  registro_1400_status text NOT NULL DEFAULT 'PENDENTE',
  c176_c179_aplicavel boolean,
  c176_c179_status text NOT NULL DEFAULT 'PENDENTE',
  registro_1601_aplicavel boolean,
  registro_1601_status text NOT NULL DEFAULT 'PENDENTE',
  inventario_aplicavel boolean,
  inventario_status text NOT NULL DEFAULT 'PENDENTE',
  contribuinte_ipi boolean,
  contribuinte_ipi_status text NOT NULL DEFAULT 'PENDENTE',
  entrega_efd_contribuicoes boolean,
  entrega_efd_contribuicoes_status text NOT NULL DEFAULT 'PENDENTE',
  evidencias jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_config_timezone_chk CHECK (
    timezone_iana IS NULL
    OR timezone_iana ~ '^[A-Za-z_+-]+(/[A-Za-z0-9_+-]+)+$'
  ),
  CONSTRAINT fiscal_sped_config_perfil_chk
    CHECK (perfil_efd IS NULL OR perfil_efd IN ('A', 'B', 'C')),
  CONSTRAINT fiscal_sped_config_ind_ativ_chk
    CHECK (indicador_atividade IS NULL OR indicador_atividade IN ('0', '1')),
  CONSTRAINT fiscal_sped_config_status_chk CHECK (
    timezone_status IN ('PENDENTE', 'CONFIRMADO', 'NAO_APLICAVEL')
    AND perfil_efd_status IN ('PENDENTE', 'CONFIRMADO', 'NAO_APLICAVEL')
    AND indicador_atividade_status IN ('PENDENTE', 'CONFIRMADO', 'NAO_APLICAVEL')
    AND bloco_k_status IN ('PENDENTE', 'CONFIRMADO', 'NAO_APLICAVEL')
    AND registro_1400_status IN ('PENDENTE', 'CONFIRMADO', 'NAO_APLICAVEL')
    AND c176_c179_status IN ('PENDENTE', 'CONFIRMADO', 'NAO_APLICAVEL')
    AND registro_1601_status IN ('PENDENTE', 'CONFIRMADO', 'NAO_APLICAVEL')
    AND inventario_status IN ('PENDENTE', 'CONFIRMADO', 'NAO_APLICAVEL')
    AND contribuinte_ipi_status IN ('PENDENTE', 'CONFIRMADO', 'NAO_APLICAVEL')
    AND entrega_efd_contribuicoes_status IN ('PENDENTE', 'CONFIRMADO', 'NAO_APLICAVEL')
  ),
  CONSTRAINT fiscal_sped_config_confirmacoes_chk CHECK (
    (timezone_status <> 'CONFIRMADO' OR timezone_iana IS NOT NULL)
    AND (perfil_efd_status <> 'CONFIRMADO' OR perfil_efd IS NOT NULL)
    AND (indicador_atividade_status <> 'CONFIRMADO' OR indicador_atividade IS NOT NULL)
    AND (bloco_k_status <> 'CONFIRMADO' OR bloco_k_obrigatorio IS NOT NULL)
    AND (registro_1400_status <> 'CONFIRMADO' OR registro_1400_aplicavel IS NOT NULL)
    AND (c176_c179_status <> 'CONFIRMADO' OR c176_c179_aplicavel IS NOT NULL)
    AND (registro_1601_status <> 'CONFIRMADO' OR registro_1601_aplicavel IS NOT NULL)
    AND (inventario_status <> 'CONFIRMADO' OR inventario_aplicavel IS NOT NULL)
    AND (contribuinte_ipi_status <> 'CONFIRMADO' OR contribuinte_ipi IS NOT NULL)
    AND (
      entrega_efd_contribuicoes_status <> 'CONFIRMADO'
      OR entrega_efd_contribuicoes IS NOT NULL
    )
  )
);

COMMENT ON TABLE public.fiscal_sped_config IS
  'Configuração corrente e gates fiscais do estabelecimento. Os valores são congelados no snapshot da versão fechada.';
COMMENT ON COLUMN public.fiscal_sped_config.timezone_iana IS
  'Timezone do estabelecimento para fontes sem offset. Não converte a data civil lexical de XML fiscal.';

CREATE TABLE public.fiscal_sped_contabilista (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL
    REFERENCES public.empresa(id) ON DELETE RESTRICT,
  vigencia_inicio date NOT NULL,
  vigencia_fim date,
  nome text NOT NULL,
  cpf text NOT NULL,
  crc text NOT NULL,
  cnpj_escritorio text,
  cep text,
  endereco text,
  numero text,
  complemento text,
  bairro text,
  telefone text,
  fax text,
  email text,
  codigo_municipio text,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_contabilista_vigencia_chk
    CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  CONSTRAINT fiscal_sped_contabilista_cpf_chk CHECK (cpf ~ '^[0-9]{11}$'),
  CONSTRAINT fiscal_sped_contabilista_cnpj_chk CHECK (
    cnpj_escritorio IS NULL
    OR (
      cnpj_escritorio = public.fiscal_cnpj_normalizar(cnpj_escritorio)
      AND public.fiscal_cnpj_valido(cnpj_escritorio)
    )
  ),
  CONSTRAINT fiscal_sped_contabilista_municipio_chk
    CHECK (codigo_municipio IS NULL OR codigo_municipio ~ '^[0-9]{7}$'),
  UNIQUE (empresa_id, vigencia_inicio)
);

CREATE INDEX fiscal_sped_contabilista_vigencia_idx
  ON public.fiscal_sped_contabilista(empresa_id, vigencia_inicio, vigencia_fim);

CREATE TABLE public.fiscal_sped_item_config (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL
    REFERENCES public.empresa(id) ON DELETE RESTRICT,
  produto_id integer
    REFERENCES public.produto(id) ON DELETE RESTRICT,
  codigo_item text NOT NULL,
  tipo_item text NOT NULL,
  genero_item text,
  ex_ipi text,
  codigo_lst text,
  cest text,
  vigencia_inicio date NOT NULL,
  vigencia_fim date,
  fonte text NOT NULL DEFAULT 'CONFIGURACAO_MANUAL',
  evidencia text NOT NULL,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_item_config_codigo_chk
    CHECK (nullif(btrim(codigo_item), '') IS NOT NULL AND position('|' IN codigo_item) = 0),
  CONSTRAINT fiscal_sped_item_config_tipo_chk CHECK (tipo_item ~ '^[0-9]{2}$'),
  CONSTRAINT fiscal_sped_item_config_genero_chk
    CHECK (genero_item IS NULL OR genero_item ~ '^[0-9]{2}$'),
  CONSTRAINT fiscal_sped_item_config_cest_chk
    CHECK (cest IS NULL OR cest ~ '^[0-9]{7}$'),
  CONSTRAINT fiscal_sped_item_config_evidencia_chk
    CHECK (nullif(btrim(evidencia), '') IS NOT NULL),
  CONSTRAINT fiscal_sped_item_config_vigencia_chk
    CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  UNIQUE (empresa_id, codigo_item, vigencia_inicio)
);

CREATE UNIQUE INDEX fiscal_sped_item_config_produto_vigente_uk
  ON public.fiscal_sped_item_config(empresa_id, produto_id)
  WHERE produto_id IS NOT NULL AND vigencia_fim IS NULL;
CREATE INDEX fiscal_sped_item_config_codigo_idx
  ON public.fiscal_sped_item_config(empresa_id, codigo_item, vigencia_inicio, vigencia_fim);

CREATE TABLE public.fiscal_sped_item_credito_decisao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL REFERENCES public.empresa(id) ON DELETE RESTRICT,
  documento_id bigint NOT NULL REFERENCES public.fiscal_dfe_documento(id) ON DELETE RESTRICT,
  numero_item integer NOT NULL,
  tratamento_credito text NOT NULL,
  evidencia text NOT NULL,
  vigencia_inicio date NOT NULL,
  vigencia_fim date,
  created_by uuid NOT NULL REFERENCES public.usuario(id) ON DELETE RESTRICT,
  updated_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_item_credito_numero_chk CHECK (numero_item > 0),
  CONSTRAINT fiscal_sped_item_credito_tratamento_chk CHECK (
    tratamento_credito IN ('CREDITAVEL', 'SEM_CREDITO', 'USO_CONSUMO', 'ATIVO_IMOBILIZADO')
  ),
  CONSTRAINT fiscal_sped_item_credito_evidencia_chk CHECK (nullif(btrim(evidencia), '') IS NOT NULL),
  CONSTRAINT fiscal_sped_item_credito_vigencia_chk CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  UNIQUE (documento_id, numero_item, vigencia_inicio)
);

CREATE INDEX fiscal_sped_item_credito_vigencia_idx
  ON public.fiscal_sped_item_credito_decisao(empresa_id, documento_id, numero_item, vigencia_inicio, vigencia_fim);

CREATE TABLE public.fiscal_sped_item_correlacao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL
    REFERENCES public.empresa(id) ON DELETE RESTRICT,
  item_principal_id bigint NOT NULL
    REFERENCES public.fiscal_sped_item_config(id) ON DELETE RESTRICT,
  item_atomico_id bigint NOT NULL
    REFERENCES public.fiscal_sped_item_config(id) ON DELETE RESTRICT,
  quantidade numeric(20,6) NOT NULL,
  vigencia_inicio date NOT NULL,
  vigencia_fim date,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_item_correlacao_quantidade_chk CHECK (quantidade > 0),
  CONSTRAINT fiscal_sped_item_correlacao_vigencia_chk
    CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  UNIQUE (item_principal_id, item_atomico_id, vigencia_inicio)
);

CREATE INDEX fiscal_sped_item_correlacao_vigencia_idx
  ON public.fiscal_sped_item_correlacao(empresa_id, item_principal_id, vigencia_inicio, vigencia_fim);

CREATE TABLE public.fiscal_sped_unidade_conversao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL
    REFERENCES public.empresa(id) ON DELETE RESTRICT,
  codigo_item text,
  unidade_origem text NOT NULL,
  unidade_destino text NOT NULL,
  fator_conversao numeric(20,10) NOT NULL,
  vigencia_inicio date NOT NULL,
  vigencia_fim date,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_unidade_conversao_unidades_chk CHECK (
    nullif(btrim(unidade_origem), '') IS NOT NULL
    AND nullif(btrim(unidade_destino), '') IS NOT NULL
    AND position('|' IN unidade_origem) = 0
    AND position('|' IN unidade_destino) = 0
  ),
  CONSTRAINT fiscal_sped_unidade_conversao_fator_chk CHECK (fator_conversao > 0),
  CONSTRAINT fiscal_sped_unidade_conversao_vigencia_chk
    CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio)
);

CREATE UNIQUE INDEX fiscal_sped_unidade_conversao_identidade_uk
  ON public.fiscal_sped_unidade_conversao(
    empresa_id, coalesce(codigo_item, ''), unidade_origem,
    unidade_destino, vigencia_inicio
  );

CREATE INDEX fiscal_sped_unidade_conversao_vigencia_idx
  ON public.fiscal_sped_unidade_conversao(
    empresa_id, unidade_origem, unidade_destino, vigencia_inicio, vigencia_fim
  );

-- Para estabelecimentos paraibanos, Fortaleza é a expectativa geográfica
-- correta. O gate continua PENDENTE: o valor precisa de confirmação cadastral
-- e nunca é usado para reinterpretar a data civil lexical de um XML.
INSERT INTO public.fiscal_sped_config(empresa_id, timezone_iana, timezone_status)
SELECT id, 'America/Fortaleza', 'PENDENTE'
  FROM public.empresa
 WHERE upper(coalesce(uf, '')) = 'PB'
ON CONFLICT (empresa_id) DO NOTHING;

COMMIT;
