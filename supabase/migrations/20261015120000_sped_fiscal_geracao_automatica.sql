BEGIN;

-- SPED Fiscal: geracao em um clique.
--
-- 1. Vigencia historica da configuracao fiscal: cada competencia usa a
--    configuracao vigente no seu primeiro dia, e uma mudanca de regime ou
--    perfil vale so dali em diante.
-- 2. Resolucao automatica de itens (0200) e decisoes de credito, gravada numa
--    unica transacao que revalida tudo contra o estado do banco.
-- 3. Processamento persistente da geracao: uma linha por pedido, com etapa,
--    concessao (lease) para retomada e no maximo um pedido ativo por
--    competencia.

-- ---------------------------------------------------------------------------
-- 1. Vigencia da configuracao
-- ---------------------------------------------------------------------------

CREATE TABLE public.fiscal_sped_config_vigencia (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL
    REFERENCES public.empresa(id) ON DELETE RESTRICT,
  vigencia_inicio date NOT NULL,
  payload jsonb NOT NULL,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_sped_config_vigencia_mes_chk
    CHECK (vigencia_inicio = date_trunc('month', vigencia_inicio)::date),
  CONSTRAINT fiscal_sped_config_vigencia_payload_chk
    CHECK (jsonb_typeof(payload) = 'object'),
  UNIQUE (empresa_id, vigencia_inicio)
);

COMMENT ON TABLE public.fiscal_sped_config_vigencia IS
  'Historico da configuracao fiscal SPED. A competencia usa a linha com maior vigencia_inicio que nao ultrapasse o seu primeiro dia; fiscal_sped_config espelha a vigencia mais recente.';

CREATE TRIGGER fiscal_sped_config_vigencia_touch_trg
BEFORE UPDATE ON public.fiscal_sped_config_vigencia
FOR EACH ROW EXECUTE FUNCTION public.fiscal_sped_touch_updated_at();

-- A configuracao existente passa a valer desde sempre: e o que o motor ja
-- usava para todas as competencias.
INSERT INTO public.fiscal_sped_config_vigencia(empresa_id, vigencia_inicio, payload, created_by, updated_by)
SELECT config.empresa_id, DATE '2000-01-01', to_jsonb(config), config.updated_by, config.updated_by
  FROM public.fiscal_sped_config config
ON CONFLICT (empresa_id, vigencia_inicio) DO NOTHING;

CREATE OR REPLACE FUNCTION public.fiscal_sped_config_efetiva(
  p_empresa_id integer,
  p_competencia date
)
RETURNS public.fiscal_sped_config
LANGUAGE plpgsql
STABLE
SET search_path = public
AS $$
DECLARE
  v_payload jsonb;
  v_config public.fiscal_sped_config%ROWTYPE;
BEGIN
  SELECT payload INTO v_payload
    FROM public.fiscal_sped_config_vigencia
   WHERE empresa_id = p_empresa_id
     AND vigencia_inicio <= p_competencia
   ORDER BY vigencia_inicio DESC
   LIMIT 1;
  IF v_payload IS NULL THEN
    SELECT payload INTO v_payload
      FROM public.fiscal_sped_config_vigencia
     WHERE empresa_id = p_empresa_id
     ORDER BY vigencia_inicio ASC
     LIMIT 1;
  END IF;
  IF v_payload IS NOT NULL THEN
    v_config := jsonb_populate_record(NULL::public.fiscal_sped_config, v_payload);
    v_config.empresa_id := p_empresa_id;
    RETURN v_config;
  END IF;
  SELECT * INTO v_config FROM public.fiscal_sped_config WHERE empresa_id = p_empresa_id;
  IF NOT FOUND THEN
    RETURN NULL;
  END IF;
  RETURN v_config;
END;
$$;

-- O fechamento confere os gates na configuracao vigente da competencia, nao
-- na configuracao corrente: uma mudanca futura nao trava nem libera o passado.
CREATE OR REPLACE FUNCTION public.fiscal_sped_fechar_versao(
  p_competencia_id bigint,
  p_versao_id bigint,
  p_expected_lock_version integer,
  p_context_hash text,
  p_usuario_id uuid
)
RETURNS integer
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_competencia public.fiscal_sped_competencia%ROWTYPE;
  v_versao public.fiscal_sped_versao%ROWTYPE;
  v_config public.fiscal_sped_config%ROWTYPE;
  v_novo_lock integer;
BEGIN
  PERFORM pg_advisory_xact_lock(2147480000, (p_competencia_id % 2147483647)::integer);
  SELECT * INTO v_competencia
    FROM public.fiscal_sped_competencia
   WHERE id = p_competencia_id
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Competencia SPED inexistente.' USING ERRCODE = 'P0002';
  END IF;
  IF v_competencia.lock_version <> p_expected_lock_version THEN
    RAISE EXCEPTION 'Competencia alterada por outro processo.' USING ERRCODE = '40001';
  END IF;
  IF v_competencia.status <> 'APTA' OR v_competencia.versao_atual_id <> p_versao_id THEN
    RAISE EXCEPTION 'Competencia nao esta apta com a versao informada.' USING ERRCODE = '55000';
  END IF;

  SELECT * INTO v_versao
    FROM public.fiscal_sped_versao
   WHERE id = p_versao_id AND competencia_id = p_competencia_id
   FOR UPDATE;
  IF NOT FOUND OR v_versao.status <> 'VALIDADA' THEN
    RAISE EXCEPTION 'Versao SPED nao esta validada.' USING ERRCODE = '55000';
  END IF;
  IF lower(p_context_hash) <> v_versao.context_hash THEN
    RAISE EXCEPTION 'Hash de contexto divergente.' USING ERRCODE = '40001';
  END IF;

  v_config := public.fiscal_sped_config_efetiva(v_competencia.empresa_id, v_competencia.competencia);
  IF v_config.empresa_id IS NULL THEN
    RAISE EXCEPTION 'Configuracao SPED ausente.' USING ERRCODE = '23514';
  END IF;
  IF v_config.timezone_status IS DISTINCT FROM 'CONFIRMADO'
     OR v_config.perfil_efd_status IS DISTINCT FROM 'CONFIRMADO'
     OR v_config.indicador_atividade_status IS DISTINCT FROM 'CONFIRMADO'
     OR coalesce(v_config.bloco_k_status, 'PENDENTE') = 'PENDENTE'
     OR coalesce(v_config.registro_1400_status, 'PENDENTE') = 'PENDENTE'
     OR coalesce(v_config.c176_c179_status, 'PENDENTE') = 'PENDENTE'
     OR coalesce(v_config.registro_1601_status, 'PENDENTE') = 'PENDENTE'
     OR coalesce(v_config.inventario_status, 'PENDENTE') = 'PENDENTE'
     OR coalesce(v_config.contribuinte_ipi_status, 'PENDENTE') = 'PENDENTE'
     OR coalesce(v_config.entrega_efd_contribuicoes_status, 'PENDENTE') = 'PENDENTE' THEN
    RAISE EXCEPTION 'Existem gates fiscais pendentes na configuracao SPED.' USING ERRCODE = '23514';
  END IF;
  IF NOT EXISTS (
    SELECT 1
      FROM public.fiscal_sped_validacao_execucao execucao
     WHERE execucao.versao_id = p_versao_id
       AND execucao.status = 'CONCLUIDA'
       AND execucao.context_hash = v_versao.context_hash
       AND execucao.quantidade_bloqueios = 0
       AND execucao.quantidade_erros = 0
  ) THEN
    RAISE EXCEPTION 'Versao sem validacao concluida e livre de erros.' USING ERRCODE = '23514';
  END IF;

  IF v_versao.versao_anterior_id IS NOT NULL THEN
    UPDATE public.fiscal_sped_versao
       SET status = 'SUBSTITUIDA', substituted_at = now()
     WHERE id = v_versao.versao_anterior_id
       AND status = 'FECHADA';
  END IF;

  UPDATE public.fiscal_sped_versao
     SET status = 'FECHADA', closed_at = now(), closed_by = p_usuario_id
   WHERE id = p_versao_id;

  UPDATE public.fiscal_sped_competencia
     SET status = 'FECHADA', fechada_at = now(), fechada_by = p_usuario_id,
         updated_by = p_usuario_id, lock_version = lock_version + 1
   WHERE id = p_competencia_id
  RETURNING lock_version INTO v_novo_lock;

  RETURN v_novo_lock;
END;
$$;

-- ---------------------------------------------------------------------------
-- 2. Resolucao automatica de itens e creditos
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.fiscal_sped_aplicar_resolucao_automatica(
  p_competencia_id bigint,
  p_itens jsonb,
  p_creditos jsonb,
  p_usuario_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_competencia public.fiscal_sped_competencia%ROWTYPE;
  v_item jsonb;
  v_credito jsonb;
  v_produto_id integer;
  v_codigo text;
  v_tipo text;
  v_inicio date;
  v_fim date;
  v_documento_id bigint;
  v_numero_item integer;
  v_tratamento text;
  v_itens_criados integer := 0;
  v_itens_ignorados integer := 0;
  v_creditos_criados integer := 0;
  v_creditos_ignorados integer := 0;
BEGIN
  IF p_usuario_id IS NULL THEN
    RAISE EXCEPTION 'Usuario responsavel e obrigatorio.' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO v_competencia
    FROM public.fiscal_sped_competencia
   WHERE id = p_competencia_id
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Competencia SPED inexistente.' USING ERRCODE = 'P0002';
  END IF;
  IF v_competencia.status = 'FECHADA' THEN
    RAISE EXCEPTION 'Competencia fechada nao aceita decisoes fiscais.' USING ERRCODE = '55000';
  END IF;

  FOR v_item IN SELECT * FROM jsonb_array_elements(coalesce(p_itens, '[]'::jsonb))
  LOOP
    v_produto_id := (v_item->>'produto_id')::integer;
    v_codigo := btrim(v_item->>'codigo_item');
    v_tipo := v_item->>'tipo_item';
    v_inicio := (v_item->>'vigencia_inicio')::date;
    v_fim := nullif(v_item->>'vigencia_fim', '')::date;
    IF v_produto_id IS NULL OR nullif(v_codigo, '') IS NULL OR position('|' IN v_codigo) > 0
       OR v_tipo IS NULL OR v_tipo !~ '^[0-9]{2}$' OR v_inicio IS NULL
       OR (v_fim IS NOT NULL AND v_fim < v_inicio)
       OR nullif(btrim(v_item->>'evidencia'), '') IS NULL THEN
      RAISE EXCEPTION 'Resolucao automatica de item invalida: %', v_item USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.produto WHERE id = v_produto_id AND NOT is_deleted) THEN
      v_itens_ignorados := v_itens_ignorados + 1;
      CONTINUE;
    END IF;
    -- Outro processo pode ter configurado o produto ou ocupado o codigo depois
    -- do plano: a decisao existente prevalece e o item e ignorado.
    IF EXISTS (
      SELECT 1 FROM public.fiscal_sped_item_config cfg
       WHERE cfg.empresa_id = v_competencia.empresa_id
         AND cfg.produto_id = v_produto_id
         AND cfg.vigencia_inicio <= coalesce(v_fim, DATE '9999-12-31')
         AND (cfg.vigencia_fim IS NULL OR cfg.vigencia_fim >= v_inicio)
    ) OR EXISTS (
      SELECT 1 FROM public.fiscal_sped_item_config cfg
       WHERE cfg.empresa_id = v_competencia.empresa_id
         AND cfg.codigo_item = v_codigo
         AND cfg.produto_id IS DISTINCT FROM v_produto_id
    ) THEN
      v_itens_ignorados := v_itens_ignorados + 1;
      CONTINUE;
    END IF;
    INSERT INTO public.fiscal_sped_item_config(
      empresa_id, produto_id, codigo_item, tipo_item, vigencia_inicio, vigencia_fim,
      fonte, evidencia, created_by, updated_by
    ) VALUES (
      v_competencia.empresa_id, v_produto_id, v_codigo, v_tipo, v_inicio, v_fim,
      'RESOLUCAO_AUTOMATICA', btrim(v_item->>'evidencia'), p_usuario_id, p_usuario_id
    );
    v_itens_criados := v_itens_criados + 1;
  END LOOP;

  FOR v_credito IN SELECT * FROM jsonb_array_elements(coalesce(p_creditos, '[]'::jsonb))
  LOOP
    v_documento_id := (v_credito->>'documento_id')::bigint;
    v_numero_item := (v_credito->>'numero_item')::integer;
    v_tratamento := v_credito->>'tratamento_credito';
    IF v_documento_id IS NULL OR v_numero_item IS NULL OR v_numero_item <= 0
       OR v_tratamento NOT IN ('CREDITAVEL', 'SEM_CREDITO', 'USO_CONSUMO', 'ATIVO_IMOBILIZADO')
       OR nullif(btrim(v_credito->>'evidencia'), '') IS NULL THEN
      RAISE EXCEPTION 'Decisao automatica de credito invalida: %', v_credito USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
      SELECT 1 FROM public.fiscal_dfe_documento
       WHERE id = v_documento_id AND empresa_id = v_competencia.empresa_id
    ) THEN
      RAISE EXCEPTION 'DFe nao pertence ao estabelecimento da competencia.' USING ERRCODE = '23503';
    END IF;
    IF EXISTS (
      SELECT 1 FROM public.fiscal_sped_item_credito_decisao decisao
       WHERE decisao.documento_id = v_documento_id
         AND decisao.numero_item = v_numero_item
         AND decisao.vigencia_inicio <= (v_competencia.competencia + interval '1 month' - interval '1 day')::date
         AND (decisao.vigencia_fim IS NULL OR decisao.vigencia_fim >= v_competencia.competencia)
    ) THEN
      v_creditos_ignorados := v_creditos_ignorados + 1;
      CONTINUE;
    END IF;
    INSERT INTO public.fiscal_sped_item_credito_decisao(
      empresa_id, documento_id, numero_item, tratamento_credito, evidencia,
      vigencia_inicio, created_by, updated_by
    ) VALUES (
      v_competencia.empresa_id, v_documento_id, v_numero_item, v_tratamento,
      btrim(v_credito->>'evidencia'), v_competencia.competencia, p_usuario_id, p_usuario_id
    );
    v_creditos_criados := v_creditos_criados + 1;
  END LOOP;

  RETURN jsonb_build_object(
    'itensCriados', v_itens_criados,
    'itensIgnorados', v_itens_ignorados,
    'creditosCriados', v_creditos_criados,
    'creditosIgnorados', v_creditos_ignorados
  );
END;
$$;

-- ---------------------------------------------------------------------------
-- 3. Processamento persistente da geracao
-- ---------------------------------------------------------------------------

CREATE TABLE public.fiscal_sped_geracao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL
    REFERENCES public.empresa(id) ON DELETE RESTRICT,
  competencia date NOT NULL,
  competencia_id bigint
    REFERENCES public.fiscal_sped_competencia(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'PENDENTE',
  etapa text NOT NULL DEFAULT 'AGUARDANDO',
  etapas jsonb NOT NULL DEFAULT '[]'::jsonb,
  resultado jsonb,
  erro_codigo text,
  erro_mensagem text,
  lease_token uuid,
  lease_until timestamptz,
  tentativas integer NOT NULL DEFAULT 0,
  solicitado_por uuid NOT NULL REFERENCES public.usuario(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  concluido_at timestamptz,
  CONSTRAINT fiscal_sped_geracao_mes_chk
    CHECK (competencia = date_trunc('month', competencia)::date),
  CONSTRAINT fiscal_sped_geracao_status_chk
    CHECK (status IN ('PENDENTE', 'PROCESSANDO', 'PENDENCIAS', 'CONCLUIDA', 'FALHOU')),
  CONSTRAINT fiscal_sped_geracao_etapa_chk CHECK (etapa IN (
    'AGUARDANDO', 'PREPARANDO', 'COLETANDO_DOCUMENTOS', 'RESOLVENDO_CADASTROS',
    'CALCULANDO_APURACAO', 'MONTANDO_REGISTROS', 'VALIDANDO', 'FECHANDO',
    'GERANDO_ARQUIVO', 'FINALIZADO'
  )),
  CONSTRAINT fiscal_sped_geracao_etapas_chk CHECK (jsonb_typeof(etapas) = 'array'),
  CONSTRAINT fiscal_sped_geracao_tentativas_chk CHECK (tentativas >= 0),
  CONSTRAINT fiscal_sped_geracao_conclusao_chk CHECK (
    (status IN ('PENDENCIAS', 'CONCLUIDA', 'FALHOU') AND concluido_at IS NOT NULL)
    OR status IN ('PENDENTE', 'PROCESSANDO')
  )
);

COMMENT ON TABLE public.fiscal_sped_geracao IS
  'Pedidos de geracao automatica do SPED Fiscal. Cada pedido avanca por etapas persistidas; a concessao (lease) permite retomar um processamento interrompido sem executar duas vezes.';

-- Clique duplo ou requisicao repetida: no maximo um pedido ativo por competencia.
CREATE UNIQUE INDEX fiscal_sped_geracao_ativa_uk
  ON public.fiscal_sped_geracao(empresa_id, competencia)
  WHERE status IN ('PENDENTE', 'PROCESSANDO');
CREATE INDEX fiscal_sped_geracao_competencia_idx
  ON public.fiscal_sped_geracao(empresa_id, competencia, created_at DESC);

CREATE TRIGGER fiscal_sped_geracao_touch_trg
BEFORE UPDATE ON public.fiscal_sped_geracao
FOR EACH ROW EXECUTE FUNCTION public.fiscal_sped_touch_updated_at();

CREATE OR REPLACE FUNCTION public.fiscal_sped_geracao_solicitar(
  p_empresa_id integer,
  p_competencia date,
  p_usuario_id uuid
)
RETURNS bigint
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_id bigint;
BEGIN
  IF p_competencia IS NULL OR p_competencia <> date_trunc('month', p_competencia)::date THEN
    RAISE EXCEPTION 'Competencia deve ser o primeiro dia do mes.' USING ERRCODE = '22023';
  END IF;
  PERFORM pg_advisory_xact_lock(2147480001, hashtext(p_empresa_id::text || ':' || p_competencia::text));
  SELECT id INTO v_id
    FROM public.fiscal_sped_geracao
   WHERE empresa_id = p_empresa_id
     AND competencia = p_competencia
     AND status IN ('PENDENTE', 'PROCESSANDO')
   ORDER BY id
   LIMIT 1;
  IF v_id IS NOT NULL THEN
    RETURN v_id;
  END IF;
  INSERT INTO public.fiscal_sped_geracao(empresa_id, competencia, solicitado_por)
  VALUES (p_empresa_id, p_competencia, p_usuario_id)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

-- Concede o processamento a um executor. Recusa enquanto outra concessao
-- estiver valida; uma concessao expirada indica execucao interrompida e pode
-- ser retomada por outro executor.
CREATE OR REPLACE FUNCTION public.fiscal_sped_geracao_reivindicar(
  p_id bigint,
  p_token uuid,
  p_lease_seconds integer
)
RETURNS public.fiscal_sped_geracao
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_row public.fiscal_sped_geracao%ROWTYPE;
BEGIN
  UPDATE public.fiscal_sped_geracao
     SET status = 'PROCESSANDO',
         lease_token = p_token,
         lease_until = now() + make_interval(secs => greatest(p_lease_seconds, 15)),
         tentativas = tentativas + 1
   WHERE id = p_id
     AND status IN ('PENDENTE', 'PROCESSANDO')
     AND (lease_until IS NULL OR lease_until < now() OR lease_token = p_token)
  RETURNING * INTO v_row;
  IF NOT FOUND THEN
    RETURN NULL;
  END IF;
  RETURN v_row;
END;
$$;

CREATE OR REPLACE FUNCTION public.fiscal_sped_geracao_avancar(
  p_id bigint,
  p_token uuid,
  p_etapa text,
  p_competencia_id bigint,
  p_lease_seconds integer
)
RETURNS void
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  UPDATE public.fiscal_sped_geracao
     SET etapa = p_etapa,
         competencia_id = coalesce(p_competencia_id, competencia_id),
         etapas = etapas || jsonb_build_array(jsonb_build_object('etapa', p_etapa, 'em', now())),
         lease_until = now() + make_interval(secs => greatest(p_lease_seconds, 15))
   WHERE id = p_id
     AND status = 'PROCESSANDO'
     AND lease_token = p_token;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Processamento SPED perdeu a concessao.' USING ERRCODE = '40001';
  END IF;
END;
$$;

-- Renova a concessao durante uma etapa longa. Retorna false se ela ja foi perdida.
CREATE OR REPLACE FUNCTION public.fiscal_sped_geracao_renovar(
  p_id bigint,
  p_token uuid,
  p_lease_seconds integer
)
RETURNS boolean
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  UPDATE public.fiscal_sped_geracao
     SET lease_until = now() + make_interval(secs => greatest(p_lease_seconds, 15))
   WHERE id = p_id
     AND status = 'PROCESSANDO'
     AND lease_token = p_token;
  RETURN FOUND;
END;
$$;

CREATE OR REPLACE FUNCTION public.fiscal_sped_geracao_concluir(
  p_id bigint,
  p_token uuid,
  p_status text,
  p_resultado jsonb,
  p_erro_codigo text,
  p_erro_mensagem text
)
RETURNS void
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF p_status NOT IN ('PENDENCIAS', 'CONCLUIDA', 'FALHOU') THEN
    RAISE EXCEPTION 'Status final invalido.' USING ERRCODE = '22023';
  END IF;
  UPDATE public.fiscal_sped_geracao
     SET status = p_status,
         etapa = CASE WHEN p_status = 'CONCLUIDA' THEN 'FINALIZADO' ELSE etapa END,
         etapas = CASE WHEN p_status = 'CONCLUIDA'
                       THEN etapas || jsonb_build_array(jsonb_build_object('etapa', 'FINALIZADO', 'em', now()))
                       ELSE etapas END,
         resultado = p_resultado,
         erro_codigo = p_erro_codigo,
         erro_mensagem = p_erro_mensagem,
         lease_token = NULL,
         lease_until = NULL,
         concluido_at = now()
   WHERE id = p_id
     AND status = 'PROCESSANDO'
     AND lease_token = p_token;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Processamento SPED perdeu a concessao.' USING ERRCODE = '40001';
  END IF;
END;
$$;

