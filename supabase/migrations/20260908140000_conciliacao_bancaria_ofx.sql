-- Conciliação bancária por importação de arquivo OFX.
--
-- O QUE ISTO ACRESCENTA
-- Duas tabelas que guardam o EXTRATO (o que o banco disse) e uma RPC que aplica
-- a decisão do usuário sobre cada linha dele. Nada aqui reimplementa baixa,
-- baixa parcial ou criação de título: a conciliação chama
-- `baixar_transacao_pendente`, que continua sendo a única dona dessas regras.
--
-- O QUE ISTO NÃO FAZ
-- Não toca em `transacao` a não ser inserindo o lançamento de um movimento que
-- não existia, e não muda nenhuma regra de DRE, adiantamento, transferência ou
-- pagamento múltiplo. Ler o arquivo não escreve nada: quem escreve é a
-- confirmação do usuário, e é por isso que a análise vive fora do banco.
--
-- POR QUE NÃO TEM `empresa_id`
-- Cada empresa tem o seu próprio banco de dados — `transacao` também não tem a
-- coluna. O isolamento aqui vem do `banco_id`, que aponta para `bancoconta`,
-- que é de uma empresa só.
BEGIN;

-- ---------------------------------------------------------------------------
-- 1) O arquivo importado
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.ofx_importacao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  banco_id bigint NOT NULL REFERENCES public.bancoconta(id) ON DELETE RESTRICT,
  arquivo_nome text NOT NULL,
  arquivo_hash text NOT NULL,

  bank_id_ofx text,
  agencia_ofx text,
  conta_ofx text,
  tipo_conta_ofx text,
  moeda text,

  periodo_inicio date,
  periodo_fim date,

  saldo_inicial numeric(14,2),
  saldo_final numeric(14,2),

  quantidade_movimentos integer NOT NULL DEFAULT 0,
  quantidade_importados integer NOT NULL DEFAULT 0,
  quantidade_repetidos integer NOT NULL DEFAULT 0,

  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.ofx_importacao OWNER TO postgres;

COMMENT ON TABLE public.ofx_importacao IS
  'Um arquivo OFX importado para uma conta bancária. Guarda o cabeçalho do extrato e as contagens do que entrou; os movimentos ficam em ofx_movimento.';
COMMENT ON COLUMN public.ofx_importacao.arquivo_hash IS
  'SHA-256 do arquivo. Responde "este arquivo já foi importado?" — pergunta diferente de "este movimento já foi importado?", que é o fingerprint do movimento.';
COMMENT ON COLUMN public.ofx_importacao.quantidade_movimentos IS
  'Linhas lidas do arquivo.';
COMMENT ON COLUMN public.ofx_importacao.quantidade_importados IS
  'Linhas gravadas por esta importação. Menor que o total quando o período se sobrepõe a uma importação anterior.';
COMMENT ON COLUMN public.ofx_importacao.quantidade_repetidos IS
  'Linhas que já existiam de outra importação da mesma conta e por isso não foram gravadas de novo.';
COMMENT ON COLUMN public.ofx_importacao.saldo_inicial IS
  'Deduzido do saldo final menos a soma dos movimentos: o OFX 1.x quase nunca envia saldo de abertura.';

-- O mesmo arquivo não entra duas vezes na mesma conta. Em contas diferentes
-- entra: é o caso, legítimo e raro, de alguém corrigir a conta escolhida.
CREATE UNIQUE INDEX IF NOT EXISTS ofx_importacao_arquivo_unico_idx
  ON public.ofx_importacao (banco_id, arquivo_hash);

CREATE INDEX IF NOT EXISTS ofx_importacao_banco_data_idx
  ON public.ofx_importacao (banco_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- 2) A linha do extrato
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.ofx_movimento (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  importacao_id bigint NOT NULL REFERENCES public.ofx_importacao(id) ON DELETE CASCADE,
  -- Desnormalizado de propósito: é o que permite a restrição de unicidade por
  -- conta, que é onde a proteção contra movimento repetido de fato mora.
  banco_id bigint NOT NULL REFERENCES public.bancoconta(id) ON DELETE RESTRICT,

  sequencia integer NOT NULL,

  fitid text,
  checknum text,
  refnum text,
  tipo_ofx text,

  data_postagem date NOT NULL,
  data_disponivel date,

  valor numeric(14,2) NOT NULL,
  valor_centavos bigint NOT NULL,

  nome text,
  memo text,

  fingerprint text NOT NULL,

  status text NOT NULL DEFAULT 'PENDENTE',
  situacao_analise text,
  score_match integer,
  acao_conciliacao text,
  observacao text,

  transacao_id bigint REFERENCES public.transacao(id) ON DELETE SET NULL,
  titulo_origem_id bigint REFERENCES public.transacao(id) ON DELETE SET NULL,

  conciliado_em timestamptz,
  conciliado_por uuid,

  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT ofx_movimento_status_check
    CHECK (status IN ('PENDENTE', 'CONCILIADO', 'IGNORADO')),
  CONSTRAINT ofx_movimento_acao_check
    CHECK (acao_conciliacao IS NULL OR acao_conciliacao IN
      ('VINCULAR', 'LIQUIDAR', 'BAIXA_PARCIAL', 'CRIAR', 'IGNORAR')),
  CONSTRAINT ofx_movimento_situacao_check
    CHECK (situacao_analise IS NULL OR situacao_analise IN
      ('MATCH_EXATO', 'MATCH_PROVAVEL', 'AMBIGUO', 'SEM_CORRESPONDENCIA', 'REVISAO_MANUAL')),
  -- Movimento conciliado sem dinheiro do outro lado seria conciliação de nada.
  -- IGNORAR é o estado que registra "vi e não é para lançar".
  CONSTRAINT ofx_movimento_conciliado_tem_transacao_check
    CHECK (status <> 'CONCILIADO' OR transacao_id IS NOT NULL)
);

ALTER TABLE public.ofx_movimento OWNER TO postgres;

COMMENT ON TABLE public.ofx_movimento IS
  'Uma linha do extrato bancário importado. É o registro do que o banco informou, e o vínculo com a transação do ERP que representa aquele mesmo dinheiro.';
COMMENT ON COLUMN public.ofx_movimento.fingerprint IS
  'Identidade determinística da linha: conta, data, valor com sinal, FITID, CHECKNUM, REFNUM, NAME, MEMO e a ocorrência dentro do arquivo. FITID sozinho não serve — os extratos observados repetem o mesmo FITID em movimentos diferentes.';
COMMENT ON COLUMN public.ofx_movimento.valor_centavos IS
  'O valor em centavos inteiros, com sinal: positivo entra na conta, negativo sai. Toda comparação financeira usa esta coluna, nunca a numérica.';
COMMENT ON COLUMN public.ofx_movimento.transacao_id IS
  'A transação do ERP que representa este dinheiro. Numa baixa parcial é a transação FILHA (o movimento de caixa), não o título.';
COMMENT ON COLUMN public.ofx_movimento.titulo_origem_id IS
  'O título que foi liquidado por este movimento, quando houve baixa. Na baixa de uma vez é a mesma linha de transacao_id; na parcial, o título que continua em aberto.';
COMMENT ON COLUMN public.ofx_movimento.situacao_analise IS
  'Como a análise classificou a linha no momento da importação. É histórico: a decisão que valeu está em acao_conciliacao.';

-- A proteção contra reimportar o mesmo movimento. Vale por conta, não por
-- arquivo: dois extratos com períodos sobrepostos trazem as mesmas linhas.
CREATE UNIQUE INDEX IF NOT EXISTS ofx_movimento_fingerprint_unico_idx
  ON public.ofx_movimento (banco_id, fingerprint);

-- Uma transação do ERP responde por um movimento bancário só. Sem isto, dois
-- movimentos poderiam apontar para o mesmo lançamento e o extrato "fecharia"
-- com metade do dinheiro.
CREATE UNIQUE INDEX IF NOT EXISTS ofx_movimento_transacao_unica_idx
  ON public.ofx_movimento (transacao_id)
  WHERE transacao_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS ofx_movimento_importacao_idx
  ON public.ofx_movimento (importacao_id, sequencia);

CREATE INDEX IF NOT EXISTS ofx_movimento_status_idx
  ON public.ofx_movimento (banco_id, status, data_postagem);

-- ---------------------------------------------------------------------------
-- 3) O líquido efetivo, em SQL
-- ---------------------------------------------------------------------------
--
-- Espelha `valorLiquidoEfetivo()` de src/lib/financeiro/transacao.ts, que é a
-- regra que o resto do sistema já usa. Existe aqui para a RPC poder conferir,
-- antes de vincular, que o dinheiro do extrato é o mesmo dinheiro da transação
-- — sem essa conferência a validação ficaria só do lado do TypeScript, e uma
-- chamada direta à RPC passaria por cima dela.
CREATE OR REPLACE FUNCTION public.transacao_valor_liquido_efetivo(p_transacao public.transacao)
RETURNS numeric
LANGUAGE sql
IMMUTABLE
AS $function$
  SELECT CASE
    WHEN coalesce(p_transacao.valor_descontos, 0) > 0 THEN
      CASE WHEN coalesce(p_transacao."valorLiquido", 0) > 0
        THEN round(p_transacao."valorLiquido", 2)
        ELSE round(coalesce(p_transacao.valor, 0) - p_transacao.valor_descontos, 2)
      END
    -- Só receita e saque têm taxa, e portanto líquido. Despesa e depósito valem
    -- o bruto — registro antigo guarda lixo nessa coluna.
    WHEN upper(p_transacao.tipo::text) NOT IN ('RECEITA', 'SAQUE') THEN
      round(coalesce(p_transacao.valor, 0), 2)
    WHEN coalesce(p_transacao."valorLiquido", 0) > 0 THEN
      round(p_transacao."valorLiquido", 2)
    ELSE round(coalesce(p_transacao.valor, 0), 2)
  END;
$function$;

ALTER FUNCTION public.transacao_valor_liquido_efetivo(public.transacao) OWNER TO postgres;

COMMENT ON FUNCTION public.transacao_valor_liquido_efetivo(public.transacao) IS
  'O dinheiro que a transação de fato movimenta, já descontada a taxa da maquineta. Mesma regra de valorLiquidoEfetivo() no TypeScript.';

-- ---------------------------------------------------------------------------
-- 4) Registrar a importação
-- ---------------------------------------------------------------------------
--
-- Uma chamada só para o arquivo inteiro: ou entram o cabeçalho e todos os
-- movimentos novos, ou não entra nada. Importação pela metade deixaria o
-- usuário com um extrato truncado que parece completo.
CREATE OR REPLACE FUNCTION public.registrar_importacao_ofx(
  p_banco_id bigint,
  p_arquivo_nome text,
  p_arquivo_hash text,
  p_cabecalho jsonb,
  p_movimentos jsonb,
  p_created_by uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_importacao_id bigint;
  v_movimento jsonb;
  v_id bigint;
  v_importados integer := 0;
  v_repetidos integer := 0;
  v_total integer;
  v_resultado jsonb := '[]'::jsonb;
  v_existente_id bigint;
BEGIN
  IF p_banco_id IS NULL OR p_banco_id <= 0 THEN
    RAISE EXCEPTION 'Conta bancária obrigatória.' USING ERRCODE = '22023';
  END IF;
  IF nullif(btrim(coalesce(p_arquivo_hash, '')), '') IS NULL THEN
    RAISE EXCEPTION 'Não foi possível identificar o arquivo.' USING ERRCODE = '22023';
  END IF;
  IF jsonb_typeof(p_movimentos) <> 'array' OR jsonb_array_length(p_movimentos) = 0 THEN
    RAISE EXCEPTION 'O extrato não tem nenhum movimento para importar.' USING ERRCODE = '22023';
  END IF;

  PERFORM 1 FROM public.bancoconta WHERE id = p_banco_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Conta bancária não encontrada.' USING ERRCODE = 'P0002';
  END IF;

  SELECT id INTO v_existente_id
    FROM public.ofx_importacao
   WHERE banco_id = p_banco_id AND arquivo_hash = p_arquivo_hash;
  IF FOUND THEN
    RAISE EXCEPTION
      'Este arquivo já foi importado nesta conta (importação #%).', v_existente_id
      USING ERRCODE = '23505';
  END IF;

  v_total := jsonb_array_length(p_movimentos);

  INSERT INTO public.ofx_importacao (
    banco_id, arquivo_nome, arquivo_hash,
    bank_id_ofx, agencia_ofx, conta_ofx, tipo_conta_ofx, moeda,
    periodo_inicio, periodo_fim, saldo_inicial, saldo_final,
    quantidade_movimentos, created_by
  ) VALUES (
    p_banco_id,
    coalesce(nullif(btrim(p_arquivo_nome), ''), 'extrato.ofx'),
    p_arquivo_hash,
    nullif(btrim(p_cabecalho->>'bankId'), ''),
    nullif(btrim(p_cabecalho->>'branchId'), ''),
    nullif(btrim(p_cabecalho->>'acctId'), ''),
    nullif(btrim(p_cabecalho->>'acctType'), ''),
    nullif(btrim(p_cabecalho->>'moeda'), ''),
    nullif(p_cabecalho->>'periodoInicio', '')::date,
    nullif(p_cabecalho->>'periodoFim', '')::date,
    nullif(p_cabecalho->>'saldoInicial', '')::numeric,
    nullif(p_cabecalho->>'saldoFinal', '')::numeric,
    v_total,
    p_created_by
  ) RETURNING id INTO v_importacao_id;

  FOR v_movimento IN SELECT * FROM jsonb_array_elements(p_movimentos) LOOP
    /*
     * A linha que já existe de outra importação NÃO é gravada de novo, e o
     * `ON CONFLICT DO NOTHING` faz isso sem abortar a transação. Contar como
     * repetida é o que permite a tela dizer "8 destes 34 já estavam aqui" em
     * vez de o usuário achar que perdeu movimento.
     */
    INSERT INTO public.ofx_movimento (
      importacao_id, banco_id, sequencia,
      fitid, checknum, refnum, tipo_ofx,
      data_postagem, data_disponivel,
      valor, valor_centavos, nome, memo,
      fingerprint, situacao_analise, score_match, observacao
    ) VALUES (
      v_importacao_id, p_banco_id,
      coalesce((v_movimento->>'sequencia')::integer, 0),
      nullif(btrim(coalesce(v_movimento->>'fitid', '')), ''),
      nullif(btrim(coalesce(v_movimento->>'checknum', '')), ''),
      nullif(btrim(coalesce(v_movimento->>'refnum', '')), ''),
      nullif(btrim(coalesce(v_movimento->>'tipoOfx', '')), ''),
      (v_movimento->>'dataPostagem')::date,
      nullif(v_movimento->>'dataDisponivel', '')::date,
      round((v_movimento->>'valorCentavos')::numeric / 100.0, 2),
      (v_movimento->>'valorCentavos')::bigint,
      nullif(btrim(coalesce(v_movimento->>'nome', '')), ''),
      nullif(btrim(coalesce(v_movimento->>'memo', '')), ''),
      v_movimento->>'fingerprint',
      nullif(v_movimento->>'situacao', ''),
      nullif(v_movimento->>'score', '')::integer,
      nullif(btrim(coalesce(v_movimento->>'observacao', '')), '')
    )
    ON CONFLICT (banco_id, fingerprint) DO NOTHING
    RETURNING id INTO v_id;

    IF v_id IS NULL THEN
      v_repetidos := v_repetidos + 1;
      SELECT id INTO v_id
        FROM public.ofx_movimento
       WHERE banco_id = p_banco_id AND fingerprint = v_movimento->>'fingerprint';
      v_resultado := v_resultado || jsonb_build_object(
        'fingerprint', v_movimento->>'fingerprint',
        'movimento_id', v_id,
        'repetido', true
      );
    ELSE
      v_importados := v_importados + 1;
      v_resultado := v_resultado || jsonb_build_object(
        'fingerprint', v_movimento->>'fingerprint',
        'movimento_id', v_id,
        'repetido', false
      );
    END IF;

    v_id := NULL;
  END LOOP;

  UPDATE public.ofx_importacao
     SET quantidade_importados = v_importados,
         quantidade_repetidos = v_repetidos
   WHERE id = v_importacao_id;

  RETURN jsonb_build_object(
    'importacao_id', v_importacao_id,
    'quantidade_movimentos', v_total,
    'quantidade_importados', v_importados,
    'quantidade_repetidos', v_repetidos,
    'movimentos', v_resultado
  );
END;
$function$;

ALTER FUNCTION public.registrar_importacao_ofx(bigint, text, text, jsonb, jsonb, uuid)
  OWNER TO postgres;

COMMENT ON FUNCTION public.registrar_importacao_ofx(bigint, text, text, jsonb, jsonb, uuid) IS
  'Grava um arquivo OFX e seus movimentos numa conta bancária, de uma vez. Recusa arquivo já importado e ignora movimento cujo fingerprint já existe na conta.';

-- ---------------------------------------------------------------------------
-- 5) Conciliar um movimento
-- ---------------------------------------------------------------------------
--
-- É AQUI que a atomicidade importa. Dar baixa num título e falhar ao marcar o
-- movimento como conciliado deixaria a próxima importação livre para dar a
-- mesma baixa outra vez. Como toda função plpgsql roda numa transação, o
-- caminho inteiro — baixa, criação, vínculo e a marcação — cai junto ou grava
-- junto.
--
-- O `FOR UPDATE` no movimento é o que serializa duas telas conciliando a mesma
-- linha ao mesmo tempo: a segunda espera, lê `status = 'CONCILIADO'` e recusa.
CREATE OR REPLACE FUNCTION public.conciliar_movimento_ofx(
  p_movimento_id bigint,
  p_acao text,
  p_transacao_id bigint DEFAULT NULL,
  p_valor numeric DEFAULT NULL,
  p_metodopagamento text DEFAULT NULL,
  p_plano_de_conta_id integer DEFAULT NULL,
  p_centro_custo_id integer DEFAULT NULL,
  p_nova jsonb DEFAULT NULL,
  p_usuario uuid DEFAULT NULL,
  p_observacao text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_mov public.ofx_movimento%ROWTYPE;
  v_imp public.ofx_importacao%ROWTYPE;
  v_tx public.transacao%ROWTYPE;
  v_acao text;
  v_data timestamptz;
  v_entrada boolean;
  v_alvo_centavos bigint;
  v_liquido_centavos bigint;
  v_saldo numeric(14,2);
  v_baixa numeric(14,2);
  v_resultado jsonb;
  v_transacao_id bigint;
  v_titulo_id bigint;
  v_tipo public.tipos_transacao;
  v_metodo public.metodo_pagamento;
  v_descricao text;
  v_acao_gravada text;
BEGIN
  v_acao := upper(btrim(coalesce(p_acao, '')));
  IF v_acao NOT IN ('VINCULAR', 'LIQUIDAR', 'CRIAR', 'IGNORAR') THEN
    RAISE EXCEPTION 'Ação de conciliação inválida: %.', p_acao USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_mov FROM public.ofx_movimento
   WHERE id = p_movimento_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Movimento do extrato não encontrado.' USING ERRCODE = 'P0002';
  END IF;
  IF v_mov.status <> 'PENDENTE' THEN
    RAISE EXCEPTION 'Este movimento do extrato já foi resolvido.' USING ERRCODE = '23505';
  END IF;

  SELECT * INTO v_imp FROM public.ofx_importacao WHERE id = v_mov.importacao_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Importação não encontrada.' USING ERRCODE = 'P0002';
  END IF;

  -- Meio-dia no fuso da oficina, igual ao que a rota de baixa já faz: ancorar na
  -- meia-noite deixaria o movimento sujeito a cair no dia anterior.
  v_data := (v_mov.data_postagem::text || ' 12:00:00-03')::timestamptz;
  v_entrada := v_mov.valor_centavos > 0;
  v_alvo_centavos := abs(v_mov.valor_centavos);

  -- ------------------------------------------------------------- ignorar
  IF v_acao = 'IGNORAR' THEN
    UPDATE public.ofx_movimento
       SET status = 'IGNORADO',
           acao_conciliacao = 'IGNORAR',
           observacao = coalesce(nullif(btrim(coalesce(p_observacao, '')), ''), observacao),
           conciliado_em = now(),
           conciliado_por = p_usuario
     WHERE id = p_movimento_id;

    RETURN jsonb_build_object('movimento_id', p_movimento_id, 'status', 'IGNORADO');
  END IF;

  -- ------------------------------------------------------------- vincular
  IF v_acao = 'VINCULAR' THEN
    IF p_transacao_id IS NULL THEN
      RAISE EXCEPTION 'Informe a transação a vincular.' USING ERRCODE = '22023';
    END IF;

    SELECT * INTO v_tx FROM public.transacao
     WHERE id = p_transacao_id AND is_deleted = false FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Transação não encontrada.' USING ERRCODE = 'P0002';
    END IF;
    IF coalesce(v_tx.pendente, false) THEN
      RAISE EXCEPTION
        'Este título ainda está em aberto. Use a baixa para liquidá-lo com o movimento do extrato.'
        USING ERRCODE = '22023';
    END IF;
    IF coalesce(v_tx.banco_id, 0) <> v_imp.banco_id THEN
      RAISE EXCEPTION
        'A transação não está na conta bancária deste extrato.' USING ERRCODE = '22023';
    END IF;
    IF (upper(v_tx.tipo::text) IN ('RECEITA', 'DEPOSITO')) <> v_entrada THEN
      RAISE EXCEPTION
        'O sentido não confere: o extrato mostra uma %, e a transação é %.',
        CASE WHEN v_entrada THEN 'entrada' ELSE 'saída' END, v_tx.tipo
        USING ERRCODE = '22023';
    END IF;

    v_liquido_centavos := round(public.transacao_valor_liquido_efetivo(v_tx) * 100)::bigint;
    IF v_liquido_centavos <> v_alvo_centavos THEN
      RAISE EXCEPTION
        'O valor não confere: o extrato mostra % e a transação movimenta %.',
        round(v_alvo_centavos / 100.0, 2), round(v_liquido_centavos / 100.0, 2)
        USING ERRCODE = '22023';
    END IF;

    v_transacao_id := v_tx.id;
    v_titulo_id := NULL;
    v_acao_gravada := 'VINCULAR';
  END IF;

  -- ------------------------------------------------------------- liquidar
  IF v_acao = 'LIQUIDAR' THEN
    IF p_transacao_id IS NULL THEN
      RAISE EXCEPTION 'Informe o título a liquidar.' USING ERRCODE = '22023';
    END IF;
    IF nullif(btrim(coalesce(p_metodopagamento, '')), '') IS NULL THEN
      RAISE EXCEPTION 'Informe a forma de pagamento da baixa.' USING ERRCODE = '22023';
    END IF;

    SELECT * INTO v_tx FROM public.transacao
     WHERE id = p_transacao_id AND is_deleted = false;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Título não encontrado.' USING ERRCODE = 'P0002';
    END IF;
    IF NOT coalesce(v_tx.pendente, false) THEN
      RAISE EXCEPTION 'Este título já foi baixado.' USING ERRCODE = '23505';
    END IF;
    IF (upper(v_tx.tipo::text) IN ('RECEITA', 'DEPOSITO')) <> v_entrada THEN
      RAISE EXCEPTION
        'O sentido não confere: o extrato mostra uma %, e o título é %.',
        CASE WHEN v_entrada THEN 'entrada' ELSE 'saída' END, v_tx.tipo
        USING ERRCODE = '22023';
    END IF;

    v_saldo := round(
      public.transacao_valor_liquido_efetivo(v_tx) - coalesce(v_tx.valor_baixado, 0), 2);
    v_baixa := round(coalesce(p_valor, v_saldo), 2);

    /*
     * O dinheiro da baixa tem que ser exatamente o dinheiro do extrato.
     *
     * Sem esta conferência a conciliação aceitaria baixar R$ 5.000 com um
     * movimento de R$ 2.000 e marcar a linha como resolvida — o extrato
     * "fecharia" com R$ 3.000 que nunca passaram pela conta.
     */
    IF round(v_baixa * 100)::bigint <> v_alvo_centavos THEN
      RAISE EXCEPTION
        'A baixa de % não corresponde ao movimento do extrato, que é de %.',
        v_baixa, round(v_alvo_centavos / 100.0, 2) USING ERRCODE = '22023';
    END IF;

    -- A baixa parcial, o saldo restante e a recusa por valor acima do saldo são
    -- todos da RPC de baixa. Aqui só se diz quanto foi pago.
    v_resultado := public.baixar_transacao_pendente(
      p_transacao_id := v_tx.id,
      p_pago_em := v_data,
      p_banco_id := v_imp.banco_id,
      p_metodopagamento := btrim(p_metodopagamento),
      p_plano_de_conta_id := p_plano_de_conta_id,
      p_centro_custo_id := p_centro_custo_id,
      p_baixado_por := p_usuario,
      p_valor := CASE WHEN v_baixa < v_saldo THEN v_baixa ELSE NULL END,
      p_valor_lancado := NULL
    );

    /*
     * Qual linha é o dinheiro?
     *
     * Na baixa de uma vez o próprio título vira o movimento de caixa: recebe
     * banco, data do pagamento e sai de pendente. Na parcial o título continua
     * aberto e quem carrega o dinheiro é a transação filha — é ela que aparece
     * no Fluxo, e é ela que o extrato representa.
     */
    IF coalesce((v_resultado->>'parcial')::boolean, false) THEN
      v_transacao_id := (v_resultado->>'baixa_id')::bigint;
      v_acao_gravada := 'BAIXA_PARCIAL';
    ELSE
      v_transacao_id := (v_resultado->>'id')::bigint;
      v_acao_gravada := 'LIQUIDAR';
    END IF;
    v_titulo_id := v_tx.id;

    IF v_transacao_id IS NULL THEN
      RAISE EXCEPTION
        'A baixa não devolveu o movimento de caixa correspondente.' USING ERRCODE = '22023';
    END IF;
  END IF;

  -- ------------------------------------------------------------- criar
  IF v_acao = 'CRIAR' THEN
    v_descricao := nullif(btrim(coalesce(p_nova->>'descricao', '')), '');
    v_descricao := coalesce(
      v_descricao,
      nullif(btrim(coalesce(v_mov.memo, '')), ''),
      nullif(btrim(coalesce(v_mov.nome, '')), ''),
      'Movimento bancário importado'
    );

    /*
     * O sentido do extrato manda; o usuário só escolhe entre os dois tipos
     * daquele sentido. Deixar o tipo livre permitiria transformar um débito em
     * receita, o que inverteria o resultado da empresa a partir de um extrato.
     */
    v_tipo := CASE
      WHEN v_entrada AND upper(coalesce(p_nova->>'tipo', '')) = 'DEPOSITO' THEN 'DEPOSITO'
      WHEN v_entrada THEN 'RECEITA'
      WHEN upper(coalesce(p_nova->>'tipo', '')) = 'SAQUE' THEN 'SAQUE'
      ELSE 'DESPESA'
    END::public.tipos_transacao;

    IF nullif(btrim(coalesce(p_metodopagamento, '')), '') IS NOT NULL THEN
      BEGIN
        v_metodo := btrim(p_metodopagamento)::public.metodo_pagamento;
      EXCEPTION WHEN OTHERS THEN
        RAISE EXCEPTION 'Forma de pagamento inválida: %.', btrim(p_metodopagamento)
          USING ERRCODE = '22023';
      END;
    ELSE
      v_metodo := NULL;
    END IF;

    INSERT INTO public.transacao (
      descricao, valor, valor_base, "valorLiquido",
      valor_acrescimos, valor_descontos,
      data, competencia_em, vencimento_em, pago_em,
      tipo, pendente, banco_id, metodopagamento,
      categoria, categoria_id, plano_de_conta_id, centro_custo_id,
      cliente_id, fornecedor_id, nomepagador, cpfcnpjpagador,
      created_by, baixado_por
    ) VALUES (
      v_descricao,
      round(v_alvo_centavos / 100.0, 2),
      round(v_alvo_centavos / 100.0, 2),
      round(v_alvo_centavos / 100.0, 2),
      0, 0,
      v_data,
      coalesce(nullif(p_nova->>'competencia_em', '')::timestamptz, v_data),
      v_data, v_data,
      v_tipo, false, v_imp.banco_id, v_metodo,
      coalesce(nullif(btrim(coalesce(p_nova->>'categoria', '')), ''), 'NÃO RELACIONADO'),
      nullif(p_nova->>'categoria_id', '')::integer,
      nullif(p_nova->>'plano_de_conta_id', '')::integer,
      nullif(p_nova->>'centro_custo_id', '')::integer,
      nullif(p_nova->>'cliente_id', '')::integer,
      nullif(p_nova->>'fornecedor_id', '')::integer,
      -- Colunas NOT NULL herdadas do desenho antigo da tabela. Tarifa bancária
      -- não tem pagador, e inventar um cadastro para ela seria pior.
      coalesce(nullif(btrim(coalesce(p_nova->>'nomepagador', '')), ''),
               nullif(btrim(coalesce(v_mov.nome, '')), ''),
               'Extrato bancário'),
      coalesce(nullif(btrim(coalesce(p_nova->>'cpfcnpjpagador', '')), ''), ''),
      p_usuario, p_usuario
    ) RETURNING id INTO v_transacao_id;

    v_titulo_id := NULL;
    v_acao_gravada := 'CRIAR';
  END IF;

  /*
   * A marcação fecha a operação. O índice único em `transacao_id` recusa aqui —
   * e derruba a baixa junto — se aquela transação já responde por outro
   * movimento do extrato.
   */
  UPDATE public.ofx_movimento
     SET status = 'CONCILIADO',
         acao_conciliacao = v_acao_gravada,
         transacao_id = v_transacao_id,
         titulo_origem_id = v_titulo_id,
         observacao = coalesce(nullif(btrim(coalesce(p_observacao, '')), ''), observacao),
         conciliado_em = now(),
         conciliado_por = p_usuario
   WHERE id = p_movimento_id;

  RETURN jsonb_build_object(
    'movimento_id', p_movimento_id,
    'status', 'CONCILIADO',
    'acao', v_acao_gravada,
    'transacao_id', v_transacao_id,
    'titulo_origem_id', v_titulo_id,
    'baixa', v_resultado
  );
END;
$function$;

