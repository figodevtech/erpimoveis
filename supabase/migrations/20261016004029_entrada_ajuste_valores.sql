CREATE TABLE public.entrada_valor_ajuste (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entrada_id bigint REFERENCES public.entrada(id) ON DELETE RESTRICT,
  usoconsumo_entrada_id bigint REFERENCES public.usoconsumo_entrada(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid NOT NULL,
  motivo text NOT NULL CHECK (length(btrim(motivo)) BETWEEN 1 AND 1000),
  versao integer NOT NULL,
  valor_anterior numeric(14,2) NOT NULL,
  valor_novo numeric(14,2) NOT NULL CHECK (valor_novo >= 0),
  itens jsonb NOT NULL CHECK (jsonb_typeof(itens) = 'array' AND jsonb_array_length(itens) > 0),
