-- Todas as operações monetárias do mesmo documento usam o mesmo bloqueio,
-- inclusive quando a chamada vem da outra metade de uma entrada mista.
CREATE FUNCTION public.contexto_valores_entrada(p_inventory text, p_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
DECLARE
  v_chave text;
  v_documento bigint;
  v_status text;
  v_produtos bigint[];
  v_uso bigint[];
  v_total numeric;
  v_original numeric;
  v_versoes jsonb;
  v_fiscal_original numeric;
  v_xml text;
  v_linhas_fiscais integer;
  v_total_uso numeric;
BEGIN
  IF p_inventory = 'produto' THEN
    SELECT notachave, fiscal_dfe_documento_id, status::text INTO v_chave, v_documento, v_status
      FROM public.entrada WHERE id = p_id;
  ELSIF p_inventory = 'usoconsumo' THEN
    SELECT chave_nfe, documento_fiscal_recebido_id, status::text INTO v_chave, v_documento, v_status
      FROM public.usoconsumo_entrada WHERE id = p_id;
  ELSE
    RAISE EXCEPTION 'Estoque inválido.' USING ERRCODE = '22023';
  END IF;
  IF v_status IS NULL THEN
    RAISE EXCEPTION 'Entrada não encontrada.' USING ERRCODE = 'P0002';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('entrada-valores:' || coalesce(
    nullif(v_chave, ''), 'documento:' || v_documento::text, p_inventory || ':' || p_id::text), 0));
  SELECT coalesce(array_agg(id ORDER BY id), '{}'::bigint[]) INTO v_produtos
    FROM public.entrada WHERE (p_inventory = 'produto' AND id = p_id)
      OR (v_status = 'CONFIRMADA' AND status::text = 'CONFIRMADA' AND (
        (v_documento IS NOT NULL AND fiscal_dfe_documento_id = v_documento)
        OR (nullif(v_chave, '') IS NOT NULL AND notachave = v_chave)));
  SELECT coalesce(array_agg(id ORDER BY id), '{}'::bigint[]) INTO v_uso
    FROM public.usoconsumo_entrada WHERE (p_inventory = 'usoconsumo' AND id = p_id)
      OR (v_status = 'CONFIRMADA' AND status::text = 'CONFIRMADA' AND (
        (v_documento IS NOT NULL AND documento_fiscal_recebido_id = v_documento)
        OR (nullif(v_chave, '') IS NOT NULL AND chave_nfe = v_chave)));
  PERFORM 1 FROM public.entrada WHERE id = ANY(v_produtos) ORDER BY id FOR UPDATE;
  PERFORM 1 FROM public.usoconsumo_entrada WHERE id = ANY(v_uso) ORDER BY id FOR UPDATE;
  -- A mesma ordem (revenda, depois estoques simples) também é usada pelo
  -- cancelamento misto. Releia o status depois de esperar pelos bloqueios.
  IF p_inventory = 'produto' THEN
    SELECT status::text INTO v_status FROM public.entrada WHERE id = p_id;
  ELSE
    SELECT status::text INTO v_status FROM public.usoconsumo_entrada WHERE id = p_id;
  END IF;
  IF v_status <> 'CONFIRMADA' THEN
    v_produtos := CASE WHEN p_inventory = 'produto' THEN ARRAY[p_id] ELSE '{}'::bigint[] END;
    v_uso := CASE WHEN p_inventory = 'usoconsumo' THEN ARRAY[p_id] ELSE '{}'::bigint[] END;
  END IF;
  SELECT coalesce(sum(valor_total), 0), coalesce(sum(original), 0),
    coalesce(jsonb_agg(jsonb_build_array(inventory, id, versao) ORDER BY inventory, id), '[]'::jsonb)
    INTO v_total, v_original, v_versoes
    FROM (
      SELECT 'produto' AS inventory, id, valor_total,
        coalesce(valor_total_original, valor_total) AS original, versao_valores AS versao
        FROM public.entrada WHERE id = ANY(v_produtos)
      UNION ALL
      SELECT 'usoconsumo', id, valor_total, coalesce(valor_total_original, valor_total), versao_valores
        FROM public.usoconsumo_entrada WHERE id = ANY(v_uso)
    ) entradas;
  -- Legado misto/híbrido guardava só os custos físicos nos dois cabeçalhos.
  -- O restante do vNF continua devido. Só recuperamos o total integral quando
  -- a consolidação garante a nota inteira, ou todas as linhas estão apropriadas.
  IF cardinality(v_produtos) > 0 AND cardinality(v_uso) > 0 THEN
    SELECT valor_fiscal_documento INTO v_fiscal_original FROM public.entrada_fiscal_personalizada
      WHERE documento_id = v_documento AND modalidade = 'HIBRIDA'
        AND (entrada_id = ANY(v_produtos) OR usoconsumo_entrada_id = ANY(v_uso)) LIMIT 1;
    IF v_fiscal_original IS NULL AND v_documento IS NOT NULL THEN
      SELECT xml INTO v_xml FROM public.fiscal_dfe_documento WHERE id = v_documento;
      BEGIN
        v_linhas_fiscais := cardinality(xpath('//*[local-name()="det"]', xmlparse(document v_xml)));
      EXCEPTION WHEN invalid_xml_document THEN v_linhas_fiscais := 0; END;
      IF v_linhas_fiscais > 0 AND (SELECT count(DISTINCT numero_item)
        FROM public.fiscal_dfe_item_apropriacao WHERE documento_id = v_documento
          AND cancelada_at IS NULL) = v_linhas_fiscais THEN
        SELECT valor_total INTO v_fiscal_original FROM public.fiscal_dfe_documento WHERE id = v_documento;
      END IF;
    END IF;
    IF v_fiscal_original IS NOT NULL THEN
      v_total := v_fiscal_original + v_total - v_original;
      v_original := v_fiscal_original;
    END IF;
  END IF;
  SELECT coalesce(sum(valor_total), 0) INTO v_total_uso FROM public.usoconsumo_entrada WHERE id = ANY(v_uso);
  RETURN jsonb_build_object('status', v_status, 'documento_id', v_documento,
    'entrada_id', v_produtos[1], 'usoconsumo_entrada_id', v_uso[1],
    'entrada_ids', to_jsonb(v_produtos), 'usoconsumo_entrada_ids', to_jsonb(v_uso),
    'valor_total', v_total, 'valor_total_original', v_original,
    'valor_total_produtos', CASE WHEN cardinality(v_produtos) > 0 THEN v_total - v_total_uso ELSE 0 END,
    'valor_total_usoconsumo', v_total_uso,
    'versao_financeiro', md5(v_versoes::text), 'versoes', v_versoes);
END;
$$;

CREATE FUNCTION public.ajustar_valores_entrada(
  p_inventory text, p_id bigint, p_itens jsonb, p_motivo text,
  p_versao_esperada integer, p_created_by uuid
) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
DECLARE
  v_contexto jsonb;
  v_entrada jsonb;
  v_item record;
  v_solicitado jsonb;
  v_unitario numeric;
  v_total numeric;
  v_delta numeric := 0;
  v_novo_total numeric;
  v_ultimo_id bigint;
  v_atualizou boolean;
  v_historico jsonb := '[]'::jsonb;
  v_auditoria_id bigint;
BEGIN
  v_contexto := public.contexto_valores_entrada(p_inventory, p_id);
  IF p_inventory = 'produto' THEN
    SELECT to_jsonb(e) INTO v_entrada FROM public.entrada e WHERE id = p_id;
  ELSE
    SELECT to_jsonb(e) INTO v_entrada FROM public.usoconsumo_entrada e WHERE id = p_id;
  END IF;
  IF v_entrada->>'status' <> 'CONFIRMADA' OR v_entrada->>'cancelada_at' IS NOT NULL THEN
    RAISE EXCEPTION 'Só é possível ajustar valores de entradas confirmadas.' USING ERRCODE = '55000';
  END IF;
  IF NOT coalesce((v_entrada->>'fiscal')::boolean, false) THEN
    RAISE EXCEPTION 'O ajuste de valores é exclusivo de entradas fiscais.' USING ERRCODE = '22023';
  END IF;
  IF p_versao_esperada IS NULL OR p_versao_esperada <> (v_entrada->>'versao_valores')::integer THEN
    RAISE EXCEPTION 'Os valores da entrada foram alterados. Recarregue e revise o ajuste.' USING ERRCODE = '40001';
  END IF;
  IF p_created_by IS NULL OR length(btrim(coalesce(p_motivo, ''))) NOT BETWEEN 1 AND 1000 THEN
    RAISE EXCEPTION 'Informe o usuário e o motivo do ajuste.' USING ERRCODE = '22023';
  END IF;
  IF p_itens IS NULL OR jsonb_typeof(p_itens) <> 'array'
    OR jsonb_array_length(p_itens) NOT BETWEEN 1 AND 990 THEN
    RAISE EXCEPTION 'Informe os itens do ajuste.' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (SELECT 1 FROM jsonb_array_elements(p_itens) i
      WHERE nullif(i->>'id', '') IS NULL OR (i->>'id')::bigint <= 0)
    OR (SELECT count(DISTINCT i->>'id') FROM jsonb_array_elements(p_itens) i) <> jsonb_array_length(p_itens) THEN
    RAISE EXCEPTION 'Os itens do ajuste são inválidos ou repetidos.' USING ERRCODE = '22023';
  END IF;
  -- Bloqueios de cadastro em ordem estável, antes de alterar qualquer item.
  IF p_inventory = 'produto' THEN
    IF (SELECT count(*) FROM public.entradaitens WHERE entrada_id = p_id
      AND id IN (SELECT (i->>'id')::bigint FROM jsonb_array_elements(p_itens) i)) <> jsonb_array_length(p_itens) THEN
      RAISE EXCEPTION 'Há itens que não pertencem à entrada.' USING ERRCODE = '22023';
    END IF;
    PERFORM 1 FROM public.produto WHERE id IN (SELECT produto_id FROM public.entradaitens
      WHERE entrada_id = p_id) ORDER BY id FOR UPDATE;
  ELSE
    IF (SELECT count(*) FROM public.usoconsumo_entrada_item WHERE entrada_id = p_id
      AND id IN (SELECT (i->>'id')::bigint FROM jsonb_array_elements(p_itens) i)) <> jsonb_array_length(p_itens) THEN
      RAISE EXCEPTION 'Há itens que não pertencem à entrada.' USING ERRCODE = '22023';
    END IF;
    PERFORM 1 FROM public.usoconsumo_item WHERE id IN (SELECT item_id FROM public.usoconsumo_entrada_item
      WHERE entrada_id = p_id) ORDER BY id FOR UPDATE;
  END IF;
  FOR v_item IN
    SELECT ei.id, ei.produto_id AS cadastro_id, ei.quantidade, ei.valor_unitario_compra,
      ei.valor_desconto, ei.valor_frete, ei.outras_despesas, ei.valor_total, ei.titulo
      FROM public.entradaitens ei WHERE p_inventory = 'produto' AND ei.entrada_id = p_id
        AND ei.id IN (SELECT (i->>'id')::bigint FROM jsonb_array_elements(p_itens) i)
    UNION ALL
    SELECT ei.id, ei.item_id, ei.quantidade, ei.valor_unitario_compra,
      ei.valor_desconto, ei.valor_frete, ei.outras_despesas, ei.valor_total, ei.titulo
      FROM public.usoconsumo_entrada_item ei WHERE p_inventory = 'usoconsumo' AND ei.entrada_id = p_id
        AND ei.id IN (SELECT (i->>'id')::bigint FROM jsonb_array_elements(p_itens) i)
    ORDER BY id
  LOOP
    SELECT i INTO v_solicitado FROM jsonb_array_elements(p_itens) i WHERE (i->>'id')::bigint = v_item.id;
    v_unitario := (v_solicitado->>'valorUnitarioCompra')::numeric;
    IF v_unitario IS NULL OR v_unitario::text IN ('NaN', 'Infinity', '-Infinity')
      OR v_unitario < 0 OR v_unitario > 9999999999.9999 OR round(v_unitario, 4) <> v_unitario THEN
      RAISE EXCEPTION 'Valor unitário inválido: use até quatro casas decimais e valor não negativo.' USING ERRCODE = '22023';
    END IF;
    IF v_unitario = v_item.valor_unitario_compra THEN CONTINUE; END IF;
    v_total := round(v_item.quantidade * v_unitario - v_item.valor_desconto
      + v_item.valor_frete + v_item.outras_despesas, 2);
    IF v_total < 0 OR v_total > 999999999999.99 THEN
      RAISE EXCEPTION 'O total do item está fora do intervalo permitido.' USING ERRCODE = '22023';
    END IF;
    v_atualizou := false;
    IF p_inventory = 'produto' THEN
      UPDATE public.entradaitens SET
        valor_unitario_compra_original = coalesce(valor_unitario_compra_original, valor_unitario_compra),
        valor_total_original = coalesce(valor_total_original, valor_total),
        valor_unitario_compra = v_unitario, valor_total = v_total, updated_at = now() WHERE id = v_item.id;
      SELECT ei.id INTO v_ultimo_id FROM public.entradaitens ei JOIN public.entrada e ON e.id = ei.entrada_id
        WHERE ei.produto_id = v_item.cadastro_id AND e.status::text = 'CONFIRMADA'
        ORDER BY e.created_at DESC, e.id DESC, ei.id DESC LIMIT 1;
      IF v_ultimo_id = v_item.id THEN
        UPDATE public.produto SET ultimovalordecompra = v_unitario, updatedat = now() WHERE id = v_item.cadastro_id;
        v_atualizou := true;
      END IF;
    ELSE
      UPDATE public.usoconsumo_entrada_item SET
        valor_unitario_compra_original = coalesce(valor_unitario_compra_original, valor_unitario_compra),
        valor_total_original = coalesce(valor_total_original, valor_total),
        valor_unitario_compra = v_unitario, valor_total = v_total WHERE id = v_item.id;
      SELECT ei.id INTO v_ultimo_id FROM public.usoconsumo_entrada_item ei
        JOIN public.usoconsumo_entrada e ON e.id = ei.entrada_id
        WHERE ei.item_id = v_item.cadastro_id AND e.status::text = 'CONFIRMADA'
        ORDER BY e.created_at DESC, e.id DESC, ei.id DESC LIMIT 1;
      IF v_ultimo_id = v_item.id THEN
        UPDATE public.usoconsumo_item SET ultimovalordecompra = v_unitario,
          updated_by = p_created_by WHERE id = v_item.cadastro_id;
        v_atualizou := true;
      END IF;
      SELECT ei.id INTO v_ultimo_id FROM public.usoconsumo_entrada_item ei
        JOIN public.usoconsumo_entrada e ON e.id = ei.entrada_id
        WHERE ei.item_id = v_item.cadastro_id AND e.status::text = 'CONFIRMADA'
          AND e.fornecedor_id = (v_entrada->>'fornecedor_id')::bigint
        ORDER BY e.created_at DESC, e.id DESC, ei.id DESC LIMIT 1;
      IF v_ultimo_id = v_item.id THEN
        UPDATE public.usoconsumo_fornecedor_item SET ultimo_valor_compra = v_unitario, updated_at = now()
          WHERE item_id = v_item.cadastro_id AND fornecedor_id = (v_entrada->>'fornecedor_id')::bigint;
      END IF;
    END IF;
    v_delta := v_delta + v_total - v_item.valor_total;
    v_historico := v_historico || jsonb_build_array(jsonb_build_object('id', v_item.id, 'titulo', v_item.titulo,
      'unitario_anterior', v_item.valor_unitario_compra, 'unitario_novo', v_unitario,
      'total_anterior', v_item.valor_total, 'total_novo', v_total, 'custo_cadastro_atualizado', v_atualizou));
  END LOOP;
  IF jsonb_array_length(v_historico) = 0 THEN
    RETURN jsonb_build_object('alterados', 0, 'valor_total', (v_entrada->>'valor_total')::numeric,
      'versao_valores', (v_entrada->>'versao_valores')::integer);
  END IF;
  v_novo_total := (v_entrada->>'valor_total')::numeric + v_delta;
  IF v_novo_total < 0 OR v_novo_total > 999999999999.99 THEN
    RAISE EXCEPTION 'O total da entrada está fora do intervalo permitido.' USING ERRCODE = '22023';
  END IF;
  IF p_inventory = 'produto' THEN
    UPDATE public.entrada SET valor_total_original = coalesce(valor_total_original, valor_total),
      valor_total = v_novo_total, versao_valores = versao_valores + 1 WHERE id = p_id;
  ELSE
    UPDATE public.usoconsumo_entrada SET valor_total_original = coalesce(valor_total_original, valor_total),
      valor_total = v_novo_total, versao_valores = versao_valores + 1 WHERE id = p_id;
  END IF;
  INSERT INTO public.entrada_valor_ajuste(entrada_id, usoconsumo_entrada_id, created_by, motivo,
    versao, valor_anterior, valor_novo, itens) VALUES (
    CASE WHEN p_inventory = 'produto' THEN p_id END, CASE WHEN p_inventory = 'usoconsumo' THEN p_id END,
    p_created_by, btrim(p_motivo), (v_entrada->>'versao_valores')::integer + 1,
    (v_entrada->>'valor_total')::numeric, v_novo_total, v_historico) RETURNING id INTO v_auditoria_id;
  RETURN jsonb_build_object('alterados', jsonb_array_length(v_historico), 'valor_total', v_novo_total,
    'versao_valores', (v_entrada->>'versao_valores')::integer + 1, 'ajuste_id', v_auditoria_id);
END;
$$;

-- Também usado pelo lançamento posterior: total, revisão, duplicidade, grupo
-- de parcelas e transações são conferidos/gravados na mesma transação.
CREATE FUNCTION public.registrar_financeiro_entrada(
  p_inventory text, p_id bigint, p_transacoes jsonb, p_versao_esperada text,
  p_created_by uuid, p_criar_grupo boolean DEFAULT true
) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
DECLARE
  v_contexto jsonb := public.contexto_valores_entrada(p_inventory, p_id);
  v_produtos bigint[];
  v_uso bigint[];
  v_total numeric;
  v_tx jsonb;
  v_grupo bigint;
  v_tx_id bigint;
  v_ids jsonb := '[]'::jsonb;
BEGIN
  IF v_contexto->>'status' <> 'CONFIRMADA' THEN
    RAISE EXCEPTION 'Não é possível lançar financeiro para uma entrada cancelada.' USING ERRCODE = '55000';
  END IF;
  IF p_versao_esperada IS NOT NULL AND p_versao_esperada <> v_contexto->>'versao_financeiro' THEN
    RAISE EXCEPTION 'O total da entrada foi alterado. Recarregue e revise o financeiro.' USING ERRCODE = '40001';
  END IF;
  SELECT coalesce(array_agg(value::bigint), '{}'::bigint[]) INTO v_produtos
    FROM jsonb_array_elements_text(v_contexto->'entrada_ids');
  SELECT coalesce(array_agg(value::bigint), '{}'::bigint[]) INTO v_uso
    FROM jsonb_array_elements_text(v_contexto->'usoconsumo_entrada_ids');
  IF EXISTS (SELECT 1 FROM public.transacao WHERE NOT is_deleted
      AND (entrada_id = ANY(v_produtos) OR usoconsumo_entrada_id = ANY(v_uso))) THEN
    RAISE EXCEPTION 'Esta entrada já possui lançamentos financeiros registrados no sistema.' USING ERRCODE = '55000';
  END IF;
  IF jsonb_typeof(p_transacoes) IS DISTINCT FROM 'array' OR jsonb_array_length(p_transacoes) = 0 THEN
    RAISE EXCEPTION 'Informe os lançamentos financeiros.' USING ERRCODE = '22023';
  END IF;
  SELECT round(sum((value->>'valor')::numeric), 2) INTO v_total FROM jsonb_array_elements(p_transacoes);
  IF v_total IS NULL OR v_total <= 0 OR v_total <> (v_contexto->>'valor_total')::numeric THEN
    RAISE EXCEPTION 'A soma dos lançamentos (%) deve ser igual ao total de compra atualizado da entrada (%).',
      v_total, v_contexto->>'valor_total' USING ERRCODE = '22023';
  END IF;
  IF p_criar_grupo AND jsonb_array_length(p_transacoes) > 1 THEN
    INSERT INTO public.transacao_parcelamento(descricao) VALUES (
      regexp_replace(p_transacoes->0->>'descricao', ' - Parcela [0-9]+/[0-9]+$', '')) RETURNING id INTO v_grupo;
  END IF;
  FOR v_tx IN SELECT value FROM jsonb_array_elements(p_transacoes) LOOP
    IF (v_tx->>'valor')::numeric IS NULL OR (v_tx->>'valor')::numeric <= 0
      OR (v_tx->>'valor')::numeric::text IN ('NaN', 'Infinity', '-Infinity') THEN
      RAISE EXCEPTION 'Todas as parcelas devem ter valor positivo.' USING ERRCODE = '22023';
    END IF;
    INSERT INTO public.transacao(descricao, valor, "valorLiquido", data, vencimento_em,
      metodopagamento, categoria, categoria_id, banco_id, plano_de_conta_id, plano_de_conta,
      centro_custo_id, centro_custo, nomepagador, cpfcnpjpagador, fornecedor_id, tipo,
      entrada_id, usoconsumo_entrada_id, origem, pendente, created_by, parcelamento_id)
    VALUES (v_tx->>'descricao', (v_tx->>'valor')::numeric,
      coalesce((v_tx->>'valorLiquido')::numeric, (v_tx->>'valor')::numeric),
      coalesce((v_tx->>'data')::timestamptz, now()), (v_tx->>'vencimento_em')::timestamptz,
      (v_tx->>'metodopagamento')::public.metodo_pagamento, v_tx->>'categoria',
      (v_tx->>'categoria_id')::bigint, (v_tx->>'banco_id')::bigint,
      (v_tx->>'plano_de_conta_id')::bigint, v_tx->>'plano_de_conta',
      (v_tx->>'centro_custo_id')::bigint, v_tx->>'centro_custo',
      v_tx->>'nomepagador', v_tx->>'cpfcnpjpagador', (v_tx->>'fornecedor_id')::bigint,
      'DESPESA'::public.tipos_transacao, (v_contexto->>'entrada_id')::bigint,
      (v_contexto->>'usoconsumo_entrada_id')::bigint,
      CASE WHEN cardinality(v_produtos) > 0 AND cardinality(v_uso) > 0 THEN 'ENTRADA_FISCAL_MISTA'
        WHEN p_inventory = 'usoconsumo' THEN 'USOCONSUMO_ENTRADA' ELSE v_tx->>'origem' END,
      coalesce((v_tx->>'pendente')::boolean, true), p_created_by, v_grupo)
      RETURNING id INTO v_tx_id;
    v_ids := v_ids || jsonb_build_array(jsonb_build_object('id', v_tx_id));
  END LOOP;
  RETURN jsonb_build_object('success', true, 'count', jsonb_array_length(v_ids), 'transacoes', v_ids);
END;
$$;

-- Os motores originais continuam validando quantidades, custo consolidado e
-- apropriações fiscais. O ajuste ocorre depois, antes de qualquer financeiro.
CREATE FUNCTION public.registrar_entrada_com_valores(
  p_modalidade text, p_parametros jsonb, p_ajustes jsonb, p_transacoes jsonb, p_created_by uuid
) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
DECLARE
  v_resultado jsonb;
  v_id bigint;
  v_uso_id bigint;
  v_inventory text;
  v_alvo_id bigint;
  v_linha jsonb;
  v_item_id bigint;
  v_itens jsonb;
  v_contexto jsonb;
  v_base numeric;
  v_cabecalhos numeric;
  v_chave text;
BEGIN
  IF p_ajustes IS NULL OR jsonb_typeof(p_ajustes->'itens') IS DISTINCT FROM 'array'
    OR jsonb_array_length(p_ajustes->'itens') = 0 THEN
    RAISE EXCEPTION 'Informe os ajustes de valores.' USING ERRCODE = '22023';
  END IF;
  v_chave := coalesce(p_parametros->'p_entrada'->>'notachave', p_parametros->'p_entrada'->>'chave_nfe',
    p_parametros->'p_entrada_produto'->>'notachave', p_parametros->'p_entrada_usoconsumo'->>'chave_nfe');
  IF nullif(v_chave, '') IS NOT NULL THEN
    PERFORM pg_advisory_xact_lock(hashtextextended('entrada-valores:' || v_chave, 0));
  END IF;
  CASE p_modalidade
    WHEN 'PRODUTO' THEN
      IF nullif(p_parametros->'p_entrada'->>'fiscal_dfe_documento_id', '') IS NOT NULL THEN
        v_resultado := public.registrar_entrada_comercial_apropriada(
          p_parametros->'p_entrada', p_parametros->'p_itens', '[]'::jsonb);
      ELSE
        v_resultado := public.registrar_entrada_confirmada(
          p_parametros->'p_entrada', p_parametros->'p_itens', '[]'::jsonb);
      END IF;
    WHEN 'USOCONSUMO' THEN
      v_resultado := public.registrar_entrada_usoconsumo(
        p_parametros->'p_entrada', p_parametros->'p_itens', '[]'::jsonb);
      v_resultado := v_resultado - 'entrada_id' || jsonb_build_object('usoconsumo_entrada_id', v_resultado->'entrada_id');
    WHEN 'MISTA' THEN
      v_resultado := public.registrar_entrada_fiscal_mista(p_parametros->'p_entrada_produto',
        p_parametros->'p_itens_produto', p_parametros->'p_entrada_usoconsumo', p_parametros->'p_itens_usoconsumo', '[]'::jsonb);
    WHEN 'PERSONALIZADA' THEN
      v_resultado := public.registrar_entrada_fiscal_personalizada(p_parametros->>'p_destino',
        p_parametros->'p_entrada', p_parametros->'p_item', p_parametros->'p_itens_fiscais',
        (p_parametros->>'p_custo_total')::numeric, '[]'::jsonb);
    WHEN 'HIBRIDA' THEN
      v_resultado := public.registrar_entrada_fiscal_hibrida(p_parametros->'p_entrada_produto',
        p_parametros->'p_itens_produto', p_parametros->'p_entrada_usoconsumo', p_parametros->'p_itens_usoconsumo',
        p_parametros->'p_apropriacoes', p_parametros->'p_auditoria', (p_parametros->>'p_custo_total')::numeric,
        (p_parametros->>'p_custo_personalizado')::numeric, (p_parametros->>'p_total_documento')::numeric, '[]'::jsonb);
    ELSE RAISE EXCEPTION 'Modalidade de entrada inválida.' USING ERRCODE = '22023';
  END CASE;
  v_id := (v_resultado->>'entrada_id')::bigint;
  v_uso_id := (v_resultado->>'usoconsumo_entrada_id')::bigint;
  IF v_id IS NOT NULL AND v_uso_id IS NOT NULL THEN
    v_base := CASE WHEN p_modalidade = 'HIBRIDA' THEN (p_parametros->>'p_total_documento')::numeric
      ELSE (p_parametros->'p_entrada_produto'->>'valor_total_documento')::numeric END;
    IF v_base IS NOT NULL THEN
      SELECT e.valor_total + ue.valor_total INTO v_cabecalhos FROM public.entrada e,
        public.usoconsumo_entrada ue WHERE e.id = v_id AND ue.id = v_uso_id;
      UPDATE public.entrada SET valor_total = valor_total + v_base - v_cabecalhos WHERE id = v_id;
    END IF;
  END IF;
  FOR v_inventory IN SELECT DISTINCT value->>'inventory' FROM jsonb_array_elements(p_ajustes->'itens') LOOP
    IF v_inventory NOT IN ('produto', 'usoconsumo') OR v_inventory IS NULL THEN
      RAISE EXCEPTION 'Estoque inválido no ajuste.' USING ERRCODE = '22023';
    END IF;
    v_alvo_id := CASE WHEN v_inventory = 'produto' THEN v_id ELSE v_uso_id END;
    IF v_alvo_id IS NULL THEN
      RAISE EXCEPTION 'O ajuste não corresponde a um estoque desta entrada.' USING ERRCODE = '22023';
    END IF;
    v_itens := '[]'::jsonb;
    FOR v_linha IN SELECT value FROM jsonb_array_elements(p_ajustes->'itens')
      WHERE value->>'inventory' = v_inventory LOOP
      IF v_inventory = 'produto' THEN
        SELECT id INTO STRICT v_item_id FROM public.entradaitens WHERE entrada_id = v_alvo_id
          AND ((numero_item_fiscal = (v_linha->>'numeroItemFiscal')::integer)
            OR (coalesce((v_linha->>'consolidado')::boolean, false) AND numero_item_fiscal IS NULL));
      ELSE
        SELECT id INTO STRICT v_item_id FROM public.usoconsumo_entrada_item WHERE entrada_id = v_alvo_id
          AND ((numero_item_fiscal = (v_linha->>'numeroItemFiscal')::integer)
            OR (coalesce((v_linha->>'consolidado')::boolean, false) AND numero_item_fiscal IS NULL));
      END IF;
      v_itens := v_itens || jsonb_build_array(jsonb_build_object('id', v_item_id,
        'valorUnitarioCompra', v_linha->'valorUnitarioCompra'));
    END LOOP;
    PERFORM public.ajustar_valores_entrada(v_inventory, v_alvo_id, v_itens, p_ajustes->>'motivo', 0, p_created_by);
  END LOOP;
  v_inventory := CASE WHEN v_id IS NOT NULL THEN 'produto' ELSE 'usoconsumo' END;
  v_alvo_id := coalesce(v_id, v_uso_id);
  v_contexto := public.contexto_valores_entrada(v_inventory, v_alvo_id);
  IF jsonb_array_length(coalesce(p_transacoes, '[]'::jsonb)) > 0 THEN
    PERFORM public.registrar_financeiro_entrada(v_inventory, v_alvo_id, p_transacoes,
      v_contexto->>'versao_financeiro', p_created_by, false);
  END IF;
  -- Preserva a forma da resposta do motor de uso/consumo.
  IF p_modalidade = 'USOCONSUMO' THEN
    v_resultado := v_resultado || jsonb_build_object('entrada_id', v_uso_id);
  END IF;
  IF p_modalidade IN ('PERSONALIZADA', 'HIBRIDA') THEN
    v_resultado := v_resultado || jsonb_build_object('custo_total_estoque',
      coalesce((SELECT sum(valor_total) FROM public.entradaitens WHERE entrada_id = v_id), 0)
      + coalesce((SELECT sum(valor_total) FROM public.usoconsumo_entrada_item WHERE entrada_id = v_uso_id), 0));
  END IF;
  IF p_modalidade = 'HIBRIDA' THEN
    v_resultado := v_resultado || jsonb_build_object('custo_personalizado',
      coalesce((SELECT sum(valor_total) FROM public.entradaitens WHERE entrada_id = v_id AND numero_item_fiscal IS NULL), 0)
      + coalesce((SELECT sum(valor_total) FROM public.usoconsumo_entrada_item WHERE entrada_id = v_uso_id AND numero_item_fiscal IS NULL), 0));
  END IF;
  RETURN v_resultado || jsonb_build_object('valor_total', v_contexto->'valor_total');
END;
$$;

REVOKE ALL ON FUNCTION public.entrada_valor_ajuste_imutavel() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.contexto_valores_entrada(text,bigint) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.ajustar_valores_entrada(text,bigint,jsonb,text,integer,uuid) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.registrar_financeiro_entrada(text,bigint,jsonb,text,uuid,boolean) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.registrar_entrada_com_valores(text,jsonb,jsonb,jsonb,uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.contexto_valores_entrada(text,bigint) TO service_role;
GRANT EXECUTE ON FUNCTION public.ajustar_valores_entrada(text,bigint,jsonb,text,integer,uuid) TO service_role;
GRANT EXECUTE ON FUNCTION public.registrar_financeiro_entrada(text,bigint,jsonb,text,uuid,boolean) TO service_role;
GRANT EXECUTE ON FUNCTION public.registrar_entrada_com_valores(text,jsonb,jsonb,jsonb,uuid) TO service_role;

COMMIT;
