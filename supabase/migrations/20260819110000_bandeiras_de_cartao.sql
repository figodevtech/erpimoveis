-- Bandeiras de cartao: a taxa da maquineta deixa de ser digitada de cabeca.
--
-- O PROBLEMA
-- Hoje o dialog de transacao tem uma chave "Taxa de recebimento" que revela um
-- campo de valor liquido em branco. Quem recebe R$ 1.000,00 no credito em 3x
-- precisa saber de cor que a Sicredi cobra 5,20% naquela faixa, fazer a conta na
-- calculadora e digitar R$ 948,00. Erra-se a faixa, erra-se a conta, e o que
-- sobra no banco e um liquido sem nenhum registro de como chegou ali.
--
-- O DESENHO
-- Uma bandeira e a combinacao (conta bancaria, metodo de pagamento, nome): a
-- Visa credito da Sicredi e uma linha, a Visa credito da Stone e outra, porque
-- as taxas sao outras. Pendurada nela, uma tabela de faixas: quais contagens de
-- parcela aquela bandeira aceita e quanto cobra em cada uma.
--
-- POR QUE A TAXA E CONGELADA NA TRANSACAO
-- `bandeira_taxa_percentual` repete na transacao o percentual usado no momento
-- do lancamento. Sem isso, uma renegociacao de taxa reescreveria o historico:
-- o relatorio do ano passado passaria a calcular com o preco de hoje. Mesma
-- razao pela qual `transacao.categoria` guarda o nome ao lado de `categoria_id`.
--
-- O ESCAPE
-- A adquirente as vezes cobra diferente do combinado — antecipacao, campanha,
-- ajuste retroativo. O liquido calculado fica travado na tela, mas ha um botao
-- que o destrava; quando isso acontece, `bandeira_taxa_ajustada` marca a linha.
-- E o que permite o relatorio separar "taxa que saiu da tabela" de "taxa que
-- alguem digitou por cima", em vez de misturar as duas e nao confiar em nenhuma.
BEGIN;

-- ---------------------------------------------------------------------------
-- 1) A bandeira
--
-- `metodo_pagamento` e enum e varia por empresa (o Demir usa DEBITO AUTOMATICO,
-- CHEQUE e CREDITO EM CONTA, que nao existem nos outros bancos). Usar o proprio
-- tipo em vez de texto livre garante que uma bandeira nao possa apontar para um
-- metodo que aquele banco nao conhece.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.bandeira_cartao (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  descricao text,
  banco_id bigint NOT NULL REFERENCES public.bancoconta(id) ON DELETE CASCADE,
  metodopagamento public.metodo_pagamento NOT NULL,
  ativo boolean NOT NULL DEFAULT true,
  createdat timestamp with time zone NOT NULL DEFAULT now(),
  updatedat timestamp with time zone NOT NULL DEFAULT now(),

  CONSTRAINT bandeira_cartao_nome_nao_vazio CHECK (btrim(nome) <> '')
);

-- Duas "Visa credito" na mesma conta seriam indistinguiveis no seletor. Em
-- contas ou metodos diferentes, sao bandeiras diferentes e convivem.
CREATE UNIQUE INDEX IF NOT EXISTS bandeira_cartao_unica_por_conta
  ON public.bandeira_cartao (banco_id, metodopagamento, lower(btrim(nome)));

-- O seletor do dialog sempre busca por este par.
CREATE INDEX IF NOT EXISTS bandeira_cartao_busca_idx
  ON public.bandeira_cartao (banco_id, metodopagamento)
  WHERE ativo;

ALTER TABLE public.bandeira_cartao OWNER TO postgres;

-- ---------------------------------------------------------------------------
-- 2) As faixas de parcela
--
-- A tabela responde duas perguntas de uma vez: QUAIS contagens a bandeira aceita
-- (as linhas que existem) e QUANTO cobra em cada uma. Nao ha faixa implicita —
-- uma bandeira sem a linha de 6x simplesmente nao oferece 6x no seletor.
--
-- Taxa zero e permitida de proposito: debito em algumas negociacoes e isento, e
-- a alternativa seria o usuario deixar a faixa fora da tabela e perder o registro
-- de que ela existe.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.bandeira_cartao_parcela (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bandeira_id integer NOT NULL REFERENCES public.bandeira_cartao(id) ON DELETE CASCADE,
  parcelas smallint NOT NULL,
  taxa_percentual numeric(6,4) NOT NULL,

  CONSTRAINT bandeira_cartao_parcela_quantidade_check
    CHECK (parcelas >= 1 AND parcelas <= 36),
  CONSTRAINT bandeira_cartao_parcela_taxa_check
    CHECK (taxa_percentual >= 0 AND taxa_percentual <= 100),
  CONSTRAINT bandeira_cartao_parcela_unica UNIQUE (bandeira_id, parcelas)
);

CREATE INDEX IF NOT EXISTS bandeira_cartao_parcela_bandeira_idx
  ON public.bandeira_cartao_parcela (bandeira_id, parcelas);

ALTER TABLE public.bandeira_cartao_parcela OWNER TO postgres;

-- ---------------------------------------------------------------------------
-- 3) A marca na transacao
--
-- Tudo anulavel: a esmagadora maioria dos lancamentos nao passa por maquineta, e
-- quem nao cadastrar bandeira nenhuma nao ve diferenca em lugar nenhum.
-- ---------------------------------------------------------------------------

ALTER TABLE public.transacao
  ADD COLUMN IF NOT EXISTS bandeira_id integer
    REFERENCES public.bandeira_cartao(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS bandeira_parcelas smallint,
  ADD COLUMN IF NOT EXISTS bandeira_taxa_percentual numeric(6,4),
  ADD COLUMN IF NOT EXISTS bandeira_taxa_ajustada boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.transacao.bandeira_parcelas IS
  'Em quantas vezes o cliente passou no cartao. Nem sempre igual ao numero de parcelas da transacao: no recebimento a vista o dinheiro entra de uma vez e este campo guarda o parcelamento que o cliente fez na maquineta.';

COMMENT ON COLUMN public.transacao.bandeira_taxa_percentual IS
  'Percentual usado no lancamento, congelado. Mudar a tabela da bandeira nao reescreve o que ja foi registrado.';

COMMENT ON COLUMN public.transacao.bandeira_taxa_ajustada IS
  'O usuario destravou o liquido calculado e digitou outro valor por cima da tabela da bandeira.';

-- Sem bandeira nao ha parcelamento de maquineta nem taxa congelada para guardar.
-- O CHECK existe para o relatorio poder confiar que os quatro campos contam a
-- mesma historia; a rota valida antes para a tela receber uma frase.
ALTER TABLE public.transacao
  DROP CONSTRAINT IF EXISTS transacao_bandeira_coerente;

ALTER TABLE public.transacao
  ADD CONSTRAINT transacao_bandeira_coerente CHECK (
    bandeira_id IS NOT NULL
    OR (
      bandeira_parcelas IS NULL
      AND bandeira_taxa_percentual IS NULL
      AND bandeira_taxa_ajustada = false
    )
  );

CREATE INDEX IF NOT EXISTS transacao_bandeira_idx
  ON public.transacao (bandeira_id)
  WHERE bandeira_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- 4) Permissoes
--
-- Mesmo recorte de tipos_ajuste_transacao: a aplicacao le e escreve pela
-- serviceRole, e o cliente so precisa enxergar o catalogo.
-- ---------------------------------------------------------------------------

GRANT SELECT ON TABLE public.bandeira_cartao TO anon, authenticated;
GRANT ALL ON TABLE public.bandeira_cartao TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.bandeira_cartao_id_seq TO service_role;

GRANT SELECT ON TABLE public.bandeira_cartao_parcela TO anon, authenticated;
GRANT ALL ON TABLE public.bandeira_cartao_parcela TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.bandeira_cartao_parcela_id_seq TO service_role;

COMMIT;
