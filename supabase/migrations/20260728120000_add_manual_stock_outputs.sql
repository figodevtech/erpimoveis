-- Saidas manuais de estoque, independentes de vendas e ordens de servico.
BEGIN;

CREATE TABLE IF NOT EXISTS public.estoque_saida (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  motivo text NOT NULL,
  observacao text,
  status text NOT NULL DEFAULT 'CONFIRMADA',
  created_by uuid,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT estoque_saida_motivo_check CHECK (
    motivo IN (
      'USO_INTERNO', 'AVARIA', 'PERDA', 'FURTO', 'VENCIMENTO',
      'DOACAO', 'TRANSFERENCIA', 'AJUSTE_INVENTARIO', 'OUTRO'
    )
  ),
  CONSTRAINT estoque_saida_status_check CHECK (status IN ('CONFIRMADA', 'CANCELADA')),
  CONSTRAINT estoque_saida_outro_observacao_check CHECK (
    motivo <> 'OUTRO' OR nullif(btrim(observacao), '') IS NOT NULL
  )
);

CREATE TABLE IF NOT EXISTS public.estoque_saida_item (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  saida_id bigint NOT NULL REFERENCES public.estoque_saida(id) ON DELETE RESTRICT,
  produto_id integer NOT NULL REFERENCES public.produto(id) ON DELETE RESTRICT,
  quantidade integer NOT NULL CHECK (quantidade > 0),
  saldo_anterior integer NOT NULL,
  saldo_resultante integer NOT NULL CHECK (saldo_resultante >= 0),
  valor_custo_aplicado numeric(14,4) NOT NULL DEFAULT 0 CHECK (valor_custo_aplicado >= 0),
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  UNIQUE (saida_id, produto_id)
);

CREATE INDEX IF NOT EXISTS estoque_saida_item_produto_idx
  ON public.estoque_saida_item(produto_id, created_at DESC);
CREATE INDEX IF NOT EXISTS estoque_saida_created_at_idx
  ON public.estoque_saida(created_at DESC);

CREATE OR REPLACE FUNCTION public.registrar_saida_estoque(
  p_produto_id integer,
  p_quantidade integer,
  p_motivo text,
  p_observacao text DEFAULT NULL,
  p_created_by uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_produto public.produto%ROWTYPE;
  v_saida_id bigint;
  v_motivo text := upper(btrim(coalesce(p_motivo, '')));
  v_observacao text := nullif(btrim(p_observacao), '');
  v_saldo_anterior integer;
  v_saldo_resultante integer;
  v_custo numeric(14,4);
BEGIN
  IF p_produto_id IS NULL OR p_produto_id <= 0 THEN
    RAISE EXCEPTION 'Produto invalido.' USING ERRCODE = '22023';
  END IF;
  IF p_quantidade IS NULL OR p_quantidade <= 0 THEN
    RAISE EXCEPTION 'A quantidade deve ser maior que zero.' USING ERRCODE = '22023';
  END IF;
  IF v_motivo NOT IN (
    'USO_INTERNO', 'AVARIA', 'PERDA', 'FURTO', 'VENCIMENTO',
    'DOACAO', 'TRANSFERENCIA', 'AJUSTE_INVENTARIO', 'OUTRO'
  ) THEN
    RAISE EXCEPTION 'Motivo de saida invalido.' USING ERRCODE = '22023';
  END IF;
  IF v_motivo = 'OUTRO' AND v_observacao IS NULL THEN
    RAISE EXCEPTION 'Informe a observacao para o motivo Outro.' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_produto
  FROM public.produto
  WHERE id = p_produto_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Produto nao encontrado.' USING ERRCODE = 'P0002';
  END IF;

  v_saldo_anterior := coalesce(v_produto.estoque, 0)::integer;
  IF v_saldo_anterior < p_quantidade THEN
    RAISE EXCEPTION 'Estoque insuficiente. Disponivel: %, solicitado: %.', v_saldo_anterior, p_quantidade
      USING ERRCODE = '23514';
  END IF;
  v_saldo_resultante := v_saldo_anterior - p_quantidade;
  v_custo := greatest(coalesce(v_produto.ultimovalordecompra, v_produto.precocompra, 0), 0);

  INSERT INTO public.estoque_saida (motivo, observacao, created_by)
  VALUES (v_motivo, v_observacao, p_created_by)
  RETURNING id INTO v_saida_id;

  INSERT INTO public.estoque_saida_item (
    saida_id, produto_id, quantidade, saldo_anterior, saldo_resultante, valor_custo_aplicado
  ) VALUES (
    v_saida_id, p_produto_id, p_quantidade, v_saldo_anterior, v_saldo_resultante, v_custo
  );

  UPDATE public.produto
  SET estoque = v_saldo_resultante,
      updatedat = now()
  WHERE id = p_produto_id;

  RETURN jsonb_build_object(
    'saida_id', v_saida_id,
    'saldo_anterior', v_saldo_anterior,
    'saldo_resultante', v_saldo_resultante
  );
END;
$$;

ALTER TABLE public.estoque_saida OWNER TO postgres;
ALTER TABLE public.estoque_saida_item OWNER TO postgres;
ALTER FUNCTION public.registrar_saida_estoque(integer, integer, text, text, uuid) OWNER TO postgres;

REVOKE ALL ON TABLE public.estoque_saida FROM anon, authenticated;
REVOKE ALL ON TABLE public.estoque_saida_item FROM anon, authenticated;
REVOKE ALL ON FUNCTION public.registrar_saida_estoque(integer, integer, text, text, uuid) FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.estoque_saida TO service_role;
GRANT ALL ON TABLE public.estoque_saida_item TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.estoque_saida_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.estoque_saida_item_id_seq TO service_role;
GRANT EXECUTE ON FUNCTION public.registrar_saida_estoque(integer, integer, text, text, uuid) TO service_role;

COMMIT;
