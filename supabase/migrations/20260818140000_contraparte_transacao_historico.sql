-- Trocar o pagador/recebedor de uma transacao passa a deixar rastro.
--
-- A aba "Cliente" do dialog era so leitura: dava para ver quem estava vinculado,
-- nao para corrigir. Quem lancou o pagamento no cliente errado — ou registrou o
-- pagador em texto livre e depois cadastrou a pessoa — nao tinha caminho pela
-- tela, e o conserto ia direto no banco.
--
-- Abrir a edicao exige registrar quem trocou o que. `transacao.updated_by` diz
-- que a linha mudou, mas nao O QUE mudou; e uma troca de contraparte e
-- exatamente o tipo de alteracao que alguem vai querer auditar depois — ela
-- muda de quem e o titulo, e com isso o score do cliente e os relatorios por
-- contraparte.
--
-- O historico guarda os ids E o texto do momento. So os ids nao bastam: o
-- cadastro pode ser renomeado ou excluido depois, e o historico viraria uma
-- linha de numeros sem nome. E a mesma escolha de snapshot que a comissao ja faz.
BEGIN;

CREATE TABLE IF NOT EXISTS public.transacao_contraparte_historico (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Sem FK, como no historico de valores: o rastro sobrevive a exclusao da
  -- transacao, que e justamente quando ele mais importa.
  transacao_id bigint NOT NULL,

  cliente_anterior_id bigint,
  cliente_novo_id bigint,
  fornecedor_anterior_id bigint,
  fornecedor_novo_id bigint,

  -- Como a contraparte se chamava, no momento da troca.
  nome_anterior text,
  nome_novo text,
  documento_anterior text,
  documento_novo text,

  alterado_por uuid,
  created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS transacao_contraparte_historico_transacao_idx
  ON public.transacao_contraparte_historico(transacao_id, created_at DESC);

COMMENT ON TABLE public.transacao_contraparte_historico IS
  'Trocas de pagador/recebedor de uma transacao. Imutavel: corrigir uma correcao gera linha nova.';

CREATE OR REPLACE FUNCTION public.proteger_transacao_contraparte_historico()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  RAISE EXCEPTION 'O historico de pagador/recebedor e imutavel.' USING ERRCODE = '55000';
END;
$$;

DROP TRIGGER IF EXISTS trg_proteger_transacao_contraparte_historico
  ON public.transacao_contraparte_historico;
CREATE TRIGGER trg_proteger_transacao_contraparte_historico
  BEFORE UPDATE OR DELETE ON public.transacao_contraparte_historico
  FOR EACH ROW EXECUTE FUNCTION public.proteger_transacao_contraparte_historico();

ALTER TABLE public.transacao_contraparte_historico OWNER TO postgres;
ALTER FUNCTION public.proteger_transacao_contraparte_historico() OWNER TO postgres;
REVOKE ALL ON TABLE public.transacao_contraparte_historico FROM anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.transacao_contraparte_historico TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.transacao_contraparte_historico_id_seq TO service_role;

-- O registro e feito por gatilho, nao pela rota.
--
-- Assim ele e atomico com o proprio UPDATE — nao existe o estado "a troca foi
-- gravada mas o rastro se perdeu" — e vale para qualquer caminho de escrita, nao
-- so o PATCH do dialog. O autor sai de `updated_by`, que a rota passou a
-- preencher; sem sessao ele fica nulo, e a linha do historico continua valendo
-- pelo que mudou e quando.
CREATE OR REPLACE FUNCTION public.tg_transacao_contraparte_historico()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF new.cliente_id IS NOT DISTINCT FROM old.cliente_id
     AND new.fornecedor_id IS NOT DISTINCT FROM old.fornecedor_id
     AND new.nomepagador IS NOT DISTINCT FROM old.nomepagador
     AND new.cpfcnpjpagador IS NOT DISTINCT FROM old.cpfcnpjpagador THEN
    RETURN new;
  END IF;

  INSERT INTO public.transacao_contraparte_historico (
    transacao_id,
    cliente_anterior_id, cliente_novo_id,
    fornecedor_anterior_id, fornecedor_novo_id,
    nome_anterior, nome_novo,
    documento_anterior, documento_novo,
    alterado_por
  ) VALUES (
    new.id,
    old.cliente_id, new.cliente_id,
    old.fornecedor_id, new.fornecedor_id,
    old.nomepagador, new.nomepagador,
    old.cpfcnpjpagador, new.cpfcnpjpagador,
    new.updated_by
  );

  RETURN new;
END;
$$;

ALTER FUNCTION public.tg_transacao_contraparte_historico() OWNER TO postgres;

DROP TRIGGER IF EXISTS transacao_contraparte_historico_trg ON public.transacao;
CREATE TRIGGER transacao_contraparte_historico_trg
  AFTER UPDATE ON public.transacao
  FOR EACH ROW EXECUTE FUNCTION public.tg_transacao_contraparte_historico();

COMMIT;
