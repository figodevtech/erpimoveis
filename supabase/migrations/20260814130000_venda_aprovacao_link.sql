-- Aprovação pública de orçamentos de venda e textos separados por finalidade.
BEGIN;

ALTER TABLE public.venda
  ADD COLUMN IF NOT EXISTS descricao text,
  ADD COLUMN IF NOT EXISTS statusaprovacao public.enum_status_aprovacao;

COMMENT ON COLUMN public.venda.descricao IS
  'Descrição comercial da venda, visível ao cliente na impressão e na aprovação.';
COMMENT ON COLUMN public.venda.observacoes IS
  'Observações internas da venda; só aparecem na impressão quando solicitadas.';
COMMENT ON COLUMN public.venda.statusaprovacao IS
  'Resposta do orçamento: nulo quando nunca enviado, PENDENTE, APROVADA ou REPROVADA.';

CREATE TABLE IF NOT EXISTS public.vendaaprovacao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendaid integer NOT NULL REFERENCES public.venda(id) ON DELETE CASCADE,
  token uuid NOT NULL UNIQUE,
  expira_em timestamptz NOT NULL,
  usado_em timestamptz,
  invalidado_em timestamptz,
  motivo_invalidacao text,
  origem text,
  resultado public.enum_status_aprovacao,
  aprovador_doc text,
  aprovador_usuario_id uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT vendaaprovacao_origem_valida
    CHECK (origem IS NULL OR origem IN ('LINK', 'INTERNA')),
  CONSTRAINT vendaaprovacao_resposta_coerente
    CHECK (
      (usado_em IS NULL AND resultado IS NULL)
      OR (usado_em IS NOT NULL AND resultado IN ('APROVADA', 'REPROVADA'))
    )
);

CREATE INDEX IF NOT EXISTS vendaaprovacao_venda_idx
  ON public.vendaaprovacao (vendaid, created_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS vendaaprovacao_uma_ativa_por_venda_idx
  ON public.vendaaprovacao (vendaid)
  WHERE usado_em IS NULL AND invalidado_em IS NULL;

ALTER TABLE public.vendaaprovacao ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.vendaaprovacao FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.vendaaprovacao TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.vendaaprovacao_id_seq TO service_role;

-- Invalida links sem apagar o histórico. A função também é usada pelos fluxos
-- de aprovação manual, cancelamento e reversão para orçamento.
CREATE OR REPLACE FUNCTION public.invalidar_aprovacoes_venda(
  p_venda_id integer,
  p_motivo text DEFAULT 'ORCAMENTO_ALTERADO'
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_quantidade integer;
BEGIN
  UPDATE public.vendaaprovacao
     SET invalidado_em = now(),
         motivo_invalidacao = nullif(btrim(p_motivo), '')
   WHERE vendaid = p_venda_id
     AND usado_em IS NULL
     AND invalidado_em IS NULL;

  GET DIAGNOSTICS v_quantidade = ROW_COUNT;
  RETURN v_quantidade;
END;
$$;

-- Uma proposta alterada deixa de ser a proposta que o cliente recebeu. Campos
-- internos, financeiros e fiscais não entram aqui porque não são exibidos no
-- link público.
CREATE OR REPLACE FUNCTION public.tg_invalidar_aprovacao_venda_alterada()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_venda_id integer;
  v_invalidacoes integer := 0;
BEGIN
  -- OLD/NEW são records dinâmicos. Referenciar OLD.venda_id no mesmo CASE
  -- executado para `venda` faz o Postgres tentar resolver uma coluna que não
  -- existe nessa tabela, mesmo que o primeiro ramo do CASE seja o escolhido.
  IF TG_TABLE_NAME = 'venda' THEN
    IF TG_OP = 'DELETE' THEN
      v_venda_id := OLD.id;
    ELSE
      v_venda_id := NEW.id;
    END IF;
  ELSIF TG_OP = 'DELETE' THEN
    v_venda_id := OLD.venda_id;
  ELSE
    v_venda_id := NEW.venda_id;
  END IF;
  v_invalidacoes := public.invalidar_aprovacoes_venda(v_venda_id, 'ORCAMENTO_ALTERADO');

  IF v_invalidacoes > 0 THEN
    UPDATE public.venda
       SET statusaprovacao = NULL,
           updatedat = now()
     WHERE id = v_venda_id;
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_venda_invalidar_aprovacao_alterada ON public.venda;
CREATE TRIGGER trg_venda_invalidar_aprovacao_alterada
AFTER UPDATE OF clienteid, descricao, desconto_tipo, desconto_valor, valor_frete, sub_total, valortotal
ON public.venda
FOR EACH ROW
WHEN (
  OLD.clienteid IS DISTINCT FROM NEW.clienteid
  OR OLD.descricao IS DISTINCT FROM NEW.descricao
  OR OLD.desconto_tipo IS DISTINCT FROM NEW.desconto_tipo
  OR OLD.desconto_valor IS DISTINCT FROM NEW.desconto_valor
  OR OLD.valor_frete IS DISTINCT FROM NEW.valor_frete
  OR OLD.sub_total IS DISTINCT FROM NEW.sub_total
  OR OLD.valortotal IS DISTINCT FROM NEW.valortotal
)
EXECUTE FUNCTION public.tg_invalidar_aprovacao_venda_alterada();

DROP TRIGGER IF EXISTS trg_venda_status_invalidar_aprovacao ON public.venda;
CREATE TRIGGER trg_venda_status_invalidar_aprovacao
AFTER UPDATE OF status ON public.venda
FOR EACH ROW
WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION public.tg_invalidar_aprovacao_venda_alterada();

CREATE OR REPLACE FUNCTION public.tg_venda_resetar_aprovacao_ao_orcamento()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.status::text = 'ORCAMENTO' AND OLD.status::text IS DISTINCT FROM 'ORCAMENTO' THEN
    NEW.statusaprovacao := NULL;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_venda_resetar_aprovacao_ao_orcamento ON public.venda;
CREATE TRIGGER trg_venda_resetar_aprovacao_ao_orcamento
BEFORE UPDATE OF status ON public.venda
FOR EACH ROW
EXECUTE FUNCTION public.tg_venda_resetar_aprovacao_ao_orcamento();

DROP TRIGGER IF EXISTS trg_vendaproduto_invalidar_aprovacao ON public.vendaproduto;
CREATE TRIGGER trg_vendaproduto_invalidar_aprovacao
AFTER INSERT OR UPDATE OR DELETE ON public.vendaproduto
FOR EACH ROW
EXECUTE FUNCTION public.tg_invalidar_aprovacao_venda_alterada();

-- A criação passa a gravar todos os dados na mesma transação dos itens e do
-- estoque. A rota valida e normaliza os pagamentos antes de chamar a função.
CREATE OR REPLACE FUNCTION public.fn_criar_venda_com_itens(p_venda jsonb)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_cliente_id integer := (p_venda->>'clienteId')::integer;
  v_created_by uuid := (p_venda->>'created_by')::uuid;
  v_status public.enum_status_venda := (p_venda->>'status')::public.enum_status_venda;
  v_baixar_estoque boolean := coalesce((p_venda->>'baixarEstoque')::boolean, true);
  v_valor_frete numeric(14,2) := round(coalesce(nullif(p_venda->>'valorFrete', '')::numeric, 0), 2);
  v_venda_id integer;
  v_item jsonb;
  v_produto_id integer;
  v_quantidade integer;
  v_comissao numeric;
BEGIN
  IF v_cliente_id IS NULL OR v_created_by IS NULL OR v_status IS NULL
     OR p_venda->>'subTotal' IS NULL OR p_venda->>'valorTotal' IS NULL THEN
    RAISE EXCEPTION 'Campos obrigatórios ausentes em p_venda.' USING ERRCODE = 'P0001';
  END IF;
  IF v_valor_frete < 0 THEN
    RAISE EXCEPTION 'O valor do frete não pode ser negativo.' USING ERRCODE = 'P0001';
  END IF;
  IF jsonb_typeof(p_venda->'itens') <> 'array' OR jsonb_array_length(p_venda->'itens') = 0 THEN
    RAISE EXCEPTION 'p_venda.itens deve possuir ao menos um item.' USING ERRCODE = 'P0001';
  END IF;

  SELECT coalesce(comissao_venda_percent, 0)
    INTO v_comissao
    FROM public.usuario
   WHERE id = v_created_by;

  INSERT INTO public.venda (
    clienteid, created_by, vendedor, status, statusaprovacao,
    forma_pagamento, pagamentos_previstos, parcelas_pagamento,
    descricao, observacoes, descricao_financeiro, observacoes_fiscais, garantia,
    sub_total, valortotal, desconto_tipo, desconto_valor, valor_frete, datavenda,
    comissao_venda_percent_aplicada, categoriavendaid
  ) VALUES (
    v_cliente_id,
    v_created_by,
    coalesce(nullif(p_venda->>'vendedor', '')::uuid, v_created_by),
    v_status,
    NULL,
    nullif(p_venda->>'formaPagamento', ''),
    nullif(p_venda->'pagamentosPrevistos', 'null'::jsonb),
    nullif(p_venda->>'parcelasPagamento', '')::integer,
    nullif(btrim(p_venda->>'descricao'), ''),
    nullif(btrim(p_venda->>'observacoes'), ''),
    nullif(btrim(p_venda->>'descricaoFinanceiro'), ''),
    nullif(btrim(p_venda->>'observacoesFiscais'), ''),
    nullif(btrim(p_venda->>'garantia'), ''),
    (p_venda->>'subTotal')::numeric,
    (p_venda->>'valorTotal')::numeric,
    nullif(p_venda->>'descontoTipo', '')::public.enum_tipo_desconto_venda,
    nullif(p_venda->>'descontoValor', '')::numeric,
    v_valor_frete,
    coalesce(nullif(p_venda->>'dataVenda', '')::timestamp, now()),
    v_comissao,
    nullif(p_venda->>'categoriaVendaId', '')::integer
  ) RETURNING id INTO v_venda_id;

  IF v_baixar_estoque THEN
    PERFORM public.estoque_definir_contexto(
      'VENDA', v_venda_id::bigint, 'Venda #' || v_venda_id, v_created_by
    );
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_venda->'itens') LOOP
    v_produto_id := (v_item->>'produtoId')::integer;
    v_quantidade := (v_item->>'quantidade')::integer;
    IF v_produto_id IS NULL OR v_quantidade IS NULL OR v_quantidade <= 0 THEN
      RAISE EXCEPTION 'Cada item deve possuir produtoId e quantidade > 0.' USING ERRCODE = 'P0001';
    END IF;

    IF v_baixar_estoque THEN
      PERFORM public.fn_baixa_estoque_produto(v_produto_id, v_quantidade);
    END IF;

    INSERT INTO public.vendaproduto (
      venda_id, produtoid, quantidade, sub_total, valor_total, valor_desconto, tipo_desconto
    ) VALUES (
      v_venda_id, v_produto_id, v_quantidade,
      (v_item->>'subTotal')::numeric, (v_item->>'valorTotal')::numeric,
      nullif(v_item->>'valorDesconto', '')::numeric,
      nullif(v_item->>'tipoDesconto', '')::public.enum_tipo_desconto_venda
    );

    IF v_baixar_estoque THEN
      INSERT INTO public.vendaproduto_baixa (venda_id, produtoid, quantidade, updated_at)
      VALUES (v_venda_id, v_produto_id, v_quantidade, now())
      ON CONFLICT (venda_id, produtoid) DO UPDATE
        SET quantidade = excluded.quantidade, updated_at = now();
    END IF;
  END LOOP;

  RETURN v_venda_id;
END;
$$;

-- Aprovação feita por um usuário interno. Os dados opcionais já chegam
-- normalizados pela API e são gravados junto com status e estoque.
CREATE OR REPLACE FUNCTION public.aprovar_orcamento_venda(
  p_venda_id integer,
  p_dados jsonb DEFAULT NULL,
  p_usuario_id uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_venda public.venda%ROWTYPE;
BEGIN
  SELECT * INTO v_venda
    FROM public.venda
   WHERE id = p_venda_id
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Venda não encontrada.' USING ERRCODE = 'P0002';
  END IF;
  IF v_venda.status::text <> 'ORCAMENTO' THEN
    RAISE EXCEPTION 'Apenas orçamentos podem ser aprovados.' USING ERRCODE = '22023';
  END IF;

  PERFORM public.invalidar_aprovacoes_venda(p_venda_id, 'APROVACAO_INTERNA');
  PERFORM public.fn_baixar_estoque_venda(p_venda_id);

  UPDATE public.venda
     SET status = 'PAGAMENTO',
         statusaprovacao = 'APROVADA',
         forma_pagamento = CASE
           WHEN p_dados ? 'formaPagamento' THEN nullif(p_dados->>'formaPagamento', '')
           ELSE forma_pagamento END,
         pagamentos_previstos = CASE
           WHEN p_dados ? 'pagamentosPrevistos' THEN nullif(p_dados->'pagamentosPrevistos', 'null'::jsonb)
           ELSE pagamentos_previstos END,
         parcelas_pagamento = CASE
           WHEN p_dados ? 'parcelasPagamento' THEN nullif(p_dados->>'parcelasPagamento', '')::integer
           ELSE parcelas_pagamento END,
         descricao = CASE
           WHEN p_dados ? 'descricao' THEN nullif(btrim(p_dados->>'descricao'), '')
           ELSE descricao END,
         observacoes = CASE
           WHEN p_dados ? 'observacoes' THEN nullif(btrim(p_dados->>'observacoes'), '')
           ELSE observacoes END,
         descricao_financeiro = CASE
           WHEN p_dados ? 'descricaoFinanceiro' THEN nullif(btrim(p_dados->>'descricaoFinanceiro'), '')
           ELSE descricao_financeiro END,
         observacoes_fiscais = CASE
           WHEN p_dados ? 'observacoesFiscais' THEN nullif(btrim(p_dados->>'observacoesFiscais'), '')
           ELSE observacoes_fiscais END,
         garantia = CASE
           WHEN p_dados ? 'garantia' THEN nullif(btrim(p_dados->>'garantia'), '')
           ELSE garantia END,
         updated_by = coalesce(p_usuario_id, updated_by),
         updatedat = now()
   WHERE id = p_venda_id;

  RETURN jsonb_build_object(
    'vendaId', p_venda_id,
    'status', 'PAGAMENTO',
    'statusaprovacao', 'APROVADA'
  );
END;
$$;

