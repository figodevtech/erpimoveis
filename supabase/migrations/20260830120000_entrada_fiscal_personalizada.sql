-- Entrada fiscal personalizada: todos os itens fiscais de uma NF-e sao
-- consolidados em uma unica linha fisica de qualquer um dos tres estoques.
--
-- Os motores existentes continuam sendo a unica autoridade sobre saldo,
-- movimentos, financeiro e DRE. Esta migration apenas os orquestra numa RPC
-- atomica e registra a trilha que explica a excecao ao vinculo linha a linha.

BEGIN;

CREATE TABLE IF NOT EXISTS public.entrada_fiscal_personalizada (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento_id bigint NOT NULL
    REFERENCES public.fiscal_dfe_documento(id) ON DELETE RESTRICT,
  destino text NOT NULL
    CHECK (destino IN ('ESTOQUE', 'USOCONSUMO', 'GERAL')),
  entrada_id bigint REFERENCES public.entrada(id) ON DELETE RESTRICT,
  usoconsumo_entrada_id bigint
    REFERENCES public.usoconsumo_entrada(id) ON DELETE RESTRICT,
  itens_originais jsonb NOT NULL,
  custo_total_estoque numeric(14,2) NOT NULL
    CHECK (custo_total_estoque >= 0),
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT entrada_fiscal_personalizada_vinculo_check CHECK (
    (destino = 'ESTOQUE' AND entrada_id IS NOT NULL AND usoconsumo_entrada_id IS NULL)
    OR
    (destino IN ('USOCONSUMO', 'GERAL') AND entrada_id IS NULL AND usoconsumo_entrada_id IS NOT NULL)
  ),
  CONSTRAINT entrada_fiscal_personalizada_itens_check CHECK (
    jsonb_typeof(itens_originais) = 'array'
    AND jsonb_array_length(itens_originais) > 0
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS entrada_fiscal_personalizada_entrada_uk
  ON public.entrada_fiscal_personalizada(entrada_id)
  WHERE entrada_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS entrada_fiscal_personalizada_usoconsumo_uk
  ON public.entrada_fiscal_personalizada(usoconsumo_entrada_id)
  WHERE usoconsumo_entrada_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS entrada_fiscal_personalizada_documento_idx
  ON public.entrada_fiscal_personalizada(documento_id, created_at DESC);

COMMENT ON TABLE public.entrada_fiscal_personalizada IS
  'Auditoria das NF-e cujas linhas fiscais foram consolidadas em um unico item de estoque.';
COMMENT ON COLUMN public.entrada_fiscal_personalizada.itens_originais IS
  'Snapshot imutavel das linhas do XML apropriadas pela entrada personalizada.';

ALTER TABLE public.entrada_fiscal_personalizada ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.entrada_fiscal_personalizada FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.entrada_fiscal_personalizada TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.entrada_fiscal_personalizada_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.registrar_entrada_fiscal_personalizada(
  p_destino text,
  p_entrada jsonb,
  p_item jsonb,
  p_itens_fiscais jsonb,
  p_custo_total numeric,
  p_transacoes jsonb DEFAULT '[]'::jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_destino text := upper(btrim(coalesce(p_destino, '')));
  v_documento_id bigint;
  v_resultado jsonb;
  v_entrada_id bigint;
  v_usoconsumo_entrada_id bigint;
  v_linha jsonb;
  v_numero_item integer;
  v_quantidade_fiscal numeric(14,4);
  v_numeros integer[] := ARRAY[]::integer[];
  v_created_by uuid := nullif(p_entrada->>'created_by', '')::uuid;
BEGIN
  IF v_destino NOT IN ('ESTOQUE', 'USOCONSUMO', 'GERAL') THEN
    RAISE EXCEPTION 'Destino da entrada personalizada invalido.' USING ERRCODE = '22023';
  END IF;
  IF jsonb_typeof(p_item) <> 'object' THEN
    RAISE EXCEPTION 'Informe o item consolidado da entrada personalizada.' USING ERRCODE = '22023';
  END IF;
  IF jsonb_typeof(p_itens_fiscais) <> 'array' OR jsonb_array_length(p_itens_fiscais) = 0 THEN
    RAISE EXCEPTION 'A entrada personalizada exige os itens originais da NF-e.' USING ERRCODE = '22023';
  END IF;
  IF p_custo_total IS NULL OR p_custo_total < 0 THEN
    RAISE EXCEPTION 'O custo total da entrada personalizada e invalido.' USING ERRCODE = '22023';
  END IF;

  v_documento_id := CASE
    WHEN v_destino = 'ESTOQUE'
      THEN nullif(p_entrada->>'fiscal_dfe_documento_id', '')::bigint
    ELSE nullif(p_entrada->>'documento_fiscal_recebido_id', '')::bigint
  END;
  IF v_documento_id IS NULL THEN
    RAISE EXCEPTION 'Informe o documento fiscal recebido.' USING ERRCODE = '22023';
  END IF;

  -- Serializa entradas personalizadas concorrentes da mesma NF-e. Entradas
  -- normais continuam protegidas pelo indice unico das apropriacoes.
  PERFORM 1 FROM public.fiscal_dfe_documento
    WHERE id = v_documento_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Documento fiscal recebido nao encontrado.' USING ERRCODE = 'P0002';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.fiscal_dfe_item_apropriacao
     WHERE documento_id = v_documento_id AND cancelada_at IS NULL
  ) THEN
    RAISE EXCEPTION 'A entrada personalizada exige uma NF-e ainda nao apropriada.' USING ERRCODE = '23505';
  END IF;

  -- Valida nItem e quantidade antes de criar qualquer saldo.
  FOR v_linha IN SELECT value FROM jsonb_array_elements(p_itens_fiscais)
  LOOP
    v_numero_item := nullif(v_linha->>'numero_item', '')::integer;
    v_quantidade_fiscal := nullif(v_linha->>'quantidade', '')::numeric;
    IF v_numero_item IS NULL OR v_numero_item < 1 OR v_numero_item > 990
       OR v_quantidade_fiscal IS NULL OR v_quantidade_fiscal <= 0 THEN
      RAISE EXCEPTION 'Os itens originais da NF-e sao invalidos.' USING ERRCODE = '22023';
    END IF;
    IF v_numero_item = ANY(v_numeros) THEN
      RAISE EXCEPTION 'O item fiscal % foi informado mais de uma vez.', v_numero_item
        USING ERRCODE = '22023';
    END IF;
    v_numeros := array_append(v_numeros, v_numero_item);
  END LOOP;

  IF v_destino = 'ESTOQUE' THEN
    SELECT public.registrar_entrada_confirmada(
      p_entrada,
      jsonb_build_array(p_item),
      p_transacoes
    ) INTO v_resultado;
    v_entrada_id := (v_resultado->>'entrada_id')::bigint;
  ELSE
    -- Sem o documento durante a chamada, o motor de uso/consumo nao tenta criar
    -- a apropriacao linha a linha. O vinculo volta logo abaixo, na mesma transacao.
    SELECT public.registrar_entrada_usoconsumo(
      p_entrada - 'documento_fiscal_recebido_id',
      jsonb_build_array(p_item),
      p_transacoes
    ) INTO v_resultado;
    v_usoconsumo_entrada_id := (v_resultado->>'entrada_id')::bigint;

    UPDATE public.usoconsumo_entrada
       SET documento_fiscal_recebido_id = v_documento_id
     WHERE id = v_usoconsumo_entrada_id;
  END IF;

  FOR v_linha IN SELECT value FROM jsonb_array_elements(p_itens_fiscais)
  LOOP
    INSERT INTO public.fiscal_dfe_item_apropriacao(
      documento_id, numero_item, destino, entrada_id,
      usoconsumo_entrada_id, quantidade, created_by
    ) VALUES (
      v_documento_id,
      (v_linha->>'numero_item')::integer,
      CASE WHEN v_destino = 'ESTOQUE' THEN 'PRODUTO' ELSE 'USOCONSUMO' END,
      v_entrada_id,
      v_usoconsumo_entrada_id,
      (v_linha->>'quantidade')::numeric,
      v_created_by
    );
  END LOOP;

  INSERT INTO public.entrada_fiscal_personalizada(
    documento_id, destino, entrada_id, usoconsumo_entrada_id,
    itens_originais, custo_total_estoque, created_by
  ) VALUES (
    v_documento_id, v_destino, v_entrada_id, v_usoconsumo_entrada_id,
    p_itens_fiscais, round(p_custo_total, 2), v_created_by
  );

  RETURN v_resultado || jsonb_build_object(
    'destino', v_destino,
    'entrada_id', v_entrada_id,
    'usoconsumo_entrada_id', v_usoconsumo_entrada_id,
    'custo_total_estoque', round(p_custo_total, 2)
  );
END;
$$;

REVOKE ALL ON FUNCTION public.registrar_entrada_fiscal_personalizada(
  text, jsonb, jsonb, jsonb, numeric, jsonb
) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.registrar_entrada_fiscal_personalizada(
  text, jsonb, jsonb, jsonb, numeric, jsonb
) TO service_role;

NOTIFY pgrst, 'reload schema';

COMMIT;
