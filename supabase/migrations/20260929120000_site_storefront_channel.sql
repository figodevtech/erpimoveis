create or replace function public.fn_reservar_sincronizacao_site(
  p_limit integer default 50,
  p_empresa_id integer default null
)
returns table (
  queue_id bigint,
  event_id uuid,
  empresa_id integer,
  product_link_id bigint,
  produto_id integer,
  desired_version bigint,
  attempts integer
)
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with candidates as (
    select q.id
      from public.site_catalog_sync_queue q
     where (
         q.status in ('PENDENTE', 'ERRO')
         or (q.status = 'PROCESSANDO' and q.locked_at < now() - interval '15 minutes')
       )
       and (q.next_retry_at is null or q.next_retry_at <= now())
       and (p_empresa_id is null or q.empresa_id = p_empresa_id)
     order by q.created_at, q.id
     for update skip locked
     limit least(greatest(coalesce(p_limit, 50), 1), 100)
  ), reserved as (
    update public.site_catalog_sync_queue q
       set status = 'PROCESSANDO',
           attempts = q.attempts + 1,
           locked_at = now(),
           updated_at = now()
      from candidates c
     where q.id = c.id
     returning q.*
  )
  select
    r.id,
    r.event_id,
    r.empresa_id,
    r.product_link_id,
    r.produto_id,
    r.desired_version,
    r.attempts
  from reserved r
  order by r.created_at, r.id;
end;
$$;

create or replace function public.fn_concluir_sincronizacao_site(
  p_queue_id bigint,
  p_desired_version bigint,
  p_success boolean,
  p_error text default null
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_queue public.site_catalog_sync_queue%rowtype;
  v_changed boolean;
  v_delay_minutes integer;
begin
  select * into v_queue
    from public.site_catalog_sync_queue
   where id = p_queue_id
   for update;

  if not found then
    return 'NAO_ENCONTRADA';
  end if;

  v_changed := v_queue.desired_version <> p_desired_version;

  if p_success and not v_changed then
    update public.site_catalog_sync_queue
       set status = 'PROCESSADA',
           locked_at = null,
           next_retry_at = null,
           last_error = null,
           processed_at = now(),
           updated_at = now()
     where id = p_queue_id;

    update public.site_product_link
       set sync_status = 'SINCRONIZADO',
           last_synced_at = now(),
           last_sync_error = null,
           updated_at = now()
     where id = v_queue.product_link_id
       and sync_version = p_desired_version;

    return 'PROCESSADA';
  end if;

  if p_success and v_changed then
    update public.site_catalog_sync_queue
       set status = 'PENDENTE',
           locked_at = null,
           next_retry_at = null,
           last_error = null,
           processed_at = null,
           updated_at = now()
     where id = p_queue_id;
    return 'REATIVADA';
  end if;

  if not p_success and v_changed then
    update public.site_catalog_sync_queue
       set status = 'PENDENTE',
           locked_at = null,
           next_retry_at = null,
           last_error = null,
           processed_at = null,
           updated_at = now()
     where id = p_queue_id;
    return 'REATIVADA';
  end if;

  v_delay_minutes := least(5 * power(2, greatest(v_queue.attempts - 1, 0))::integer, 360);

  update public.site_catalog_sync_queue
     set status = 'ERRO',
         locked_at = null,
         next_retry_at = now() + make_interval(mins => v_delay_minutes),
         last_error = left(coalesce(p_error, 'Falha ao sincronizar com a loja.'), 2000),
         processed_at = null,
         updated_at = now()
   where id = p_queue_id;

  update public.site_product_link
     set sync_status = 'ERRO',
         last_sync_error = left(coalesce(p_error, 'Falha ao sincronizar com a loja.'), 2000),
         updated_at = now()
   where id = v_queue.product_link_id;

  return 'ERRO';
end;
$$;

create or replace view public.site_catalog_export
with (security_invoker = true)
as
select
  link.id as product_link_id,
  link.empresa_id,
  p.id as produto_id,
  link.sync_version,
  link.status,
  link.sync_status,
  link.last_synced_at,
  link.last_sync_error,
  coalesce(nullif(btrim(link.titulo_site), ''), nullif(btrim(p."tituloMarketplace"), ''), p.titulo) as titulo,
  coalesce(nullif(btrim(link.descricao_site), ''), nullif(btrim(p."descricaoMarketplace"), ''), '') as descricao,
  case when link.usar_preco_erp then p.precovenda else link.preco_site end as preco,
  least(
    greatest(coalesce(p.estoque, 0) - link.estoque_seguranca, 0),
    coalesce(link.estoque_maximo_site, 2147483647)
  )::integer as estoque,
  p.referencia,
  p.fabricante,
  p.grupo_produto_id,
  grupo.nome as grupo_nome,
  p."imgUrl" as imagem_principal,
  p.conservacao,
  p.codigobarras,
  link.destaque,
  link.slug,
  (
    link.status = 'PUBLICADO'
    and coalesce(p.is_deleted, false) = false
    and coalesce(grupo.ativo, true) = true
    and coalesce(case when link.usar_preco_erp then p.precovenda else link.preco_site end, 0) > 0
  ) as visible,
  greatest(link.updated_at, coalesce(p.updatedat, p.createdat), coalesce(grupo.updatedat, grupo.createdat)) as source_updated_at
from public.site_product_link link
join public.produto p on p.id = link.produto_id
left join public.produtogrupo grupo on grupo.id = p.grupo_produto_id;

