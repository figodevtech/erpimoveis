begin;

create table if not exists public.site_product_link (
  id bigint generated by default as identity primary key,
  empresa_id integer not null references public.empresa(id) on delete cascade,
  produto_id integer not null references public.produto(id) on delete cascade,
  status text not null default 'RASCUNHO'
    check (status in ('RASCUNHO', 'PUBLICADO', 'PAUSADO', 'ERRO')),
  titulo_site text,
  descricao_site text,
  usar_preco_erp boolean not null default true,
  preco_site numeric(14,2)
    check (preco_site is null or preco_site >= 0),
  estoque_seguranca integer not null default 0
    check (estoque_seguranca >= 0),
  estoque_maximo_site integer
    check (estoque_maximo_site is null or estoque_maximo_site >= 0),
  destaque boolean not null default false,
  slug text,
  url_publica text,
  sync_version bigint not null default 0,
  sync_status text not null default 'NAO_SINCRONIZADO'
    check (sync_status in ('NAO_SINCRONIZADO', 'PENDENTE', 'SINCRONIZADO', 'ERRO')),
  last_synced_at timestamptz,
  last_sync_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (empresa_id, produto_id),
  unique (empresa_id, slug)
);

comment on table public.site_product_link is
  'Configuração do produto no canal Loja própria. Não interfere em produto.exibirPdv.';
comment on column public.site_product_link.usar_preco_erp is
  'Quando true, publica produto.precovenda. Quando false, exige preco_site.';
comment on column public.site_product_link.estoque_seguranca is
  'Quantidade mantida fora do saldo publicável da loja.';

create index if not exists idx_site_product_link_status
  on public.site_product_link (empresa_id, status, produto_id);
create index if not exists idx_site_product_link_sync
  on public.site_product_link (empresa_id, sync_status, updated_at);

create table if not exists public.site_catalog_sync_queue (
  id bigint generated by default as identity primary key,
  empresa_id integer not null references public.empresa(id) on delete cascade,
  product_link_id bigint not null
    references public.site_product_link(id) on delete cascade,
  produto_id integer not null references public.produto(id) on delete cascade,
  event_id uuid not null default gen_random_uuid(),
  desired_version bigint not null,
  status text not null default 'PENDENTE'
    check (status in ('PENDENTE', 'PROCESSANDO', 'PROCESSADA', 'ERRO')),
  attempts integer not null default 0 check (attempts >= 0),
  locked_at timestamptz,
  next_retry_at timestamptz,
  last_error text,
  processed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_link_id),
  unique (event_id)
);

create index if not exists idx_site_catalog_sync_queue_pending
  on public.site_catalog_sync_queue (status, next_retry_at, created_at)
  where status in ('PENDENTE', 'ERRO');

create table if not exists public.site_catalog_sync_run (
  id bigint generated by default as identity primary key,
  run_id uuid not null default gen_random_uuid() unique,
  empresa_id integer references public.empresa(id) on delete set null,
  status text not null default 'EXECUTANDO'
    check (status in ('EXECUTANDO', 'SUCESSO', 'PARCIAL', 'ERRO')),
  requested_count integer not null default 0,
  success_count integer not null default 0,
  error_count integer not null default 0,
  error_summary text,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

create or replace function public.fn_enfileirar_site_product_link(
  p_product_link_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_link public.site_product_link%rowtype;
begin
  update public.site_product_link
     set sync_version = sync_version + 1,
         sync_status = 'PENDENTE',
         last_sync_error = null,
         updated_at = now()
   where id = p_product_link_id
   returning * into v_link;

  if not found then
    return;
  end if;

  insert into public.site_catalog_sync_queue (
    empresa_id,
    product_link_id,
    produto_id,
    event_id,
    desired_version,
    status,
    attempts,
    locked_at,
    next_retry_at,
    last_error,
    processed_at,
    updated_at
  ) values (
    v_link.empresa_id,
    v_link.id,
    v_link.produto_id,
    gen_random_uuid(),
    v_link.sync_version,
    'PENDENTE',
    0,
    null,
    null,
    null,
    null,
    now()
  )
  on conflict (product_link_id) do update
     set event_id = excluded.event_id,
         desired_version = excluded.desired_version,
         status = case
           when site_catalog_sync_queue.status = 'PROCESSANDO'
             then 'PROCESSANDO'
           else 'PENDENTE'
         end,
         attempts = case
           when site_catalog_sync_queue.status = 'PROCESSANDO'
             then site_catalog_sync_queue.attempts
           else 0
         end,
         locked_at = case
           when site_catalog_sync_queue.status = 'PROCESSANDO'
             then site_catalog_sync_queue.locked_at
           else null
         end,
         next_retry_at = null,
         last_error = null,
         processed_at = null,
         updated_at = now();
end;
$$;

create or replace function public.fn_site_product_link_changed()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.fn_enfileirar_site_product_link(new.id);
  return new;
end;
$$;

drop trigger if exists trg_site_product_link_changed on public.site_product_link;
create trigger trg_site_product_link_changed
after insert or update of
  status,
  titulo_site,
  descricao_site,
  usar_preco_erp,
  preco_site,
  estoque_seguranca,
  estoque_maximo_site,
  destaque,
  slug
on public.site_product_link
for each row execute function public.fn_site_product_link_changed();

create or replace function public.fn_site_product_changed()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_link_id bigint;
begin
  for v_link_id in
    select id
      from public.site_product_link
     where produto_id = new.id
       and status <> 'RASCUNHO'
  loop
    perform public.fn_enfileirar_site_product_link(v_link_id);
  end loop;
  return new;
end;
$$;

drop trigger if exists trg_site_product_changed on public.produto;
create trigger trg_site_product_changed
after update of
  titulo,
  "tituloMarketplace",
  "descricaoMarketplace",
  precovenda,
  estoque,
  referencia,
  fabricante,
  grupo_produto_id,
  "imgUrl",
  conservacao,
  codigobarras,
  is_deleted
on public.produto
for each row
when (
  old.titulo is distinct from new.titulo
  or old."tituloMarketplace" is distinct from new."tituloMarketplace"
  or old."descricaoMarketplace" is distinct from new."descricaoMarketplace"
  or old.precovenda is distinct from new.precovenda
  or old.estoque is distinct from new.estoque
  or old.referencia is distinct from new.referencia
  or old.fabricante is distinct from new.fabricante
  or old.grupo_produto_id is distinct from new.grupo_produto_id
  or old."imgUrl" is distinct from new."imgUrl"
  or old.conservacao is distinct from new.conservacao
  or old.codigobarras is distinct from new.codigobarras
  or old.is_deleted is distinct from new.is_deleted
)
execute function public.fn_site_product_changed();

create or replace function public.fn_site_product_group_changed()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_link_id bigint;
begin
  for v_link_id in
    select link.id
      from public.site_product_link link
      join public.produto p on p.id = link.produto_id
     where p.grupo_produto_id = new.id
       and link.status <> 'RASCUNHO'
  loop
    perform public.fn_enfileirar_site_product_link(v_link_id);
  end loop;
  return new;
end;
$$;

