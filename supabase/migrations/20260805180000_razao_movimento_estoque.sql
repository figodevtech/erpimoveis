-- Razao unico de movimentacao do estoque de produtos.
--
-- Hoje entrada e saida manual tem rastro proprio (estoque_movimento_entrada e
-- estoque_saida_item, ambos com saldo_anterior/saldo_resultante), mas venda e OS
-- nao tem: vendaproduto_baixa e osproduto_baixa sao um retrato do estado atual,
-- gravados por upsert e apagados no estorno. osproduto_baixa nem sequer tem data.
-- Por isso as baixas de venda e de OS nao aparecem em nenhuma tela de historico.
--
-- Esta migracao cria a tabela append-only que faltava e liga um gatilho em
-- produto.estoque, de modo que qualquer alteracao de saldo passe a deixar linha,
-- independente do caminho que a provocou.
--
-- SEGURANCA DO BACKFILL: a carga historica da secao 3 e composta exclusivamente
-- por INSERT em public.estoque_movimento. Nenhum comando desta migracao executa
-- UPDATE em public.produto, portanto nenhum saldo e alterado ao importar o
-- passado. O gatilho que grava o razao so dispara em UPDATE OF estoque ON
-- produto e por isso nao pode ser acionado por um INSERT no razao - nao existe
-- ciclo entre as duas coisas. Alem disso o gatilho e criado na secao 4, depois
-- da carga, para que nem por engano a importacao passe por ele.
BEGIN;

-- ---------------------------------------------------------------------------
-- 1) Tabela
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.estoque_movimento (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produto_id integer NOT NULL REFERENCES public.produto(id) ON DELETE RESTRICT,

  -- Sentido do efeito no saldo, derivado do delta aplicado em produto.estoque.
  sentido text NOT NULL CHECK (sentido IN ('ENTRADA', 'SAIDA')),

  -- Processo que originou o movimento. NAO_IDENTIFICADA marca alteracao de saldo
  -- feita fora dos fluxos previstos; serve para tornar visivel qualquer caminho
  -- que ainda escreva direto em produto.estoque.
  origem text NOT NULL CHECK (origem IN (
    'ENTRADA', 'SAIDA_MANUAL', 'VENDA', 'ORDEM_SERVICO', 'NAO_IDENTIFICADA'
  )),

  acao text NOT NULL CHECK (acao IN ('REGISTRO', 'ESTORNO')),

  quantidade integer NOT NULL CHECK (quantidade > 0),

  -- Nulos apenas em linhas reconstruidas, onde o saldo da epoca nao e conhecido.
  saldo_anterior integer,
  saldo_resultante integer,

  -- entrada e saida manual nunca sao removidas (cancelamento e mudanca de
  -- status), entao carregam FK. venda e OS podem ser excluidas de fato, e o
  -- razao precisa sobreviver a isso: ficam como referencia solta, acompanhadas
  -- do rotulo abaixo.
  entrada_id bigint REFERENCES public.entrada(id) ON DELETE RESTRICT,
  saida_id bigint REFERENCES public.estoque_saida(id) ON DELETE RESTRICT,
  venda_id integer,
  ordemservicoid integer,

  -- Descricao do documento congelada no momento da gravacao, para a linha
  -- continuar legivel mesmo que o documento seja excluido depois.
  documento_label text,

  observacao text,

  -- true nas linhas importadas pela carga historica desta migracao, que nao
  -- foram observadas ao vivo pelo gatilho.
  reconstruido boolean NOT NULL DEFAULT false,

  created_by uuid,
  created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS estoque_movimento_produto_idx
  ON public.estoque_movimento(produto_id, created_at DESC);
CREATE INDEX IF NOT EXISTS estoque_movimento_created_at_idx
  ON public.estoque_movimento(created_at DESC);
CREATE INDEX IF NOT EXISTS estoque_movimento_origem_idx
  ON public.estoque_movimento(origem, created_at DESC);
CREATE INDEX IF NOT EXISTS estoque_movimento_venda_idx
  ON public.estoque_movimento(venda_id) WHERE venda_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS estoque_movimento_os_idx
  ON public.estoque_movimento(ordemservicoid) WHERE ordemservicoid IS NOT NULL;
CREATE INDEX IF NOT EXISTS estoque_movimento_entrada_idx
  ON public.estoque_movimento(entrada_id) WHERE entrada_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS estoque_movimento_saida_idx
  ON public.estoque_movimento(saida_id) WHERE saida_id IS NOT NULL;

ALTER TABLE public.estoque_movimento OWNER TO postgres;

-- ---------------------------------------------------------------------------
-- 2) Imutabilidade
--
-- Um razao que pode ser editado nao serve de prova. O estorno e sempre uma
-- linha nova com acao = 'ESTORNO', nunca a alteracao da linha original.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.tg_estoque_movimento_imutavel()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  RAISE EXCEPTION 'O razao de movimentacao de estoque e imutavel: registre um estorno em vez de alterar a linha.'
    USING ERRCODE = '42501';
END;
$$;

ALTER FUNCTION public.tg_estoque_movimento_imutavel() OWNER TO postgres;

DROP TRIGGER IF EXISTS estoque_movimento_imutavel_trg ON public.estoque_movimento;
CREATE TRIGGER estoque_movimento_imutavel_trg
  BEFORE UPDATE OR DELETE ON public.estoque_movimento
  FOR EACH ROW EXECUTE FUNCTION public.tg_estoque_movimento_imutavel();

-- ---------------------------------------------------------------------------
-- 3) Carga historica
--
-- Somente INSERT. Nada aqui toca public.produto, logo nenhum saldo se move.
--
-- Fidelidade por fonte:
--   - entrada e saida manual: exatas, inclusive saldos, porque as tabelas de
--     origem gravam saldo_anterior/saldo_resultante;
--   - venda e OS: apenas as baixas ainda vigentes, sem saldo da epoca. O que ja
--     foi estornado ou excluido nao existe mais em lugar nenhum e nao entra.
--     Nas OS a data e aproximada, tirada da propria OS, porque osproduto_baixa
--     nao tem carimbo de tempo.
-- Todas as linhas desta secao vao com reconstruido = true.
-- ---------------------------------------------------------------------------

-- 3.1) Entradas confirmadas e cancelamentos de entrada (fieis, com saldo).
INSERT INTO public.estoque_movimento (
  produto_id, sentido, origem, acao, quantidade,
  saldo_anterior, saldo_resultante, entrada_id, documento_label,
  observacao, reconstruido, created_by, created_at
)
SELECT
  m.produto_id,
  CASE WHEN m.tipo = 'CANCELAMENTO' THEN 'SAIDA' ELSE 'ENTRADA' END,
  'ENTRADA',
  CASE WHEN m.tipo = 'CANCELAMENTO' THEN 'ESTORNO' ELSE 'REGISTRO' END,
  m.quantidade,
  m.saldo_anterior,
  m.saldo_resultante,
  m.entrada_id,
  'Entrada #' || m.entrada_id,
  'Importado de estoque_movimento_entrada (saldos preservados).',
  true,
  e.created_by,
  m.created_at
FROM public.estoque_movimento_entrada m
JOIN public.entrada e ON e.id = m.entrada_id;

-- 3.2) Saidas manuais confirmadas (fieis, com saldo).
INSERT INTO public.estoque_movimento (
  produto_id, sentido, origem, acao, quantidade,
  saldo_anterior, saldo_resultante, saida_id, documento_label,
  observacao, reconstruido, created_by, created_at
)
SELECT
  i.produto_id,
  'SAIDA',
  'SAIDA_MANUAL',
  'REGISTRO',
  i.quantidade,
  i.saldo_anterior,
  i.saldo_resultante,
  i.saida_id,
  'Saida #' || i.saida_id || ' - ' || replace(s.motivo, '_', ' '),
  'Importado de estoque_saida_item (saldos preservados).',
  true,
  s.created_by,
  i.created_at
FROM public.estoque_saida_item i
JOIN public.estoque_saida s ON s.id = i.saida_id;

-- 3.3) Devolucao das saidas manuais canceladas. cancelar_saida_estoque devolve o
-- saldo mas nao grava linha, entao o estorno e sintetizado aqui pela data de
-- cancelamento. Os saldos da epoca sao desconhecidos e ficam nulos.
INSERT INTO public.estoque_movimento (
  produto_id, sentido, origem, acao, quantidade,
  saldo_anterior, saldo_resultante, saida_id, documento_label,
  observacao, reconstruido, created_by, created_at
)
SELECT
  i.produto_id,
  'ENTRADA',
  'SAIDA_MANUAL',
  'ESTORNO',
  i.quantidade,
  NULL,
  NULL,
  i.saida_id,
  'Saida #' || i.saida_id || ' - cancelada',
  'Estorno reconstruido a partir do cancelamento da saida; saldos da epoca desconhecidos.',
  true,
  s.cancelada_by,
  COALESCE(s.cancelada_at, s.created_at)
FROM public.estoque_saida_item i
JOIN public.estoque_saida s ON s.id = i.saida_id
WHERE s.status = 'CANCELADA';

-- 3.4) Baixas de venda ainda vigentes.
INSERT INTO public.estoque_movimento (
  produto_id, sentido, origem, acao, quantidade,
  saldo_anterior, saldo_resultante, venda_id, documento_label,
  observacao, reconstruido, created_by, created_at
)
SELECT
  b.produtoid,
  'SAIDA',
  'VENDA',
  'REGISTRO',
  b.quantidade,
  NULL,
  NULL,
  b.venda_id,
  'Venda #' || b.venda_id,
  'Reconstruido a partir da baixa vigente em vendaproduto_baixa; saldos da epoca desconhecidos.',
  true,
  v.created_by,
  COALESCE(b.created_at, v.datavenda, v.createdat, now())
FROM public.vendaproduto_baixa b
JOIN public.venda v ON v.id = b.venda_id
WHERE b.quantidade > 0;

-- 3.5) Baixas de OS ainda vigentes. Sem data propria: usa a data da OS.
INSERT INTO public.estoque_movimento (
  produto_id, sentido, origem, acao, quantidade,
  saldo_anterior, saldo_resultante, ordemservicoid, documento_label,
  observacao, reconstruido, created_by, created_at
)
SELECT
  b.produtoid,
  'SAIDA',
  'ORDEM_SERVICO',
  'REGISTRO',
  b.quantidade,
  NULL,
  NULL,
  b.ordemservicoid,
  'OS #' || b.ordemservicoid,
  'Reconstruido a partir da baixa vigente em osproduto_baixa; data aproximada pela OS e saldos da epoca desconhecidos.',
  true,
  os.created_by,
  COALESCE(os.dataentrada::timestamptz, os.createdat::timestamptz, now())
FROM public.osproduto_baixa b
JOIN public.ordemservico os ON os.id = b.ordemservicoid
WHERE b.quantidade > 0;

-- ---------------------------------------------------------------------------
-- 4) Gravacao automatica
--
-- Criado depois da carga, de proposito. O contexto (processo e documento) e
-- passado pela RPC que provoca a alteracao, via set_config transacional - mesmo
-- mecanismo ja usado por usoconsumo_proteger_saldo. Sem contexto, o movimento
-- ainda e gravado, porem como NAO_IDENTIFICADA, para que fique visivel em vez
-- de silencioso.
-- ---------------------------------------------------------------------------

-- acao nao e parametro: ela decorre de (origem, sentido). Saldo saindo por venda
-- ou OS e baixa; saldo voltando por venda ou OS so pode ser devolucao. O mesmo
-- vale, invertido, para entrada e saida manual. Derivar em vez de receber tira
-- do chamador a chance de rotular errado.
CREATE OR REPLACE FUNCTION public.estoque_definir_contexto(
  p_origem text,
  p_documento_id bigint DEFAULT NULL,
  p_documento_label text DEFAULT NULL,
  p_usuario uuid DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM set_config('app.estoque_origem', COALESCE(p_origem, ''), true);
  PERFORM set_config('app.estoque_documento_id', COALESCE(p_documento_id::text, ''), true);
  PERFORM set_config('app.estoque_documento_label', COALESCE(p_documento_label, ''), true);
  PERFORM set_config('app.estoque_usuario', COALESCE(p_usuario::text, ''), true);
END;
$$;

ALTER FUNCTION public.estoque_definir_contexto(text, bigint, text, uuid) OWNER TO postgres;

CREATE OR REPLACE FUNCTION public.tg_estoque_movimento_registrar()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_delta integer;
  v_sentido text;
  v_origem text;
  v_acao text;
  v_documento bigint;
  v_label text;
  v_usuario uuid;
BEGIN
  v_delta := COALESCE(new.estoque, 0) - COALESCE(old.estoque, 0);
  IF v_delta = 0 THEN
    RETURN new;
  END IF;

  v_sentido := CASE WHEN v_delta > 0 THEN 'ENTRADA' ELSE 'SAIDA' END;

  v_origem := COALESCE(nullif(current_setting('app.estoque_origem', true), ''), 'NAO_IDENTIFICADA');
  IF v_origem NOT IN ('ENTRADA', 'SAIDA_MANUAL', 'VENDA', 'ORDEM_SERVICO') THEN
    v_origem := 'NAO_IDENTIFICADA';
  END IF;

  -- Entrada de mercadoria soma; os demais processos subtraem. Movimento no
  -- sentido contrario ao natural da origem so pode ser desfazimento.
  v_acao := CASE
    WHEN v_origem = 'NAO_IDENTIFICADA' THEN 'REGISTRO'
    WHEN v_origem = 'ENTRADA' AND v_sentido = 'SAIDA' THEN 'ESTORNO'
    WHEN v_origem <> 'ENTRADA' AND v_sentido = 'ENTRADA' THEN 'ESTORNO'
    ELSE 'REGISTRO'
  END;

  v_documento := nullif(current_setting('app.estoque_documento_id', true), '')::bigint;
  v_label := nullif(current_setting('app.estoque_documento_label', true), '');
  v_usuario := nullif(current_setting('app.estoque_usuario', true), '')::uuid;

  INSERT INTO public.estoque_movimento (
    produto_id, sentido, origem, acao, quantidade,
    saldo_anterior, saldo_resultante,
    entrada_id, saida_id, venda_id, ordemservicoid,
    documento_label, created_by
  ) VALUES (
    new.id,
    v_sentido,
    v_origem,
    v_acao,
    abs(v_delta),
    COALESCE(old.estoque, 0),
    COALESCE(new.estoque, 0),
    CASE WHEN v_origem = 'ENTRADA' THEN v_documento END,
    CASE WHEN v_origem = 'SAIDA_MANUAL' THEN v_documento END,
    CASE WHEN v_origem = 'VENDA' THEN v_documento::integer END,
    CASE WHEN v_origem = 'ORDEM_SERVICO' THEN v_documento::integer END,
    v_label,
    v_usuario
  );

  RETURN new;
END;
$$;

ALTER FUNCTION public.tg_estoque_movimento_registrar() OWNER TO postgres;

DROP TRIGGER IF EXISTS produto_estoque_movimento_trg ON public.produto;
CREATE TRIGGER produto_estoque_movimento_trg
  AFTER UPDATE OF estoque ON public.produto
  FOR EACH ROW EXECUTE FUNCTION public.tg_estoque_movimento_registrar();

-- ---------------------------------------------------------------------------
-- 5) Conferencia
--
-- Soma do razao por produto contra produto.estoque. Enquanto houver linhas
-- reconstruidas o total nao fecha (o passado importado esta incompleto por
-- natureza); a coluna considera_reconstruido serve para separar as duas
-- leituras. A partir daqui, movimento novo tem que fechar.
-- Nada aqui corrige saldo: e uma visao de leitura.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE VIEW public.estoque_conferencia AS
SELECT
  p.id AS produto_id,
  p.titulo,
  p.estoque AS saldo_atual,
  COALESCE(SUM(
    CASE WHEN m.sentido = 'ENTRADA' THEN m.quantidade ELSE -m.quantidade END
  ), 0) AS saldo_pelo_razao,
  COALESCE(SUM(
    CASE
      WHEN m.reconstruido THEN 0
      WHEN m.sentido = 'ENTRADA' THEN m.quantidade
      ELSE -m.quantidade
    END
  ), 0) AS saldo_pelo_razao_ao_vivo,
  COUNT(m.id) FILTER (WHERE m.reconstruido) AS movimentos_reconstruidos,
  COUNT(m.id) FILTER (WHERE m.origem = 'NAO_IDENTIFICADA') AS movimentos_sem_origem
FROM public.produto p
LEFT JOIN public.estoque_movimento m ON m.produto_id = p.id
WHERE p.is_deleted = false
GROUP BY p.id, p.titulo, p.estoque;

ALTER VIEW public.estoque_conferencia OWNER TO postgres;

-- ---------------------------------------------------------------------------
-- 6) Acesso
--
-- Mesma politica do estoque de uso e consumo: nada exposto a anon/authenticated,
-- leitura e escrita apenas pelo servidor.
-- ---------------------------------------------------------------------------

ALTER TABLE public.estoque_movimento ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.estoque_movimento NO FORCE ROW LEVEL SECURITY;

REVOKE ALL ON public.estoque_movimento FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.estoque_movimento TO service_role;

REVOKE ALL ON public.estoque_conferencia FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.estoque_conferencia TO service_role;

REVOKE ALL ON FUNCTION public.estoque_definir_contexto(text, bigint, text, uuid)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.estoque_definir_contexto(text, bigint, text, uuid)
  TO service_role;

GRANT USAGE, SELECT ON SEQUENCE public.estoque_movimento_id_seq TO service_role;

COMMIT;
