-- Histórico de ajuste de valores: a tabela que faltou.
--
-- Ordem invertida de propósito. A migration original que criava esta tabela
-- nasceu com o mesmo número de versão de `add_produto_avulso_os`, que veio da
-- develop. Como aquela versão já constava aplicada nos bancos, o CLI tratou o
-- número como resolvido e pulou o arquivo em silêncio — mas a `170000`, que só
-- faz CREATE OR REPLACE da função, aplicou normalmente. Resultado: a função
-- `ajustar_valores_transacao` passou a existir em todos os bancos gravando numa
-- tabela que nunca foi criada. plpgsql não valida referências do corpo na
-- criação, então nada acusou o erro até a primeira chamada.
--
-- Esta migration fecha esse buraco e é idempotente: em banco novo ela roda
-- depois da `170000` e o estado final é o mesmo.
BEGIN;

CREATE TABLE IF NOT EXISTS public.transacao_valor_historico (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Mantemos o identificador mesmo se a transacao for posteriormente excluida.
  transacao_id bigint NOT NULL,
  valor_anterior numeric(14,2) NOT NULL,
  valor_novo numeric(14,2) NOT NULL,
  valor_liquido_anterior numeric(14,2),
  valor_liquido_novo numeric(14,2),
  alterado_por uuid,
  motivo text,
  created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS transacao_valor_historico_transacao_idx
  ON public.transacao_valor_historico(transacao_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.proteger_transacao_valor_historico()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  RAISE EXCEPTION 'O historico de ajuste de valores e imutavel.' USING ERRCODE = '55000';
END;
$$;

DROP TRIGGER IF EXISTS trg_proteger_transacao_valor_historico
  ON public.transacao_valor_historico;
CREATE TRIGGER trg_proteger_transacao_valor_historico
  BEFORE UPDATE OR DELETE ON public.transacao_valor_historico
  FOR EACH ROW EXECUTE FUNCTION public.proteger_transacao_valor_historico();

ALTER TABLE public.transacao_valor_historico OWNER TO postgres;
ALTER FUNCTION public.proteger_transacao_valor_historico() OWNER TO postgres;
REVOKE ALL ON TABLE public.transacao_valor_historico FROM anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.transacao_valor_historico TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.transacao_valor_historico_id_seq TO service_role;

COMMIT;
