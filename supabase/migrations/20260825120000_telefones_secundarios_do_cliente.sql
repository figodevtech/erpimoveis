BEGIN;

-- O telefone principal continua em `cliente.telefone`: é ele que a NF-e, os
-- contatos automáticos e as telas antigas leem. Esta tabela guarda apenas os
-- contatos adicionais, com o nome de quem atende naquele número.
CREATE TABLE IF NOT EXISTS public.cliente_telefone (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id integer NOT NULL
    REFERENCES public.cliente(id) ON DELETE CASCADE,
  telefone text NOT NULL,
  contato text,
  observacao text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Guardamos só dígitos (DDD + número), como no telefone principal.
  CONSTRAINT cliente_telefone_formato CHECK (telefone ~ '^[0-9]{10,11}$'),
  CONSTRAINT cliente_telefone_unico UNIQUE (cliente_id, telefone)
);

CREATE INDEX IF NOT EXISTS cliente_telefone_cliente_idx
  ON public.cliente_telefone (cliente_id, id);

-- O ERP autentica com NextAuth e acessa os dados por APIs do servidor com
-- service_role; anon/authenticated não leem a tabela direto do navegador.
ALTER TABLE public.cliente_telefone ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cliente_telefone NO FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.cliente_telefone FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.cliente_telefone_id_seq FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.cliente_telefone TO service_role;
GRANT ALL ON SEQUENCE public.cliente_telefone_id_seq TO service_role;

COMMIT;
