CREATE TABLE IF NOT EXISTS public.estoque_saida_fiscal (
  saida_id bigint PRIMARY KEY REFERENCES public.estoque_saida(id) ON DELETE RESTRICT,
  operacao_fiscal_codigo text NOT NULL REFERENCES public.fiscal_nfe_saida_operacao(codigo) ON DELETE RESTRICT,
  natureza_operacao text NOT NULL,
  finalidade text NOT NULL CHECK (finalidade IN ('NORMAL', 'COMPLEMENTAR', 'AJUSTE', 'DEVOLUCAO')),
  documento_referenciado_obrigatorio boolean NOT NULL DEFAULT false,
  entrada_origem_id bigint REFERENCES public.entrada(id) ON DELETE RESTRICT,
  chave_acesso_referenciada text,
  destinatario_snapshot jsonb,
  observacoes_fiscais text,
  created_by uuid,
  updated_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT estoque_saida_fiscal_chave_check CHECK (
    chave_acesso_referenciada IS NULL
    OR chave_acesso_referenciada ~ '^[0-9]{44}$'
  ),
  CONSTRAINT estoque_saida_fiscal_referencia_obrigatoria_check CHECK (
    NOT documento_referenciado_obrigatorio
    OR chave_acesso_referenciada ~ '^[0-9]{44}$'
  )
);

CREATE TABLE IF NOT EXISTS public.estoque_saida_item_fiscal (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  saida_id bigint NOT NULL REFERENCES public.estoque_saida_fiscal(saida_id) ON DELETE CASCADE,
  saida_item_id bigint NOT NULL REFERENCES public.estoque_saida_item(id) ON DELETE RESTRICT,
  entrada_item_origem_id bigint REFERENCES public.entradaitens(id) ON DELETE RESTRICT,
  numero_item_referenciado integer CHECK (
    numero_item_referenciado IS NULL OR numero_item_referenciado BETWEEN 1 AND 990
  ),
  percentual_devolucao numeric(7,4) CHECK (
    percentual_devolucao IS NULL OR percentual_devolucao > 0 AND percentual_devolucao <= 100
  ),
  valor_ipi_devolvido numeric(14,2) NOT NULL DEFAULT 0 CHECK (valor_ipi_devolvido >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (saida_id, saida_item_id)
);

CREATE INDEX IF NOT EXISTS estoque_saida_item_fiscal_entrada_idx
  ON public.estoque_saida_item_fiscal(entrada_item_origem_id)
  WHERE entrada_item_origem_id IS NOT NULL;

-- Reconcilia o item fiscal com a baixa real e serializa o consumo da entrada
-- de origem. Assim duas requisições concorrentes não conseguem devolver mais
-- unidades do que foram recebidas.
CREATE OR REPLACE FUNCTION public.estoque_saida_item_fiscal_validar_origem()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_saida_produto integer;
  v_saida_quantidade numeric;
  v_entrada_produto integer;
  v_entrada_quantidade numeric;
  v_ja_vinculada numeric;
  v_exige_referencia boolean;
BEGIN
  SELECT produto_id, quantidade
    INTO v_saida_produto, v_saida_quantidade
    FROM public.estoque_saida_item
   WHERE id = NEW.saida_item_id
     AND saida_id = NEW.saida_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'O item fiscal não pertence à saída informada.' USING ERRCODE = '23514';
  END IF;

  SELECT documento_referenciado_obrigatorio OR finalidade = 'DEVOLUCAO'
    INTO v_exige_referencia
    FROM public.estoque_saida_fiscal
   WHERE saida_id = NEW.saida_id;

  IF v_exige_referencia AND (
    NEW.entrada_item_origem_id IS NULL OR NEW.numero_item_referenciado IS NULL
  ) THEN
    RAISE EXCEPTION 'A operação fiscal exige a entrada e o número do item de origem.'
      USING ERRCODE = '23514';
  END IF;

  IF NEW.entrada_item_origem_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT produto_id, quantidade
    INTO v_entrada_produto, v_entrada_quantidade
    FROM public.entradaitens
   WHERE id = NEW.entrada_item_origem_id
   FOR UPDATE;

  IF NOT FOUND OR v_entrada_produto <> v_saida_produto THEN
    RAISE EXCEPTION 'O item da entrada de origem pertence a outro produto.' USING ERRCODE = '23514';
  END IF;

  SELECT coalesce(sum(saida_item.quantidade), 0)
    INTO v_ja_vinculada
    FROM public.estoque_saida_item_fiscal vinculo
    JOIN public.estoque_saida_item saida_item ON saida_item.id = vinculo.saida_item_id
   WHERE vinculo.entrada_item_origem_id = NEW.entrada_item_origem_id
     AND vinculo.id <> coalesce(NEW.id, -1);

  IF v_ja_vinculada + v_saida_quantidade > v_entrada_quantidade THEN
    RAISE EXCEPTION 'A quantidade total vinculada supera a quantidade recebida no item de origem.'
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_estoque_saida_item_fiscal_validar_origem
  ON public.estoque_saida_item_fiscal;
CREATE TRIGGER trg_estoque_saida_item_fiscal_validar_origem
BEFORE INSERT OR UPDATE OF saida_id, saida_item_id, entrada_item_origem_id, numero_item_referenciado
ON public.estoque_saida_item_fiscal
FOR EACH ROW
EXECUTE FUNCTION public.estoque_saida_item_fiscal_validar_origem();

CREATE OR REPLACE FUNCTION public.salvar_contexto_fiscal_saida(
  p_contexto jsonb,
  p_itens jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_saida_id bigint := nullif(p_contexto->>'saida_id', '')::bigint;
  v_item jsonb;
BEGIN
  IF v_saida_id IS NULL OR jsonb_typeof(p_itens) <> 'array' OR jsonb_array_length(p_itens) = 0 THEN
    RAISE EXCEPTION 'Contexto fiscal ou itens da saída inválidos.' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.estoque_saida_fiscal (
    saida_id, operacao_fiscal_codigo, natureza_operacao, finalidade,
    documento_referenciado_obrigatorio, entrada_origem_id,
    chave_acesso_referenciada, destinatario_snapshot, observacoes_fiscais,
    created_by, updated_by, updated_at
  ) VALUES (
    v_saida_id,
    p_contexto->>'operacao_fiscal_codigo',
    p_contexto->>'natureza_operacao',
    p_contexto->>'finalidade',
    coalesce((p_contexto->>'documento_referenciado_obrigatorio')::boolean, false),
    nullif(p_contexto->>'entrada_origem_id', '')::bigint,
    nullif(p_contexto->>'chave_acesso_referenciada', ''),
    p_contexto->'destinatario_snapshot',
    nullif(btrim(coalesce(p_contexto->>'observacoes_fiscais', '')), ''),
    nullif(p_contexto->>'user_id', '')::uuid,
    nullif(p_contexto->>'user_id', '')::uuid,
    now()
  )
  ON CONFLICT (saida_id) DO UPDATE SET
    operacao_fiscal_codigo = EXCLUDED.operacao_fiscal_codigo,
    natureza_operacao = EXCLUDED.natureza_operacao,
    finalidade = EXCLUDED.finalidade,
    documento_referenciado_obrigatorio = EXCLUDED.documento_referenciado_obrigatorio,
    entrada_origem_id = EXCLUDED.entrada_origem_id,
    chave_acesso_referenciada = EXCLUDED.chave_acesso_referenciada,
    destinatario_snapshot = EXCLUDED.destinatario_snapshot,
    observacoes_fiscais = EXCLUDED.observacoes_fiscais,
    updated_by = EXCLUDED.updated_by,
    updated_at = now();

  DELETE FROM public.estoque_saida_item_fiscal WHERE saida_id = v_saida_id;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_itens) LOOP
    INSERT INTO public.estoque_saida_item_fiscal (
      saida_id, saida_item_id, entrada_item_origem_id,
      numero_item_referenciado, percentual_devolucao,
      valor_ipi_devolvido, updated_at
    ) VALUES (
      v_saida_id,
      (v_item->>'saida_item_id')::bigint,
      nullif(v_item->>'entrada_item_origem_id', '')::bigint,
      nullif(v_item->>'numero_item_referenciado', '')::integer,
      nullif(v_item->>'percentual_devolucao', '')::numeric,
      coalesce(nullif(v_item->>'valor_ipi_devolvido', '')::numeric, 0),
      now()
    );
  END LOOP;

  RETURN jsonb_build_object('saida_id', v_saida_id);
END;
$$;

-- A aplicação barra inclusive rascunhos. Esta guarda transacional protege a
-- fronteira irreversível: uma saída nunca pode ter duas NF-e transmitidas.
CREATE UNIQUE INDEX IF NOT EXISTS nfe_origem_saida_modelo_ativa_idx
  ON public.nfe (saidaid, modelo)
  WHERE saidaid IS NOT NULL
    AND is_deleted = false
    AND status IN (
      'RASCUNHO', 'ASSINADA', 'ENVIADA', 'AUTORIZADA', 'PENDENTE_ENVIO',
      'CONTINGENCIA', 'RESULTADO_INCERTO'
    );

CREATE OR REPLACE FUNCTION public.nfe_impedir_saida_transmitida_duplicada()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.saidaid IS NULL
     OR coalesce(NEW.is_deleted, false)
     OR NEW.status NOT IN (
       'ASSINADA', 'ENVIADA', 'AUTORIZADA', 'PENDENTE_ENVIO',
       'CONTINGENCIA', 'RESULTADO_INCERTO'
     ) THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE'
     AND NEW.saidaid IS NOT DISTINCT FROM OLD.saidaid
     AND NEW.modelo IS NOT DISTINCT FROM OLD.modelo
     AND NOT coalesce(OLD.is_deleted, false)
     AND OLD.status IN (
       'ASSINADA', 'ENVIADA', 'AUTORIZADA', 'PENDENTE_ENVIO',
       'CONTINGENCIA', 'RESULTADO_INCERTO'
     ) THEN
    RETURN NEW;
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended(format('nfe:saida:%s:modelo:%s', NEW.saidaid, NEW.modelo), 0)
  );

  IF EXISTS (
    SELECT 1
      FROM public.nfe existente
     WHERE existente.id <> coalesce(NEW.id, -1)
       AND existente.saidaid = NEW.saidaid
       AND existente.modelo = NEW.modelo
       AND existente.is_deleted = false
       AND existente.status IN (
         'ASSINADA', 'ENVIADA', 'AUTORIZADA', 'PENDENTE_ENVIO',
         'CONTINGENCIA', 'RESULTADO_INCERTO'
       )
  ) THEN
    RAISE EXCEPTION USING
      ERRCODE = '23505',
      MESSAGE = format(
        'A saída %s já possui uma nota transmitida do modelo %s.',
        NEW.saidaid,
        NEW.modelo
      ),
      CONSTRAINT = 'nfe_origem_saida_modelo_ativa_idx';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_nfe_saida_transmitida_unica ON public.nfe;
CREATE TRIGGER trg_nfe_saida_transmitida_unica
BEFORE INSERT OR UPDATE OF saidaid, modelo, status, is_deleted
ON public.nfe
FOR EACH ROW
EXECUTE FUNCTION public.nfe_impedir_saida_transmitida_duplicada();

