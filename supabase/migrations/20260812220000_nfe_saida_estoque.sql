  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_nfe_saida_operacao_cfop_interno_check CHECK (
    cfop_interno IS NULL OR cfop_interno ~ '^[5][0-9]{3}$'
