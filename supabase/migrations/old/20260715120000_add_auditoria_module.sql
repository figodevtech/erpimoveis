-- Historico centralizado de alteracoes nas tabelas de negocio.
-- O trigger registra apenas os campos alterados em UPDATE e mascara dados sensiveis.

create table if not exists public.auditoria_evento (
  id bigint generated by default as identity primary key,
  ocorrido_em timestamptz not null default now(),
  operacao text not null check (operacao in ('INSERT', 'UPDATE', 'DELETE')),
  modulo text not null,
  tabela text not null,
  registro_id text,
  usuario_id uuid references public.usuario(id) on delete set null,
  dados_anteriores jsonb,
  dados_novos jsonb,
  campos_alterados text[] not null default '{}'::text[],
  origem text not null default 'sistema' check (origem in ('usuario', 'sistema')),
  fonte text not null default 'evento' check (fonte in ('evento', 'legado')),
  transacao_id bigint not null default txid_current()
);
alter table public.auditoria_evento
  add column if not exists modulo text;
alter table public.auditoria_evento
  add column if not exists fonte text not null default 'evento';
alter table public.usuario add column if not exists created_by uuid references public.usuario(id) on delete set null;
alter table public.usuario add column if not exists updated_by uuid references public.usuario(id) on delete set null;
alter table public.perfil add column if not exists created_by uuid references public.usuario(id) on delete set null;
alter table public.perfil add column if not exists updated_by uuid references public.usuario(id) on delete set null;
alter table public.perfilpermissao add column if not exists created_by uuid references public.usuario(id) on delete set null;
alter table public.perfilpermissao add column if not exists updated_by uuid references public.usuario(id) on delete set null;
create index if not exists auditoria_evento_ocorrido_em_idx
  on public.auditoria_evento (ocorrido_em desc);
create index if not exists auditoria_evento_tabela_ocorrido_idx
  on public.auditoria_evento (tabela, ocorrido_em desc);
create index if not exists auditoria_evento_modulo_ocorrido_idx
  on public.auditoria_evento (modulo, ocorrido_em desc);
create index if not exists auditoria_evento_usuario_ocorrido_idx
  on public.auditoria_evento (usuario_id, ocorrido_em desc)
  where usuario_id is not null;
create index if not exists auditoria_evento_operacao_ocorrido_idx
  on public.auditoria_evento (operacao, ocorrido_em desc);
alter table public.auditoria_evento enable row level security;
revoke all on table public.auditoria_evento from anon, authenticated;
create or replace function public.auditoria_try_uuid(valor text)
returns uuid
language plpgsql
immutable
as $$
begin
  if valor is null or btrim(valor) = '' then
    return null;
  end if;
  return valor::uuid;
exception when invalid_text_representation then
  return null;
end;
$$;
-- Propaga o administrador que criou o usuario pelo metadata enviado ao Auth.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  ator uuid := public.auditoria_try_uuid(new.raw_user_meta_data ->> 'created_by');
begin
  insert into public.usuario (
    id, email, nome, perfilid, setorid, createdat, updatedat, created_by, updated_by
  ) values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'nome', new.email),
    nullif(new.raw_user_meta_data ->> 'perfilid', '')::int,
    nullif(new.raw_user_meta_data ->> 'setorid', '')::int,
    now(),
    now(),
    ator,
    ator
  )
  on conflict (id) do update
    set email = excluded.email,
        nome = coalesce(excluded.nome, public.usuario.nome),
        perfilid = coalesce(excluded.perfilid, public.usuario.perfilid),
        setorid = coalesce(excluded.setorid, public.usuario.setorid),
        created_by = coalesce(public.usuario.created_by, excluded.created_by),
        updated_by = coalesce(excluded.updated_by, public.usuario.updated_by),
        updatedat = now();
  return new;
end;
$$;
create or replace function public.auditoria_json_seguro(valor jsonb)
returns jsonb
language plpgsql
immutable
as $$
declare
  resultado jsonb;
begin
  if valor is null then
    return null;
  end if;

  if jsonb_typeof(valor) = 'object' then
    select coalesce(
      jsonb_object_agg(
        chave,
        case
          when lower(chave) ~ '(senha|password|secret|token|certificado|private.?key|access.?key|refresh.?key|authorization)'
            then '"[PROTEGIDO]"'::jsonb
          else public.auditoria_json_seguro(item)
        end
      ),
      '{}'::jsonb
    )
    into resultado
    from jsonb_each(valor) as entrada(chave, item);
    return resultado;
  end if;

  if jsonb_typeof(valor) = 'array' then
    select coalesce(jsonb_agg(public.auditoria_json_seguro(item)), '[]'::jsonb)
      into resultado
    from jsonb_array_elements(valor) as entrada(item);
    return resultado;
  end if;

  return valor;
end;
$$;
create or replace function public.auditoria_modulo_tabela(nome_tabela text)
returns text
language sql
immutable
as $$
  select case
    when nome_tabela ~* '^(mercadolivre|marketplace)' then 'marketplace'
    when nome_tabela ~* '^desmanche' then 'desmanche'
    when nome_tabela ~* '^(agendamento)' then 'agendamentos'
    when nome_tabela ~* '^(ordemservico|os|checklist|imagemvistoria)' then 'ordens'
    when nome_tabela ~* '^(venda|categoria_venda)' then 'vendas'
    when nome_tabela ~* '^(produto|fornecedor|peca|unidademedida|produtogrupo)' then 'estoque'
    when nome_tabela ~* '^(pagamento|transacao|bancoconta|categoriatransacao)' then 'financeiro'
    when nome_tabela ~* '^(nfe|nfse|notafiscal|fiscal)' then 'fiscal'
    when nome_tabela ~* '^(veiculo|transferencias_veiculos|cores_veiculos)' then 'veiculos'
    when nome_tabela ~* '^cliente' then 'clientes'
    when nome_tabela ~* '^(usuario|perfil|permissao|perfilpermissao|setor)' then 'usuarios'
    when nome_tabela ~* '^(config|empresa|categoriaservico|tiposervico|servico)' then 'configuracoes'
    else 'outros'
  end;
$$;
update public.auditoria_evento
set modulo = public.auditoria_modulo_tabela(tabela)
where modulo is null;
alter table public.auditoria_evento
  alter column modulo set not null;
create or replace function public.registrar_auditoria()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  anterior jsonb := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end;
  novo jsonb := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) else null end;
  anterior_alterado jsonb;
  novo_alterado jsonb;
  campos text[] := '{}'::text[];
  linha_referencia jsonb;
  ator uuid;
  id_registro text;
begin
  -- Evita eventos vazios causados por UPDATE que nao mudou nenhum valor.
  if tg_op = 'UPDATE' and anterior = novo then
    return new;
  end if;

  linha_referencia := coalesce(novo, anterior);

  if tg_op = 'UPDATE' then
    select
      coalesce(jsonb_object_agg(chave, anterior -> chave), '{}'::jsonb),
      coalesce(jsonb_object_agg(chave, novo -> chave), '{}'::jsonb),
      coalesce(array_agg(chave order by chave), '{}'::text[])
    into anterior_alterado, novo_alterado, campos
    from (
      select chave
      from jsonb_object_keys(anterior || novo) as chaves(chave)
      where (anterior -> chave) is distinct from (novo -> chave)
    ) alteracoes;
  elsif tg_op = 'INSERT' then
    novo_alterado := novo;
    select coalesce(array_agg(chave order by chave), '{}'::text[])
      into campos
    from jsonb_object_keys(novo) as chaves(chave);
  else
    anterior_alterado := anterior;
    select coalesce(array_agg(chave order by chave), '{}'::text[])
      into campos
    from jsonb_object_keys(anterior) as chaves(chave);
  end if;

  ator := coalesce(
    public.auditoria_try_uuid(current_setting('app.audit_user_id', true)),
    auth.uid()
  );

  if ator is null and tg_op = 'INSERT' then
    ator := coalesce(
      public.auditoria_try_uuid(novo ->> 'created_by'),
      public.auditoria_try_uuid(novo ->> 'createdby'),
      public.auditoria_try_uuid(novo ->> 'usuariocriadorid'),
      public.auditoria_try_uuid(novo ->> 'usuarioid')
    );
  elsif ator is null and tg_op = 'UPDATE' then
    -- Nao usa created_by em alteracoes: isso atribuiria a mudanca ao criador
    -- quando a rota nao informou o editor.
    ator := coalesce(
      public.auditoria_try_uuid(novo ->> 'updated_by'),
      public.auditoria_try_uuid(novo ->> 'updatedby'),
      public.auditoria_try_uuid(novo ->> 'usuarioalteracaoid')
    );
  elsif ator is null and tg_op = 'DELETE' then
    ator := coalesce(
      public.auditoria_try_uuid(anterior ->> 'deleted_by'),
      public.auditoria_try_uuid(anterior ->> 'updated_by'),
      public.auditoria_try_uuid(anterior ->> 'updatedby'),
      public.auditoria_try_uuid(anterior ->> 'usuarioalteracaoid')
    );
  end if;

  -- Uma FK invalida nao deve impedir a operacao principal.
  if ator is not null and not exists (select 1 from public.usuario where id = ator) then
    ator := null;
  end if;

  id_registro := coalesce(
    linha_referencia ->> 'id',
    linha_referencia ->> 'uuid',
    linha_referencia ->> 'ordemservicoid',
    linha_referencia ->> 'vendaid',
    linha_referencia ->> 'produtoid',
    linha_referencia ->> 'clienteid',
    nullif(concat_ws(':', linha_referencia ->> 'perfilid', linha_referencia ->> 'permissaoid'), '')
  );

  insert into public.auditoria_evento (
    operacao,
    modulo,
    tabela,
    registro_id,
    usuario_id,
    dados_anteriores,
    dados_novos,
    campos_alterados,
    origem
  ) values (
    tg_op,
    public.auditoria_modulo_tabela(tg_table_name),
    tg_table_name,
    id_registro,
    ator,
    public.auditoria_json_seguro(anterior_alterado),
    public.auditoria_json_seguro(novo_alterado),
    campos,
    case when ator is null then 'sistema' else 'usuario' end
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
exception when others then
  -- Auditoria nunca deve interromper uma operacao de negocio.
  raise warning 'Falha ao auditar %.%: %', tg_table_schema, tg_table_name, sqlerrm;
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;
create or replace function public.atualizar_permissoes_perfil_auditado(
  p_perfilid integer,
  p_permissoes_ids integer[],
  p_usuario_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_usuario_id is not null and not exists (select 1 from public.usuario where id = p_usuario_id) then
    raise exception 'Usuario responsavel invalido';
  end if;

  if p_usuario_id is not null then
    perform set_config('app.audit_user_id', p_usuario_id::text, true);
  end if;

  delete from public.perfilpermissao pp
  where pp.perfilid = p_perfilid
    and not (pp.permissaoid = any(coalesce(p_permissoes_ids, '{}'::integer[])));

  insert into public.perfilpermissao (perfilid, permissaoid, created_by, updated_by)
  select p_perfilid, permissaoid, p_usuario_id, p_usuario_id
  from unnest(coalesce(p_permissoes_ids, '{}'::integer[])) as permissaoid
  on conflict (perfilid, permissaoid) do nothing;
end;
$$;
revoke all on function public.atualizar_permissoes_perfil_auditado(integer, integer[], uuid)
  from public, anon, authenticated;
grant execute on function public.atualizar_permissoes_perfil_auditado(integer, integer[], uuid)
  to service_role;
-- Carga inicial: representa o estado de cadastros anteriores a auditoria.
-- Esses eventos sao explicitamente marcados como legado e nao fingem ser um
-- historico completo de alteracoes.
insert into public.auditoria_evento (
  ocorrido_em, operacao, modulo, tabela, registro_id, usuario_id,
  dados_novos, campos_alterados, origem, fonte
)
select
  coalesce(o.createdat, o.dataentrada, now()),
  'INSERT', 'ordens', 'ordemservico', o.id::text,
  coalesce(o.created_by, o.usuariocriadorid),
  public.auditoria_json_seguro(to_jsonb(o)),
  array(select jsonb_object_keys(to_jsonb(o))),
  case when coalesce(o.created_by, o.usuariocriadorid) is null then 'sistema' else 'usuario' end,
  'legado'
from public.ordemservico o
where not exists (
  select 1 from public.auditoria_evento a
  where a.fonte = 'legado' and a.tabela = 'ordemservico' and a.registro_id = o.id::text
);
insert into public.auditoria_evento (
  ocorrido_em, operacao, modulo, tabela, registro_id, usuario_id,
  dados_novos, campos_alterados, origem, fonte
)
select
  coalesce(p.createdat, now()), 'INSERT', 'estoque', 'produto', p.id::text, p.created_by,
  public.auditoria_json_seguro(to_jsonb(p)), array(select jsonb_object_keys(to_jsonb(p))),
  case when p.created_by is null then 'sistema' else 'usuario' end, 'legado'
from public.produto p
where not exists (
  select 1 from public.auditoria_evento a
  where a.fonte = 'legado' and a.tabela = 'produto' and a.registro_id = p.id::text
);
insert into public.auditoria_evento (
  ocorrido_em, operacao, modulo, tabela, registro_id, usuario_id,
  dados_novos, campos_alterados, origem, fonte
)
select
  coalesce(c.createdat, now()), 'INSERT', 'clientes', 'cliente', c.id::text, c.created_by,
  public.auditoria_json_seguro(to_jsonb(c)), array(select jsonb_object_keys(to_jsonb(c))),
  case when c.created_by is null then 'sistema' else 'usuario' end, 'legado'
from public.cliente c
where not exists (
  select 1 from public.auditoria_evento a
  where a.fonte = 'legado' and a.tabela = 'cliente' and a.registro_id = c.id::text
);
insert into public.auditoria_evento (
