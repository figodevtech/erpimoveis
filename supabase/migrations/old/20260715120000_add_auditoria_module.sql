create or replace function public.habilitar_auditoria_tabela(nome_tabela regclass)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  schema_nome text;
  tabela_nome text;
begin
  select n.nspname, c.relname
    into schema_nome, tabela_nome
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where c.oid = nome_tabela;

  if schema_nome <> 'public' or tabela_nome = 'auditoria_evento' then
    raise exception 'A auditoria so pode ser habilitada em tabelas de negocio do schema public';
  end if;

  execute format('drop trigger if exists auditoria_linha on %I.%I', schema_nome, tabela_nome);
  execute format(
    'create trigger auditoria_linha after insert or update or delete on %I.%I for each row execute function public.registrar_auditoria()',
    schema_nome,
    tabela_nome
  );
end;
$$;
revoke all on function public.habilitar_auditoria_tabela(regclass) from public, anon, authenticated;
-- Habilita nas tabelas existentes. Logs tecnicos, filas e tabelas de sessao ficam fora
-- para evitar ruido e crescimento desnecessario.
do $$
declare
  tabela record;
begin
  for tabela in
    select c.oid::regclass as nome
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relkind = 'r'
      and c.relname <> 'auditoria_evento'
      and c.relname !~* '(audit|auditoria|log|queue|fila|metric|notification|notificacao|evento|session|verification)'
  loop
    perform public.habilitar_auditoria_tabela(tabela.nome);
  end loop;
end;
$$;
