-- Eventos financeiros persistidos da ordem de servico.
-- Nao representam pagamentos: sao o retrato economico da OS no momento de cada marco.

create table if not exists public.eventos_financeiros (
  id bigint generated by default as identity primary key,
  ordemservicoid integer not null references public.ordemservico(id) on delete cascade,
  origem text not null check (origem in ('PRODUTO', 'SERVICO', 'COMISSAO', 'AVULSO')),
  natureza text not null check (natureza in ('RECEITA', 'DESPESA')),
  status text not null default 'ATIVO' check (status in ('ATIVO', 'CANCELADO', 'CONVERTIDO')),
  chave_origem text,
  descricao text not null,
  detalhe text,
  valor numeric(14,2) not null check (valor >= 0),
  data_evento timestamptz not null default now(),
  produtoid integer references public.produto(id) on delete set null,
  servicoid integer references public.servico(id) on delete set null,
  usuarioid uuid references public.usuario(id) on delete set null,
  quantidade_snapshot numeric(14,4),
  valor_unitario_snapshot numeric(14,4),
  percentual_snapshot numeric(8,4),
  valor_base_snapshot numeric(14,2),
  dados_snapshot jsonb not null default '{}'::jsonb,
  pode_gerar_transacao boolean not null default false,
  transacaoid bigint references public.transacao(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid,
  constraint eventos_financeiros_origem_chave_uk
    unique (ordemservicoid, origem, chave_origem, natureza)
);

create index if not exists idx_eventos_financeiros_os
  on public.eventos_financeiros (ordemservicoid, data_evento, id);
create unique index if not exists idx_eventos_financeiros_transacao
  on public.eventos_financeiros (transacaoid) where transacaoid is not null;

alter table public.transacao
  add column if not exists evento_financeiro_id bigint;

alter table public.transacao
  drop constraint if exists transacao_evento_financeiro_id_fkey;
alter table public.transacao
  add constraint transacao_evento_financeiro_id_fkey
  foreign key (evento_financeiro_id) references public.eventos_financeiros(id) on delete set null;
create unique index if not exists idx_transacao_evento_financeiro
  on public.transacao (evento_financeiro_id) where evento_financeiro_id is not null;

create or replace function public.tg_vincular_transacao_evento_financeiro()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_evento public.eventos_financeiros%rowtype;
begin
  if new.evento_financeiro_id is null then return new; end if;
  select * into v_evento from public.eventos_financeiros where id = new.evento_financeiro_id for update;
  if not found then raise exception 'Evento financeiro nao encontrado.'; end if;
  if v_evento.status <> 'ATIVO' or v_evento.transacaoid is not null then
    raise exception 'Este evento ja foi convertido ou cancelado.';
  end if;
  if v_evento.ordemservicoid <> new.ordemservicoid or v_evento.natureza <> new.tipo::text then
    raise exception 'A transacao nao corresponde a OS ou a natureza do evento financeiro.';
  end if;
  return new;
end;
$$;

create or replace function public.tg_confirmar_transacao_evento_financeiro()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.evento_financeiro_id is not null then
    update public.eventos_financeiros
       set status = 'CONVERTIDO', transacaoid = new.id, updated_at = now()
     where id = new.evento_financeiro_id;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_validar_transacao_evento_financeiro on public.transacao;
create trigger trg_validar_transacao_evento_financeiro
before insert on public.transacao for each row execute function public.tg_vincular_transacao_evento_financeiro();
drop trigger if exists trg_confirmar_transacao_evento_financeiro on public.transacao;
create trigger trg_confirmar_transacao_evento_financeiro
after insert on public.transacao for each row execute function public.tg_confirmar_transacao_evento_financeiro();

create or replace function public.sincronizar_eventos_financeiros_os(
  p_ordemservicoid integer,
  p_incluir_comissoes boolean default false
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_total_itens numeric := 0;
  v_total_os numeric := 0;
  v_fator numeric := 1;
begin
  select coalesce(o.orcamentototal, 0),
         coalesce((select sum(coalesce(op.subtotal, 0)) from public.osproduto op where op.ordemservicoid = o.id), 0)
           + coalesce((select sum(coalesce(os.subtotal, 0)) from public.osservico os where os.ordemservicoid = o.id), 0)
    into v_total_os, v_total_itens
  from public.ordemservico o
  where o.id = p_ordemservicoid;

  if not found then return; end if;
  if v_total_itens > 0 then v_fator := v_total_os / v_total_itens; end if;

  insert into public.eventos_financeiros
    (ordemservicoid, origem, natureza, chave_origem, descricao, detalhe, valor,
     produtoid, quantidade_snapshot, valor_unitario_snapshot, dados_snapshot)
  select p_ordemservicoid, 'PRODUTO', 'RECEITA', op.produtoid::text,
         'Venda - ' || coalesce(nullif(p.titulo, ''), nullif(p.descricao, ''), 'Produto #' || op.produtoid),
         op.quantidade || ' unidade(s)', round(coalesce(op.subtotal, 0) * v_fator, 2),
         op.produtoid, op.quantidade, op.precounitario,
         jsonb_build_object('subtotal', op.subtotal, 'fator_desconto_os', v_fator)
  from public.osproduto op join public.produto p on p.id = op.produtoid
  where op.ordemservicoid = p_ordemservicoid
  on conflict (ordemservicoid, origem, chave_origem, natureza) do nothing;

  insert into public.eventos_financeiros
    (ordemservicoid, origem, natureza, chave_origem, descricao, detalhe, valor,
     produtoid, quantidade_snapshot, valor_unitario_snapshot, dados_snapshot)
  select p_ordemservicoid, 'PRODUTO', 'DESPESA', op.produtoid::text,
         'Custo - ' || coalesce(nullif(p.titulo, ''), nullif(p.descricao, ''), 'Produto #' || op.produtoid),
         case when op.custo_unitario_aplicado is null then 'Ultimo valor de compra no momento da aprovacao' else 'Custo registrado na OS' end,
         round(coalesce(op.custo_unitario_aplicado, p.ultimovalordecompra, 0) * coalesce(op.quantidade, 0), 2),
         op.produtoid, op.quantidade, coalesce(op.custo_unitario_aplicado, p.ultimovalordecompra, 0),
         jsonb_build_object('custo_nao_informado', op.custo_unitario_aplicado is null and p.ultimovalordecompra is null,
                            'custo_estimado', op.custo_unitario_aplicado is null and p.ultimovalordecompra is not null)
  from public.osproduto op join public.produto p on p.id = op.produtoid
  where op.ordemservicoid = p_ordemservicoid
  on conflict (ordemservicoid, origem, chave_origem, natureza) do nothing;

  insert into public.eventos_financeiros
    (ordemservicoid, origem, natureza, chave_origem, descricao, detalhe, valor,
     servicoid, quantidade_snapshot, valor_unitario_snapshot, dados_snapshot)
  select p_ordemservicoid, 'SERVICO', 'RECEITA', os.servicoid::text,
         'Servico - ' || coalesce(nullif(os.descricao, ''), nullif(s.descricao, ''), 'Servico #' || os.servicoid),
         os.quantidade || ' unidade(s)', round(coalesce(os.subtotal, 0) * v_fator, 2),
         os.servicoid, os.quantidade, os.precounitario,
         jsonb_build_object('subtotal', os.subtotal, 'fator_desconto_os', v_fator)
  from public.osservico os join public.servico s on s.id = os.servicoid
  where os.ordemservicoid = p_ordemservicoid
  on conflict (ordemservicoid, origem, chave_origem, natureza) do nothing;

  if p_incluir_comissoes then
    insert into public.eventos_financeiros
      (ordemservicoid, origem, natureza, chave_origem, descricao, detalhe, valor,
       servicoid, usuarioid, percentual_snapshot, valor_base_snapshot, dados_snapshot, pode_gerar_transacao)
    select p_ordemservicoid, 'COMISSAO', 'DESPESA', r.servicoid || ':' || r.usuarioid,
           'Comissao - ' || coalesce(nullif(os.descricao, ''), nullif(s.descricao, ''), 'Servico #' || r.servicoid),
           coalesce(u.nome, 'Realizador'), coalesce(r.valor_comissao, 0),
           r.servicoid, r.usuarioid, r.comissao_percent_aplicada, r.valor_base,
           jsonb_build_object('realizador_nome', u.nome), true
    from public.osservico_realizador r
    join public.osservico os on os.ordemservicoid = r.ordemservicoid and os.servicoid = r.servicoid
    join public.servico s on s.id = r.servicoid
    left join public.usuario u on u.id = r.usuarioid
    where r.ordemservicoid = p_ordemservicoid
    on conflict (ordemservicoid, origem, chave_origem, natureza) do nothing;
  end if;
end;
$$;

create or replace function public.tg_gerar_eventos_financeiros_os()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'ORCAMENTO_APROVADO' and old.status is distinct from new.status then
    perform public.sincronizar_eventos_financeiros_os(new.id, false);
  elsif new.status = 'EM_ANDAMENTO' and old.status is distinct from new.status then
    if exists (
      select 1 from public.osservico s
      where s.ordemservicoid = new.id
        and not exists (select 1 from public.osservico_realizador r
                        where r.ordemservicoid = s.ordemservicoid and r.servicoid = s.servicoid)
    ) then
      raise exception 'Defina os realizadores de todos os servicos antes de iniciar a OS.';
    end if;
    perform public.sincronizar_eventos_financeiros_os(new.id, true);
  end if;
  return new;
end;
$$;

drop trigger if exists trg_gerar_eventos_financeiros_os on public.ordemservico;
create trigger trg_gerar_eventos_financeiros_os
after update of status on public.ordemservico
for each row execute function public.tg_gerar_eventos_financeiros_os();

create or replace function public.converter_evento_financeiro_em_transacao(
  p_eventoid bigint,
  p_usuarioid uuid default null
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_evento public.eventos_financeiros%rowtype;
  v_transacaoid bigint;
begin
  select * into v_evento from public.eventos_financeiros where id = p_eventoid for update;
  if not found then raise exception 'Evento financeiro nao encontrado.'; end if;
  if v_evento.origem not in ('AVULSO', 'COMISSAO') or not v_evento.pode_gerar_transacao then
    raise exception 'Este evento nao pode gerar uma transacao.';
  end if;
  if v_evento.status <> 'ATIVO' or v_evento.transacaoid is not null then
    raise exception 'Este evento ja foi convertido ou cancelado.';
  end if;

  insert into public.transacao
    (descricao, valor, "valorLiquido", data, tipo, ordemservicoid, pendente,
     categoria, nomepagador, cpfcnpjpagador, created_by, evento_financeiro_id)
  values
    (v_evento.descricao, v_evento.valor, v_evento.valor, now(),
     v_evento.natureza::public.tipos_transacao, v_evento.ordemservicoid, true,
     'NAO RELACIONADO', 'Evento financeiro OS #' || v_evento.ordemservicoid, '',
     p_usuarioid, v_evento.id)
  returning id into v_transacaoid;

  update public.eventos_financeiros
     set status = 'CONVERTIDO', transacaoid = v_transacaoid, updated_at = now()
   where id = v_evento.id;
  return v_transacaoid;
end;
$$;

-- OSs que ja passaram pelos marcos tambem recebem o retrato atual uma unica vez.
do $$ declare r record; begin
  for r in select id, status::text status from public.ordemservico
           where status::text in ('ORCAMENTO_APROVADO','EM_ANDAMENTO','PAGAMENTO','SEM_COBRANCA','CONCLUIDO')
             and coalesce(is_deleted, false) = false
  loop
    perform public.sincronizar_eventos_financeiros_os(r.id, r.status in ('EM_ANDAMENTO','PAGAMENTO','SEM_COBRANCA','CONCLUIDO'));
  end loop;
end $$;

grant select, insert, update on public.eventos_financeiros to authenticated, service_role;
grant usage, select on sequence public.eventos_financeiros_id_seq to authenticated, service_role;
grant execute on function public.sincronizar_eventos_financeiros_os(integer, boolean) to service_role;
grant execute on function public.converter_evento_financeiro_em_transacao(bigint, uuid) to service_role;
