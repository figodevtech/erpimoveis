GRANT ALL ON TABLE public.fiscal_dfe_documento TO anon;
GRANT ALL ON TABLE public.fiscal_dfe_documento TO authenticated;
GRANT ALL ON TABLE public.fiscal_dfe_documento TO service_role;
GRANT EXECUTE ON FUNCTION public.fiscal_try_lock_dfe(integer, timestamp with time zone) TO anon;
