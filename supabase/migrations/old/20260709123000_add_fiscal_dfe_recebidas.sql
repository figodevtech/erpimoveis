CREATE TABLE IF NOT EXISTS public.fiscal_dfe_controle (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL REFERENCES public.empresa(id) ON DELETE CASCADE,
  ult_nsu text NOT NULL DEFAULT '000000000000000',
  max_nsu text NOT NULL DEFAULT '000000000000000',
  last_sync_at timestamp with time zone,
  last_cstat text,
  last_xmotivo text,
  consumo_indevido_until timestamp with time zone,
  sync_lock_until timestamp with time zone,
  sync_started_at timestamp with time zone,
  createdat timestamp with time zone NOT NULL DEFAULT now(),
  updatedat timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_dfe_controle_empresa_id_key UNIQUE (empresa_id)
);

CREATE TABLE IF NOT EXISTS public.fiscal_dfe_documento (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL REFERENCES public.empresa(id) ON DELETE CASCADE,
  nsu text NOT NULL,
  schema text NOT NULL,
  tipo_documento text NOT NULL,
  chave_acesso text,
  data_emissao timestamp with time zone,
  emitente_nome text,
  emitente_cnpj text,
  valor_total numeric(14,2),
  status text,
  status_manifestacao text,
  xml text NOT NULL,
  resumo jsonb NOT NULL DEFAULT '{}'::jsonb,
  createdat timestamp with time zone NOT NULL DEFAULT now(),
  updatedat timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_dfe_documento_empresa_nsu_key UNIQUE (empresa_id, nsu)
);

CREATE UNIQUE INDEX IF NOT EXISTS fiscal_dfe_documento_empresa_chave_schema_key
  ON public.fiscal_dfe_documento (empresa_id, chave_acesso, schema)
  WHERE chave_acesso IS NOT NULL AND btrim(chave_acesso) <> '';

CREATE INDEX IF NOT EXISTS idx_fiscal_dfe_documento_empresa_data
  ON public.fiscal_dfe_documento (empresa_id, data_emissao DESC);

CREATE INDEX IF NOT EXISTS idx_fiscal_dfe_documento_chave
  ON public.fiscal_dfe_documento (chave_acesso);

CREATE OR REPLACE FUNCTION public.fiscal_try_lock_dfe(
  p_empresa_id integer,
  p_lock_until timestamp with time zone
)
RETURNS boolean
LANGUAGE plpgsql
AS $$
DECLARE
  v_id bigint;
BEGIN
  INSERT INTO public.fiscal_dfe_controle (
    empresa_id,
    sync_lock_until,
    sync_started_at,
    updatedat
  )
  VALUES (
    p_empresa_id,
    p_lock_until,
    now(),
    now()
  )
  ON CONFLICT (empresa_id)
  DO UPDATE SET
    sync_lock_until = EXCLUDED.sync_lock_until,
    sync_started_at = now(),
    updatedat = now()
  WHERE public.fiscal_dfe_controle.sync_lock_until IS NULL
     OR public.fiscal_dfe_controle.sync_lock_until < now()
  RETURNING id INTO v_id;

  RETURN v_id IS NOT NULL;
END;
$$;

