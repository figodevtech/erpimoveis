create table if not exists public.lote_imagem (
  id bigint generated by default as identity primary key,
  lote_id bigint not null references public.lotes(id) on delete cascade,
  url text not null,
  path text,
  ordem integer not null default 1,
  createdat timestamptz not null default now()
);

create index if not exists idx_lote_imagem_lote_id_ordem
  on public.lote_imagem (lote_id, ordem);

alter table public.lotes
  add column if not exists "imgUrl" text;

insert into storage.buckets (id, name, public)
values ('lote_imagem', 'lote_imagem', true)
on conflict (id) do nothing;
