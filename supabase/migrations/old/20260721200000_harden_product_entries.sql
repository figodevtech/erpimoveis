-- Entradas de estoque confirmadas, atômicas e rastreáveis.
-- O sistema é monoempresa; nenhuma relação empresa_id é criada aqui.

BEGIN;

ALTER TABLE public.entrada
  ADD COLUMN IF NOT EXISTS origem text NOT NULL DEFAULT 'MANUAL',
  ADD COLUMN IF NOT EXISTS numero_nota text,
  ADD COLUMN IF NOT EXISTS serie_nota text,
  ADD COLUMN IF NOT EXISTS data_emissao timestamp with time zone,
  ADD COLUMN IF NOT EXISTS fiscal_dfe_documento_id bigint,
  ADD COLUMN IF NOT EXISTS valor_total numeric(14,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS cancelada_at timestamp with time zone;

ALTER TABLE public.entrada
  DROP CONSTRAINT IF EXISTS entrada_origem_check;
ALTER TABLE public.entrada
  ADD CONSTRAINT entrada_origem_check
  CHECK (origem IN ('AJUSTE_RAPIDO', 'MANUAL', 'NFE_TERCEIRO'));

DO $$
BEGIN
  IF to_regclass('public.fiscal_dfe_documento') IS NOT NULL
     AND NOT EXISTS (
       SELECT 1 FROM pg_constraint
       WHERE conname = 'entrada_fiscal_dfe_documento_id_fkey'
     ) THEN
    ALTER TABLE public.entrada
      ADD CONSTRAINT entrada_fiscal_dfe_documento_id_fkey
      FOREIGN KEY (fiscal_dfe_documento_id)
      REFERENCES public.fiscal_dfe_documento(id) ON DELETE RESTRICT;
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS entrada_fiscal_dfe_documento_unique
  ON public.entrada(fiscal_dfe_documento_id)
  WHERE fiscal_dfe_documento_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS entrada_notachave_valida_unique
  ON public.entrada(notachave)
  WHERE fiscal AND notachave ~ '^[0-9]{44}$';

ALTER TABLE public.entradaitens
  ADD COLUMN IF NOT EXISTS valor_unitario_compra numeric(14,4),
  ADD COLUMN IF NOT EXISTS valor_desconto numeric(14,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS valor_frete numeric(14,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS outras_despesas numeric(14,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS valor_total numeric(14,2);

UPDATE public.entradaitens ei
SET valor_unitario_compra = COALESCE(
      p.ultimovalordecompra,
      p.precocompra,
      ei.precovenda,
      0
    ),
    valor_total = round(
      ei.quantidade * COALESCE(
        p.ultimovalordecompra,
        p.precocompra,
        ei.precovenda,
        0
      ), 2
    )
FROM public.produto p
WHERE p.id = ei.produto_id
  AND (ei.valor_unitario_compra IS NULL OR ei.valor_total IS NULL);

ALTER TABLE public.entradaitens
  ALTER COLUMN valor_unitario_compra SET NOT NULL,
  ALTER COLUMN valor_total SET NOT NULL;

ALTER TABLE public.entradaitens
  DROP CONSTRAINT IF EXISTS entradaitens_quantidade_positiva_check,
  DROP CONSTRAINT IF EXISTS entradaitens_valores_compra_check;
ALTER TABLE public.entradaitens
  ADD CONSTRAINT entradaitens_quantidade_positiva_check
    CHECK (quantidade > 0 AND quantidade = trunc(quantidade)) NOT VALID,
  ADD CONSTRAINT entradaitens_valores_compra_check
    CHECK (
      valor_unitario_compra >= 0 AND valor_desconto >= 0
      AND valor_frete >= 0 AND outras_despesas >= 0 AND valor_total >= 0
    ) NOT VALID;

ALTER TABLE public.transacao
  ADD COLUMN IF NOT EXISTS entrada_id bigint,
  ADD COLUMN IF NOT EXISTS estorno_transacao_id bigint;

ALTER TABLE public.transacao
  DROP CONSTRAINT IF EXISTS transacao_entrada_id_fkey,
  DROP CONSTRAINT IF EXISTS transacao_estorno_transacao_id_fkey;
ALTER TABLE public.transacao
  ADD CONSTRAINT transacao_entrada_id_fkey
    FOREIGN KEY (entrada_id) REFERENCES public.entrada(id) ON DELETE RESTRICT,
  ADD CONSTRAINT transacao_estorno_transacao_id_fkey
    FOREIGN KEY (estorno_transacao_id) REFERENCES public.transacao(id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS transacao_entrada_id_idx ON public.transacao(entrada_id);
CREATE UNIQUE INDEX IF NOT EXISTS transacao_estorno_unique
  ON public.transacao(estorno_transacao_id)
  WHERE estorno_transacao_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.estoque_movimento_entrada (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entrada_id bigint NOT NULL REFERENCES public.entrada(id) ON DELETE RESTRICT,
  entrada_item_id bigint REFERENCES public.entradaitens(id) ON DELETE RESTRICT,
  produto_id integer NOT NULL REFERENCES public.produto(id) ON DELETE RESTRICT,
  tipo text NOT NULL CHECK (tipo IN ('ENTRADA', 'CANCELAMENTO')),
  quantidade integer NOT NULL CHECK (quantidade > 0),
  saldo_anterior integer,
  saldo_resultante integer,
  valor_unitario_compra numeric(14,4) NOT NULL CHECK (valor_unitario_compra >= 0),
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  UNIQUE (entrada_item_id, tipo)
);

CREATE INDEX IF NOT EXISTS estoque_movimento_entrada_produto_idx
  ON public.estoque_movimento_entrada(produto_id, created_at DESC);
CREATE INDEX IF NOT EXISTS estoque_movimento_entrada_entrada_idx
  ON public.estoque_movimento_entrada(entrada_id);

ALTER TABLE public.estoque_movimento_entrada OWNER TO postgres;
GRANT ALL ON TABLE public.estoque_movimento_entrada TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.estoque_movimento_entrada_id_seq TO service_role;

-- O estoque legado já foi movimentado. Registramos somente a trilha histórica,
-- sem aplicar novamente as quantidades ao saldo atual.
INSERT INTO public.estoque_movimento_entrada (
  entrada_id, entrada_item_id, produto_id, tipo, quantidade,
  valor_unitario_compra
)
SELECT ei.entrada_id, ei.id, ei.produto_id, 'ENTRADA', ei.quantidade::integer,
       ei.valor_unitario_compra
FROM public.entradaitens ei
WHERE ei.quantidade > 0
  AND ei.quantidade = trunc(ei.quantidade)
ON CONFLICT (entrada_item_id, tipo) DO NOTHING;

-- Algumas bases antigas nunca tiveram o valor RASCUNHO no enum. O comando
-- dinâmico evita tentar converter um literal inexistente nessas instalações.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM pg_type t
    JOIN pg_enum e ON e.enumtypid = t.oid
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public'
      AND t.typname = 'enum_status_entrada'
      AND e.enumlabel = 'RASCUNHO'
  ) THEN
    EXECUTE $sql$
      UPDATE public.entrada
      SET status = 'CONFIRMADA'
      WHERE status::text = 'RASCUNHO'
    $sql$;
  END IF;
END;
$$;

ALTER TABLE public.entrada ALTER COLUMN status DROP DEFAULT;
ALTER TYPE public.enum_status_entrada RENAME TO enum_status_entrada_legacy;
CREATE TYPE public.enum_status_entrada AS ENUM ('CONFIRMADA', 'CANCELADA');
ALTER TABLE public.entrada
  ALTER COLUMN status TYPE public.enum_status_entrada
  USING status::text::public.enum_status_entrada;
ALTER TABLE public.entrada
  ALTER COLUMN status SET DEFAULT 'CONFIRMADA'::public.enum_status_entrada;
DROP TYPE public.enum_status_entrada_legacy;

UPDATE public.entrada
SET origem = CASE WHEN fiscal THEN 'NFE_TERCEIRO' ELSE 'MANUAL' END,
    valor_total = COALESCE((
      SELECT round(sum(ei.valor_total), 2)
      FROM public.entradaitens ei
      WHERE ei.entrada_id = entrada.id
    ), 0);

-- Registros legados com chave em notação científica continuam consultáveis.
-- A restrição NOT VALID passa a proteger toda nova entrada sem bloquear a migração.
ALTER TABLE public.entrada
  DROP CONSTRAINT IF EXISTS entrada_notachave_formato_check;
ALTER TABLE public.entrada
  ADD CONSTRAINT entrada_notachave_formato_check
  CHECK (NOT fiscal OR notachave ~ '^[0-9]{44}$') NOT VALID;

CREATE OR REPLACE FUNCTION public.registrar_entrada_confirmada(
  p_entrada jsonb,
  p_itens jsonb,
  p_transacoes jsonb DEFAULT '[]'::jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_entrada_id bigint;
  v_item jsonb;
  v_item_id bigint;
  v_produto public.produto%ROWTYPE;
  v_produto_id integer;
  v_quantidade integer;
  v_custo numeric(14,4);
  v_desconto numeric(14,2);
  v_frete numeric(14,2);
  v_outras numeric(14,2);
  v_total_item numeric(14,2);
  v_total numeric(14,2) := 0;
  v_total_documento numeric(14,2) := nullif(p_entrada->>'valor_total_documento', '')::numeric;
  v_total_financeiro numeric(14,2) := 0;
  v_transacao jsonb;
  v_chave text := nullif(regexp_replace(coalesce(p_entrada->>'notachave', ''), '\D', '', 'g'), '');
  v_fiscal boolean := coalesce((p_entrada->>'fiscal')::boolean, false);
  v_origem text := coalesce(nullif(p_entrada->>'origem', ''), 'MANUAL');
BEGIN
  IF jsonb_typeof(p_itens) <> 'array' OR jsonb_array_length(p_itens) = 0 THEN
    RAISE EXCEPTION 'Informe ao menos um item para a entrada.' USING ERRCODE = '22023';
  END IF;

  IF v_origem NOT IN ('AJUSTE_RAPIDO', 'MANUAL', 'NFE_TERCEIRO') THEN
    RAISE EXCEPTION 'Origem da entrada inválida.' USING ERRCODE = '22023';
  END IF;
  IF v_total_documento IS NOT NULL AND v_total_documento < 0 THEN
    RAISE EXCEPTION 'O total do documento fiscal não pode ser negativo.' USING ERRCODE = '22023';
  END IF;

  IF v_fiscal AND (v_chave IS NULL OR length(v_chave) <> 44) THEN
    RAISE EXCEPTION 'A entrada fiscal exige uma chave de acesso com 44 dígitos.' USING ERRCODE = '22023';
  END IF;
  IF v_fiscal AND nullif(p_entrada->>'fornecedorid', '') IS NULL THEN
    RAISE EXCEPTION 'A entrada fiscal exige um fornecedor vinculado.' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.entrada (
    fornecedorid, fiscal, notachave, tipo, status, origem,
    numero_nota, serie_nota, data_emissao, fiscal_dfe_documento_id, valor_total
  ) VALUES (
    nullif(p_entrada->>'fornecedorid', '')::integer,
    v_fiscal,
    v_chave,
    coalesce(nullif(p_entrada->>'tipo', ''), 'COMPRA_FORNECEDOR')::public.enum_tipos_entrada,
    'CONFIRMADA'::public.enum_status_entrada,
    v_origem,
    nullif(p_entrada->>'numero_nota', ''),
    nullif(p_entrada->>'serie_nota', ''),
    nullif(p_entrada->>'data_emissao', '')::timestamp with time zone,
    nullif(p_entrada->>'fiscal_dfe_documento_id', '')::bigint,
    0
  ) RETURNING id INTO v_entrada_id;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_itens)
  LOOP
    v_produto_id := nullif(v_item->>'produto_id', '')::integer;
    v_quantidade := nullif(v_item->>'quantidade', '')::integer;
    v_custo := nullif(v_item->>'valor_unitario_compra', '')::numeric;
    v_desconto := coalesce(nullif(v_item->>'valor_desconto', '')::numeric, 0);
    v_frete := coalesce(nullif(v_item->>'valor_frete', '')::numeric, 0);
    v_outras := coalesce(nullif(v_item->>'outras_despesas', '')::numeric, 0);

    IF v_produto_id IS NULL OR v_quantidade IS NULL OR v_quantidade <= 0 THEN
      RAISE EXCEPTION 'Produto e quantidade inteira positiva são obrigatórios.' USING ERRCODE = '22023';
    END IF;
    IF v_custo IS NULL OR v_custo < 0 OR v_desconto < 0 OR v_frete < 0 OR v_outras < 0 THEN
      RAISE EXCEPTION 'Os valores de compra do item são inválidos.' USING ERRCODE = '22023';
    END IF;

    SELECT * INTO v_produto FROM public.produto WHERE id = v_produto_id FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Produto % não encontrado.', v_produto_id USING ERRCODE = 'P0002';
    END IF;

    v_total_item := round((v_quantidade * v_custo) - v_desconto + v_frete + v_outras, 2);
    IF v_total_item < 0 THEN
      RAISE EXCEPTION 'O total do item não pode ser negativo.' USING ERRCODE = '22023';
    END IF;

    INSERT INTO public.entradaitens (
      entrada_id, produto_id, quantidade, precovenda, unidade,
      valor_unitario_compra, valor_desconto, valor_frete, outras_despesas, valor_total,
      ncm, cest, csosn, referencia, titulo, "cClassTrib", "cstIbs", "cstCbs",
      cst, aliquotaicms, cfop, cst_pis, aliquota_pis, cst_cofins, aliquota_cofins
    ) VALUES (
      v_entrada_id, v_produto_id, v_quantidade, coalesce(v_produto.precovenda, 0),
      coalesce(nullif(v_item->>'unidade', '')::public.unidade_medida, v_produto.unidade, 'UN'),
      v_custo, v_desconto, v_frete, v_outras, v_total_item,
      coalesce(nullif(v_item->>'ncm', ''), v_produto.ncm),
      coalesce(nullif(v_item->>'cest', ''), v_produto.cest),
      coalesce(nullif(v_item->>'csosn', ''), v_produto.csosn),
      coalesce(nullif(v_item->>'referencia', ''), v_produto.referencia),
      coalesce(nullif(v_item->>'titulo', ''), v_produto.titulo),
      coalesce(nullif(v_item->>'cClassTrib', ''), v_produto."cClassTrib"),
      coalesce(nullif(v_item->>'cstIbs', ''), v_produto."cstIbs"),
      coalesce(nullif(v_item->>'cstCbs', ''), v_produto."cstCbs"),
      coalesce(nullif(v_item->>'cst', ''), v_produto.cst),
      coalesce(nullif(v_item->>'aliquotaicms', '')::numeric, v_produto.aliquotaicms),
      coalesce(nullif(v_item->>'cfop', ''), v_produto.cfop),
      coalesce(nullif(v_item->>'cst_pis', ''), v_produto.cst_pis),
      coalesce(nullif(v_item->>'aliquota_pis', '')::numeric, v_produto.aliquota_pis),
      coalesce(nullif(v_item->>'cst_cofins', ''), v_produto.cst_cofins),
      coalesce(nullif(v_item->>'aliquota_cofins', '')::numeric, v_produto.aliquota_cofins)
    ) RETURNING id INTO v_item_id;

    UPDATE public.produto
    SET estoque = coalesce(estoque, 0) + v_quantidade,
        ultimovalordecompra = v_custo,
        updatedat = now()
    WHERE id = v_produto_id;

    INSERT INTO public.estoque_movimento_entrada (
      entrada_id, entrada_item_id, produto_id, tipo, quantidade,
      saldo_anterior, saldo_resultante, valor_unitario_compra
    ) VALUES (
      v_entrada_id, v_item_id, v_produto_id, 'ENTRADA', v_quantidade,
      coalesce(v_produto.estoque, 0), coalesce(v_produto.estoque, 0) + v_quantidade, v_custo
    );

    v_total := v_total + v_total_item;
  END LOOP;

  UPDATE public.entrada
  SET valor_total = round(coalesce(v_total_documento, v_total), 2)
  WHERE id = v_entrada_id;

  IF p_transacoes IS NOT NULL AND jsonb_typeof(p_transacoes) = 'array'
     AND jsonb_array_length(p_transacoes) > 0 THEN
    SELECT round(coalesce(sum((value->>'valor')::numeric), 0), 2)
      INTO v_total_financeiro
    FROM jsonb_array_elements(p_transacoes);
    IF v_total_financeiro <> round(coalesce(v_total_documento, v_total), 2) THEN
      RAISE EXCEPTION 'A soma dos lançamentos financeiros (%) difere do total da entrada (%).',
        v_total_financeiro, round(coalesce(v_total_documento, v_total), 2) USING ERRCODE = '22023';
    END IF;

    FOR v_transacao IN SELECT value FROM jsonb_array_elements(p_transacoes)
    LOOP
      IF coalesce((v_transacao->>'valor')::numeric, 0) <= 0 THEN
        RAISE EXCEPTION 'O valor do lançamento financeiro deve ser positivo.' USING ERRCODE = '22023';
      END IF;
      INSERT INTO public.transacao (
        descricao, valor, "valorLiquido", data, metodopagamento, categoria, categoria_id,
        tipo, cliente_id, banco_id, nomepagador, cpfcnpjpagador, pendente,
        plano_de_conta_id, plano_de_conta, centro_custo_id, centro_custo, entrada_id
      ) VALUES (
        coalesce(nullif(v_transacao->>'descricao', ''), 'Compra de mercadorias'),
        (v_transacao->>'valor')::numeric,
        (v_transacao->>'valor')::numeric,
        coalesce(nullif(v_transacao->>'data', '')::timestamp with time zone, now()),
        nullif(v_transacao->>'metodopagamento', '')::public.metodo_pagamento,
        coalesce(nullif(v_transacao->>'categoria', ''), 'NÃO RELACIONADO'),
        nullif(v_transacao->>'categoria_id', '')::integer,
        'DESPESA'::public.tipos_transacao,
        NULL,
        nullif(v_transacao->>'banco_id', '')::bigint,
        coalesce(nullif(v_transacao->>'nomepagador', ''), 'Fornecedor'),
        coalesce(nullif(regexp_replace(v_transacao->>'cpfcnpjpagador', '\D', '', 'g'), ''), 'NÃO INFORMADO'),
        coalesce((v_transacao->>'pendente')::boolean, false),
        nullif(v_transacao->>'plano_de_conta_id', '')::integer,
        nullif(v_transacao->>'plano_de_conta', ''),
        nullif(v_transacao->>'centro_custo_id', '')::integer,
        nullif(v_transacao->>'centro_custo', ''),
        v_entrada_id
      );
    END LOOP;
  END IF;

  RETURN jsonb_build_object(
    'entrada_id', v_entrada_id,
    'valor_total', round(coalesce(v_total_documento, v_total), 2)
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.cancelar_entrada_confirmada(p_entrada_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_entrada public.entrada%ROWTYPE;
  v_item record;
  v_estoque integer;
  v_ultimo_custo numeric;
  v_transacao public.transacao%ROWTYPE;
  v_tipo_estorno public.tipos_transacao;
BEGIN
  SELECT * INTO v_entrada FROM public.entrada WHERE id = p_entrada_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Entrada não encontrada.' USING ERRCODE = 'P0002';
  END IF;
  IF v_entrada.status = 'CANCELADA'::public.enum_status_entrada THEN
    RAISE EXCEPTION 'Esta entrada já está cancelada.' USING ERRCODE = '22023';
  END IF;

  FOR v_item IN
    SELECT * FROM public.entradaitens WHERE entrada_id = p_entrada_id ORDER BY id FOR UPDATE
  LOOP
    SELECT estoque INTO v_estoque FROM public.produto WHERE id = v_item.produto_id FOR UPDATE;
    IF coalesce(v_estoque, 0) < v_item.quantidade THEN
      RAISE EXCEPTION 'Não há saldo suficiente do produto % para cancelar a entrada.', v_item.produto_id
        USING ERRCODE = '22023';
    END IF;

    UPDATE public.produto
    SET estoque = estoque - v_item.quantidade::integer, updatedat = now()
    WHERE id = v_item.produto_id;

    INSERT INTO public.estoque_movimento_entrada (
      entrada_id, entrada_item_id, produto_id, tipo, quantidade,
      saldo_anterior, saldo_resultante, valor_unitario_compra
    ) VALUES (
      p_entrada_id, v_item.id, v_item.produto_id, 'CANCELAMENTO', v_item.quantidade::integer,
      v_estoque, v_estoque - v_item.quantidade::integer, v_item.valor_unitario_compra
    );

    SELECT ei.valor_unitario_compra INTO v_ultimo_custo
    FROM public.entradaitens ei
    JOIN public.entrada e ON e.id = ei.entrada_id
    WHERE ei.produto_id = v_item.produto_id
      AND e.id <> p_entrada_id
      AND e.status = 'CONFIRMADA'::public.enum_status_entrada
    ORDER BY e.created_at DESC, e.id DESC, ei.id DESC LIMIT 1;

    UPDATE public.produto
    SET ultimovalordecompra = v_ultimo_custo
    WHERE id = v_item.produto_id;
  END LOOP;

  FOR v_transacao IN
    SELECT * FROM public.transacao
    WHERE entrada_id = p_entrada_id AND NOT is_deleted AND estorno_transacao_id IS NULL
    FOR UPDATE
  LOOP
    IF v_transacao.pendente THEN
      UPDATE public.transacao
      SET pendente = false, is_deleted = true, deleted_at = now(), updated_at = now()
      WHERE id = v_transacao.id;
    ELSE
      v_tipo_estorno := CASE v_transacao.tipo
        WHEN 'DESPESA'::public.tipos_transacao THEN 'RECEITA'::public.tipos_transacao
        WHEN 'RECEITA'::public.tipos_transacao THEN 'DESPESA'::public.tipos_transacao
        WHEN 'DEPOSITO'::public.tipos_transacao THEN 'SAQUE'::public.tipos_transacao
        ELSE 'DEPOSITO'::public.tipos_transacao
      END;
      INSERT INTO public.transacao (
        descricao, valor, "valorLiquido", data, metodopagamento, categoria, categoria_id,
        tipo, cliente_id, banco_id, nomepagador, cpfcnpjpagador, pendente,
        plano_de_conta_id, plano_de_conta, centro_custo_id, centro_custo,
        entrada_id, estorno_transacao_id
      ) VALUES (
        'Estorno: ' || v_transacao.descricao, v_transacao.valor, v_transacao."valorLiquido", now(),
        v_transacao.metodopagamento, v_transacao.categoria, v_transacao.categoria_id,
        v_tipo_estorno, v_transacao.cliente_id, v_transacao.banco_id,
        v_transacao.nomepagador, v_transacao.cpfcnpjpagador, false,
        v_transacao.plano_de_conta_id, v_transacao.plano_de_conta,
        v_transacao.centro_custo_id, v_transacao.centro_custo,
        p_entrada_id, v_transacao.id
      );
    END IF;
  END LOOP;

  UPDATE public.entrada
  SET status = 'CANCELADA'::public.enum_status_entrada, cancelada_at = now()
  WHERE id = p_entrada_id;

  RETURN jsonb_build_object('entrada_id', p_entrada_id, 'status', 'CANCELADA');
END;
$$;

REVOKE ALL ON FUNCTION public.registrar_entrada_confirmada(jsonb, jsonb, jsonb) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.cancelar_entrada_confirmada(bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.registrar_entrada_confirmada(jsonb, jsonb, jsonb) TO service_role;
GRANT EXECUTE ON FUNCTION public.cancelar_entrada_confirmada(bigint) TO service_role;

-- Toda mutação passa pelos endpoints autorizados e pelas RPCs transacionais.
REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
  ON public.entrada, public.entradaitens, public.estoque_movimento_entrada
  FROM anon, authenticated;
GRANT SELECT ON public.entrada, public.entradaitens, public.estoque_movimento_entrada
  TO anon, authenticated;

COMMIT;
