CREATE OR REPLACE FUNCTION public.fiscal_registrar_cancelamento_nfe(
  p_nfe_id bigint,
  p_empresa_id integer,
  p_chave_acesso text,
  p_justificativa text,
  p_status_evento text,
  p_protocolo_evento text,
  p_data_evento_original text,
  p_data_evento_civil date,
  p_data_evento_offset text,
  p_data_evento_instante_utc timestamptz,
  p_xml_evento text,
  p_resposta_sefaz text,
  p_xml_sha256 text,
  p_resposta_sha256 text
)
RETURNS void
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_evento public.fiscal_documento_evento%ROWTYPE;
BEGIN
  PERFORM 1
    FROM public.nfe
   WHERE id = p_nfe_id
     AND empresaid = p_empresa_id
     AND chave_acesso = p_chave_acesso
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'NF-e do cancelamento não encontrada ou contexto divergente.'
      USING ERRCODE = 'P0002';
  END IF;

  SELECT * INTO v_evento
    FROM public.fiscal_documento_evento
   WHERE nfe_id = p_nfe_id
     AND tipo_evento = '110111'
     AND sequencia = 1;

  IF FOUND THEN
    IF v_evento.protocolo_evento IS DISTINCT FROM p_protocolo_evento
       OR v_evento.xml_sha256 IS DISTINCT FROM p_xml_sha256
       OR v_evento.resposta_sha256 IS DISTINCT FROM p_resposta_sha256 THEN
      RAISE EXCEPTION 'Cancelamento já preservado com conteúdo divergente.'
        USING ERRCODE = '23505';
    END IF;
  ELSE
    INSERT INTO public.fiscal_documento_evento(
      empresa_id, nfe_id, chave_acesso, tipo_evento, sequencia,
      status_evento, protocolo_evento, data_evento_original,
      data_evento_civil, data_evento_offset, data_evento_instante_utc,
      xml_evento, resposta_sefaz, xml_sha256, resposta_sha256, origem
    ) VALUES (
      p_empresa_id, p_nfe_id, p_chave_acesso, '110111', 1,
      p_status_evento, p_protocolo_evento, p_data_evento_original,
      p_data_evento_civil, p_data_evento_offset, p_data_evento_instante_utc,
      p_xml_evento, p_resposta_sefaz, p_xml_sha256, p_resposta_sha256, 'SEFAZ'
    );
  END IF;

  UPDATE public.nfe
     SET status = 'CANCELADA',
         updatedat = now(),
         justificativacancelamento = p_justificativa
   WHERE id = p_nfe_id;
END;
$$;

REVOKE ALL ON FUNCTION public.fiscal_registrar_cancelamento_nfe(
