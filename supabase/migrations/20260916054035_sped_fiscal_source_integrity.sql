CREATE TABLE public.fiscal_documento_evento (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL
    REFERENCES public.empresa(id) ON DELETE RESTRICT,
  nfe_id bigint
    REFERENCES public.nfe(id) ON DELETE RESTRICT,
  fiscal_dfe_documento_id bigint
    REFERENCES public.fiscal_dfe_documento(id) ON DELETE RESTRICT,
  chave_acesso text NOT NULL,
  tipo_evento text NOT NULL,
  sequencia integer NOT NULL DEFAULT 1,
  status_evento text,
  protocolo_evento text,
  data_evento_original text,
  data_evento_civil date,
  data_evento_offset text,
  data_evento_instante_utc timestamptz,
  xml_evento text NOT NULL,
  resposta_sefaz text,
  xml_sha256 text NOT NULL,
  resposta_sha256 text,
  origem text NOT NULL DEFAULT 'SEFAZ',
  created_by uuid REFERENCES public.usuario(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_documento_evento_origem_documento_chk
    CHECK (num_nonnulls(nfe_id, fiscal_dfe_documento_id) = 1),
  CONSTRAINT fiscal_documento_evento_chave_chk
    CHECK (chave_acesso ~ '^[0-9]{44}$'),
  CONSTRAINT fiscal_documento_evento_sequencia_chk
    CHECK (sequencia > 0),
  CONSTRAINT fiscal_documento_evento_data_offset_chk
    CHECK (
      data_evento_offset IS NULL
      OR data_evento_offset ~ '^(Z|[+-](0[0-9]|1[0-4]):[0-5][0-9])$'
    ),
  CONSTRAINT fiscal_documento_evento_xml_hash_chk
    CHECK (xml_sha256 ~ '^[a-f0-9]{64}$'),
  CONSTRAINT fiscal_documento_evento_resposta_hash_chk
    CHECK (resposta_sha256 IS NULL OR resposta_sha256 ~ '^[a-f0-9]{64}$'),
  CONSTRAINT fiscal_documento_evento_origem_chk
    CHECK (origem IN ('SEFAZ', 'DISTRIBUICAO_DFE', 'IMPORTACAO_MANUAL'))
);

CREATE UNIQUE INDEX fiscal_documento_evento_nfe_uk
