create table if not exists public.mercadolivre_listing_edit_log (
  id bigint generated by default as identity primary key,
  empresa_id bigint not null references public.empresa(id) on delete cascade,
  product_link_id bigint references public.mercadolivre_product_link(id) on delete set null,
  produto_id bigint references public.produto(id) on delete set null,
  ml_item_id text not null,
  status text not null default 'PROCESSANDO'
    check (status in ('PROCESSANDO', 'SUCESSO', 'PARCIAL', 'ERRO')),
  requested_changes jsonb not null default '{}'::jsonb,
  confirmed_changes jsonb not null default '{}'::jsonb,
  warnings jsonb not null default '[]'::jsonb,
  error text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create index if not exists mercadolivre_listing_edit_log_empresa_created_idx
  on public.mercadolivre_listing_edit_log (empresa_id, created_at desc);

alter table public.mercadolivre_listing_edit_log enable row level security;
