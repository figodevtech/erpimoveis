begin;

alter table public.venda
  add column if not exists separacao_em timestamptz,
  add column if not exists entregue_em timestamptz;

create table if not exists public.order_fulfillment_event (
  id bigint generated by default as identity primary key,
  venda_id bigint not null references public.venda(id) on delete cascade,
  status text not null check (status in ('PAGO', 'SEPARACAO', 'FATURADO', 'ENVIADO', 'ENTREGUE')),
  source text not null default 'SISTEMA' check (source in ('ASAAS', 'ERP', 'SISTEMA')),
  description text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists order_fulfillment_event_venda_idx
  on public.order_fulfillment_event (venda_id, created_at asc);

alter table public.order_fulfillment_event enable row level security;
revoke all on public.order_fulfillment_event from public, anon, authenticated;
grant select on public.order_fulfillment_event to authenticated;
grant all on public.order_fulfillment_event to service_role;

drop policy if exists order_fulfillment_event_own on public.order_fulfillment_event;
create policy order_fulfillment_event_own
  on public.order_fulfillment_event for select to authenticated
  using (
    exists (
      select 1 from public.venda v
      join public.cliente c on c.id = v.clienteid
      where v.id = order_fulfillment_event.venda_id and c.user_id = auth.uid()
    )
  );

create or replace function public.fn_prepare_order_fulfillment()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'PAGO' and old.status is distinct from 'PAGO' and new.status_entrega is null then
    new.status_entrega := 'SEPARACAO';
  end if;
  if new.status_entrega is distinct from old.status_entrega then
    if new.status_entrega = 'SEPARACAO' then
      new.separacao_em := coalesce(new.separacao_em, now());
    elsif new.status_entrega = 'FATURADO' then
      new.faturado_em := coalesce(new.faturado_em, now());
    elsif new.status_entrega = 'ENVIADO' then
      new.enviado_em := coalesce(new.enviado_em, now());
    elsif new.status_entrega = 'ENTREGUE' then
      new.entregue_em := coalesce(new.entregue_em, now());
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_prepare_order_fulfillment on public.venda;
create trigger trg_prepare_order_fulfillment
before update of status, status_entrega on public.venda
for each row execute function public.fn_prepare_order_fulfillment();

create or replace function public.fn_record_order_fulfillment_event()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'PAGO' and old.status is distinct from 'PAGO' then
    insert into public.order_fulfillment_event (venda_id, status, source, description)
    values (new.id, 'PAGO', 'ASAAS', 'Pagamento confirmado pelo Asaas.');
  end if;
  if new.status_entrega is distinct from old.status_entrega and new.status_entrega is not null then
    insert into public.order_fulfillment_event (venda_id, status, source, description, metadata)
    values (
      new.id, new.status_entrega, 'ERP',
      case new.status_entrega
        when 'SEPARACAO' then 'Pedido enviado para separação.'
        when 'FATURADO' then 'Nota fiscal emitida no ERP.'
        when 'ENVIADO' then 'Pedido enviado para a transportadora.'
        when 'ENTREGUE' then 'Entrega confirmada pelo ERP.'
      end,
      jsonb_strip_nulls(jsonb_build_object(
        'trackingCode', new.codigo_rastreio,
        'carrier', new.transportadora,
        'invoiceNumber', new.nfe_numero,
        'invoiceAccessKey', new.nfe_chave_acesso
      ))
    );
  end if;
  return new;
end;
$$;

drop trigger if exists trg_record_order_fulfillment_event on public.venda;
create trigger trg_record_order_fulfillment_event
after update of status, status_entrega on public.venda
for each row execute function public.fn_record_order_fulfillment_event();

update public.venda
set status_entrega = 'SEPARACAO', separacao_em = coalesce(separacao_em, updatedat, datavenda, createdat, now())
where status = 'PAGO' and canal = 'ONLINE' and status_entrega is null;

insert into public.order_fulfillment_event (venda_id, status, source, description, created_at)
select v.id, 'PAGO', 'ASAAS', 'Pagamento confirmado pelo Asaas.', coalesce(v.updatedat, v.datavenda, v.createdat, now())
from public.venda v
where v.status = 'PAGO' and v.canal = 'ONLINE'
  and not exists (
    select 1 from public.order_fulfillment_event e where e.venda_id = v.id and e.status = 'PAGO'
  );

commit;
