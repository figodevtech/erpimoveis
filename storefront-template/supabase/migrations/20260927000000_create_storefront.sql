  id integer primary key,
  nome text not null,
  descricao text,
  ativo boolean not null default true,
  createdat timestamptz not null default now(),
  updatedat timestamptz not null default now()
);

create table if not exists public.produto (
  -- O ID e o identificador publico recebido do ERP; nao e uma FK ao banco do ERP.
  id integer primary key,
  titulo text not null,
  "tituloMarketplace" text not null default '',
  "descricaoMarketplace" text not null default '',
  precovenda numeric(14,2) not null default 0 check (precovenda >= 0),
  estoque integer not null default 0 check (estoque >= 0),
  em_estoque boolean generated always as (estoque > 0) stored,
  status_estoque text generated always as (
    case
      when estoque <= 0 then 'ESGOTADO'
      when estoque <= 2 then 'CRITICO'
      when estoque <= 5 then 'BAIXO'
      else 'OK'
    end
  ) stored,
  referencia text,
  fabricante text,
  grupo_produto_id integer references public.produtogrupo(id) on delete set null,
  "imgUrl" text,
  conservacao text check (conservacao is null or conservacao in ('NOVO', 'USADO', 'RECONDICIONADO')),
  destaque boolean not null default false,
  visible boolean not null default true,
  is_deleted boolean not null default false,
  codigobarras text,
  erp_updated_at timestamptz,
  synced_at timestamptz not null default now(),
  createdat timestamptz not null default now(),
  updatedat timestamptz not null default now()
);

