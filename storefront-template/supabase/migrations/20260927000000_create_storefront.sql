create policy cliente_own on public.cliente for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy endereco_own on public.cliente_endereco for all to authenticated
  using (cliente_id in (select id from public.cliente where user_id = auth.uid()))
  with check (cliente_id in (select id from public.cliente where user_id = auth.uid()));

create policy categoria_public_read on public.produtogrupo for select to anon, authenticated
  using (ativo = true);

create policy produto_public_read on public.produto for select to anon, authenticated
  using (visible = true and is_deleted = false);

create policy produto_imagem_public_read on public.produto_imagem for select to anon, authenticated
  using (exists (
    select 1 from public.produto p
    where p.id = produto_id and p.visible = true and p.is_deleted = false
  ));

create policy favorito_own on public.favorito for all to authenticated
  using (cliente_id in (select id from public.cliente where user_id = auth.uid()))
  with check (cliente_id in (select id from public.cliente where user_id = auth.uid()));

create policy venda_own_read on public.venda for select to authenticated
  using (clienteid in (select id from public.cliente where user_id = auth.uid()));

create policy vendaproduto_own_read on public.vendaproduto for select to authenticated
  using (venda_id in (
    select v.id from public.venda v
    join public.cliente c on c.id = v.clienteid
    where c.user_id = auth.uid()
  ));

