create extension if not exists pgcrypto;

create table if not exists public.cliente (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  tipopessoa text not null check (tipopessoa in ('FISICA', 'JURIDICA')),
  cpfcnpj text not null unique,
  nomerazaosocial text not null,
  email text not null unique,
  telefone text not null,
  asaas_customer_id text unique,
  createdat timestamptz not null default now(),
  updatedat timestamptz not null default now()
);

create table if not exists public.cliente_endereco (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.cliente(id) on delete cascade,
  cep text not null,
  logradouro text not null,
  numero text not null,
  complemento text,
  bairro text not null,
  cidade text not null,
  estado text not null,
  principal boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

