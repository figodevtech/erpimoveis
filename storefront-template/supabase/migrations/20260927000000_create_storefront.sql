create or replace function public.fn_criar_pedido_site(
  p_cliente_id bigint,
  p_endereco_snapshot jsonb,
  p_itens jsonb,
  p_subtotal numeric,
  p_total numeric,
  p_canal text default 'ONLINE',
  p_forma_pagamento text default 'Asaas'
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_venda_id bigint;
  v_item jsonb;
begin
  if p_cliente_id is null or not exists (
    select 1 from public.cliente where id = p_cliente_id
  ) then
    raise exception 'Cliente invalido para criacao de pedido.';
  end if;

  if p_itens is null or jsonb_typeof(p_itens) <> 'array' or jsonb_array_length(p_itens) = 0 then
    raise exception 'Pedido deve conter pelo menos um item.';
  end if;

  insert into public.venda (
    clienteid, status, sub_total, valortotal, forma_pagamento,
    endereco_entrega_snapshot, canal
  ) values (
    p_cliente_id, 'PENDENTE', p_subtotal, p_total, p_forma_pagamento,
    p_endereco_snapshot, coalesce(p_canal, 'ONLINE')
  ) returning id into v_venda_id;

  for v_item in select * from jsonb_array_elements(p_itens)
  loop
    if coalesce((v_item->>'quantidade')::integer, 0) <= 0 then
      raise exception 'Quantidade invalida no pedido.';
    end if;

    insert into public.vendaproduto (
      venda_id, produtoid, quantidade, sub_total, valor_total,
      valor_desconto, valor_frete, tipo_desconto
    ) values (
      v_venda_id,
      (v_item->>'produtoid')::integer,
      (v_item->>'quantidade')::integer,
      (v_item->>'sub_total')::numeric,
      (v_item->>'valor_total')::numeric,
      coalesce((v_item->>'valor_desconto')::numeric, 0),
      0,
      v_item->>'tipo_desconto'
    );
  end loop;

  return v_venda_id;
end;
$$;

create or replace function public.fn_baixar_estoque_venda(p_venda_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item record;
begin
  perform 1 from public.venda
    where id = p_venda_id and estoque_baixado = false
    for update;
  if not found then
    return;
  end if;

  for v_item in
    select produtoid, quantidade from public.vendaproduto where venda_id = p_venda_id
  loop
    update public.produto
      set estoque = estoque - v_item.quantidade, updatedat = now()
      where id = v_item.produtoid and estoque >= v_item.quantidade;
    if not found then
      raise exception 'Estoque insuficiente para o produto %.', v_item.produtoid;
    end if;
  end loop;

  update public.venda set estoque_baixado = true, updatedat = now()
    where id = p_venda_id;
end;
$$;

create or replace function public.fn_estornar_estoque_venda(p_venda_id bigint)
