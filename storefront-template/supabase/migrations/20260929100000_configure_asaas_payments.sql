-- Integração financeira exclusiva com Asaas.
-- Execute no banco Supabase da loja, nunca no banco do ERP.

alter table public.cliente
  add column if not exists asaas_customer_id text;

create unique index if not exists cliente_asaas_customer_id_uidx
  on public.cliente (asaas_customer_id)
  where asaas_customer_id is not null;

alter table public.venda
  add column if not exists payment_provider text not null default 'ASAAS',
  add column if not exists gateway_payment_id text,
  add column if not exists gateway_checkout_url text,
  add column if not exists gateway_status text,
  add column if not exists gateway_due_date date,
  add column if not exists commission_percent numeric(7,4) not null default 0
    check (commission_percent >= 0 and commission_percent < 100);

create unique index if not exists venda_gateway_payment_id_uidx
  on public.venda (gateway_payment_id)
  where gateway_payment_id is not null;

create table if not exists public.payment_webhook_event (
  id bigint generated by default as identity primary key,
  provider text not null,
  event_id text not null,
  event_type text not null,
  payment_id text not null,
  venda_id bigint references public.venda(id),
  gateway_status text not null,
  resulting_order_status text,
  processed_at timestamptz not null default now(),
  unique (provider, event_id)
);

create index if not exists payment_webhook_event_venda_idx
  on public.payment_webhook_event (venda_id, processed_at desc);

alter table public.payment_webhook_event enable row level security;
revoke all on public.payment_webhook_event from public, anon, authenticated;

create or replace function public.fn_processar_evento_pagamento_asaas(
  p_event_id text,
  p_event_type text,
  p_payment_id text,
  p_venda_id bigint,
  p_gateway_status text,
  p_novo_status text,
  p_forma_pagamento text
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_venda public.venda%rowtype;
  v_item record;
  v_inserted_event_id bigint;
  v_resulting_status text;
begin
  if nullif(trim(p_event_id), '') is null
    or nullif(trim(p_payment_id), '') is null
    or p_venda_id is null then
    raise exception 'Evento Asaas incompleto.';
  end if;

  if p_novo_status not in ('PENDENTE', 'PAGO', 'CANCELADO') then
    raise exception 'Status local invalido: %.', p_novo_status;
  end if;

  insert into public.payment_webhook_event (
    provider, event_id, event_type, payment_id, venda_id, gateway_status
  ) values (
    'ASAAS', p_event_id, p_event_type, p_payment_id, p_venda_id, p_gateway_status
  )
  on conflict (provider, event_id) do nothing
  returning id into v_inserted_event_id;

  if v_inserted_event_id is null then
    return 'DUPLICADO';
  end if;

  select * into v_venda
  from public.venda
  where id = p_venda_id
    and payment_provider = 'ASAAS'
    and gateway_payment_id = p_payment_id
  for update;

  if not found then
    raise exception 'Venda % nao encontrada ou cobranca Asaas divergente.', p_venda_id;
  end if;

  if p_novo_status = 'PAGO' and v_venda.status <> 'PAGO' then
    if not v_venda.estoque_baixado then
      for v_item in
        select produtoid, quantidade
        from public.vendaproduto
        where venda_id = p_venda_id
        order by produtoid
      loop
        update public.produto
        set estoque = estoque - v_item.quantidade,
            updatedat = now()
        where id = v_item.produtoid
          and estoque >= v_item.quantidade;

        if not found then
          raise exception 'Estoque insuficiente para o produto %.', v_item.produtoid;
        end if;
      end loop;
    end if;

    update public.venda
    set status = 'PAGO',
        estoque_baixado = true,
        forma_pagamento = coalesce(nullif(p_forma_pagamento, ''), forma_pagamento),
        gateway_status = p_gateway_status,
        updatedat = now()
    where id = p_venda_id;

  elsif p_novo_status = 'CANCELADO' then
    if v_venda.estoque_baixado then
      for v_item in
        select produtoid, quantidade
        from public.vendaproduto
        where venda_id = p_venda_id
        order by produtoid
      loop
        update public.produto
        set estoque = estoque + v_item.quantidade,
            updatedat = now()
        where id = v_item.produtoid;
      end loop;
    end if;

    update public.venda
    set status = 'CANCELADO',
        estoque_baixado = false,
        gateway_status = p_gateway_status,
        updatedat = now()
    where id = p_venda_id;

  else
    update public.venda
    set status = case
          when status in ('PAGO', 'CANCELADO') then status
          else 'PENDENTE'
        end,
        gateway_status = p_gateway_status,
        updatedat = now()
    where id = p_venda_id;
  end if;

  select status into v_resulting_status
  from public.venda
  where id = p_venda_id;

  update public.payment_webhook_event
  set resulting_order_status = v_resulting_status
  where id = v_inserted_event_id;

  return 'PROCESSADO';
end;
$$;

revoke all on function public.fn_processar_evento_pagamento_asaas(
  text, text, text, bigint, text, text, text
) from public, anon, authenticated;

grant execute on function public.fn_processar_evento_pagamento_asaas(
  text, text, text, bigint, text, text, text
) to service_role;
