create table if not exists public.veiculo_compatibilidade (
  id bigint generated by default as identity primary key,
  montadora text not null,
  modelo text not null,
  ano_inicio integer not null,
  ano_fim integer not null,
  motor text,
  versao text,
  combustivel text,
  created_at timestamptz not null default now()
);

create table if not exists public.produto_compatibilidade (
  id bigint generated by default as identity primary key,
  produto_id integer not null references public.produto(id) on delete cascade,
  compatibilidade_id bigint not null references public.veiculo_compatibilidade(id) on delete cascade,
  observacao text,
  created_at timestamptz not null default now(),
  unique (produto_id, compatibilidade_id)
);

create index if not exists veiculo_comp_busca_idx
  on public.veiculo_compatibilidade (montadora, modelo, ano_inicio, ano_fim);


alter table public.veiculo_compatibilidade enable row level security;
alter table public.produto_compatibilidade enable row level security;
revoke all on public.veiculo_compatibilidade, public.produto_compatibilidade from public, anon, authenticated;
grant all on public.veiculo_compatibilidade, public.produto_compatibilidade to service_role;
grant usage, select on sequence public.veiculo_compatibilidade_id_seq, public.produto_compatibilidade_id_seq to service_role;
